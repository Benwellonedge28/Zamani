//! # Zamani Backend Reproducibility
//!
//! Path: `src/backend/reproducibility.rs`
//! Edition: Rust 2021.
//! Minimum Rust version: 1.97.
//! Safety: Safe Rust only.
//!
//! ## Purpose
//!
//! Define deterministic, content-addressed identities for compilation inputs
//! and outputs. Supply the existing backend cache with complete, stable keys.
//!
//! ## Ownership
//!
//! This module owns:
//! - Domain-separated canonical fingerprint construction.
//! - Strongly typed fingerprints for relevant compilation inputs.
//! - Immutable compilation identity and build identity calculation.
//! - Adaptation of a compilation identity to `backend::cache::CacheKey`.
//!
//! This module does not own:
//! - Source-language semantics, grammar, parsing, or semantic analysis.
//! - Construction or verification of classical, quantum, HDL, or other IRs.
//! - Dependency discovery or incremental compilation planning.
//! - Target selection, capability negotiation, or resource allocation.
//! - Artifact serialization, persistence, signing, or verification.
//! - External tool execution or environment discovery.
//!
//! ## Reproducibility contract
//!
//! Identical canonical inputs produce identical fingerprints. Field names,
//! domain separators, field lengths, field order, optional-value presence,
//! and sequence order are included in the digest contract.
//!
//! A caller must include every input that can affect the compilation result.
//! This module cannot infer omitted inputs or guarantee that an external
//! compiler is deterministic.
//!
//! Fingerprints are identifiers, not signatures, authorization tokens, proof
//! of correctness, or proof that an artifact is safe to execute.
//!
//! ## Integration
//!
//! - `cache.rs` owns cache storage and `CacheKey`.
//! - `artifact.rs` owns artifact payloads and their content digests.
//! - `manifest.rs` owns artifact manifests and serialized provenance.
//! - `compiler/incremental.rs` owns dependency invalidation and build planning.
//! - The compilation pipeline owns the authoritative set of inputs to hash.
//!
//! This module has no dependency on grammar internals, target emitters, or IR
//! implementation types. A future domain can participate by supplying stable
//! fingerprints through the same contracts.
//!
//! ## Resource model
//!
//! No hardware-capacity or universal input-size limit is imposed here.
//! Fingerprinting consumes CPU time and memory proportional to the data
//! supplied. Operational budgets belong to the compilation pipeline.

use std::fmt;

use sha2::{Digest, Sha256};

use super::cache::{CacheKey, CacheKeyError, CacheKeyParts};

/// Number of bytes in a SHA-256 fingerprint.
pub const FINGERPRINT_LEN: usize = 32;

/// Canonical encoding contract version.
///
/// Change this value when changing the fingerprint framing rules in a way
/// that should invalidate identities generated by the previous contract.
pub const FINGERPRINT_SCHEMA: &str = "zamani-fingerprint-v1";

const HASH_DOMAIN: &[u8] = b"zamani.reproducibility.fingerprint.v1";

/// A canonical builder for domain-separated SHA-256 fingerprints.
///
/// Fields are hashed in the order supplied. Each field includes its label
/// and length, so different field boundaries cannot produce the same encoded
/// input merely by concatenating different values.
///
/// Callers representing unordered collections must canonicalize their order
/// before adding fields. This type deliberately does not guess whether an
/// input collection is ordered or unordered.
pub struct FingerprintBuilder {
    hasher: Sha256,
    field_count: u128,
}

impl FingerprintBuilder {
    /// Create a builder for a named fingerprint domain.
    ///
    /// The domain must be a stable, nonempty identifier chosen by the
    /// implementation, not a timestamp or machine-local value.
    pub fn new(domain: &str) -> Self {
        let mut builder = Self {
            hasher: Sha256::new(),
            field_count: 0,
        };

        builder.hasher.update(HASH_DOMAIN);
        builder.write_frame(domain.as_bytes());
        builder.write_frame(FINGERPRINT_SCHEMA.as_bytes());
        builder
    }

    /// Add a required byte field.
    ///
    /// Repeated labels are allowed and preserve insertion order.
    pub fn field(&mut self, label: &str, value: &[u8]) -> &mut Self {
        self.write_frame(label.as_bytes());
        self.write_frame(value);
        self.field_count = self.field_count.saturating_add(1);
        self
    }

    /// Add a required UTF-8 string field without normalization.
    ///
    /// Unicode normalization, path normalization, case folding, or other
    /// canonicalization must be an explicit upstream contract where needed.
    pub fn string(&mut self, label: &str, value: &str) -> &mut Self {
        self.field(label, value.as_bytes())
    }

    /// Add an explicitly present or absent optional byte field.
    ///
    /// `None` and `Some(&[])` have different encodings.
    pub fn optional_field(
        &mut self,
        label: &str,
        value: Option<&[u8]>,
    ) -> &mut Self {
        self.write_frame(label.as_bytes());

        match value {
            None => {
                self.hasher.update([0_u8]);
                self.write_frame(&[]);
            }
            Some(bytes) => {
                self.hasher.update([1_u8]);
                self.write_frame(bytes);
            }
        }

        self.field_count = self.field_count.saturating_add(1);
        self
    }

    /// Add an explicitly present or absent optional string field.
    pub fn optional_string(
        &mut self,
        label: &str,
        value: Option<&str>,
    ) -> &mut Self {
        self.optional_field(label, value.map(str::as_bytes))
    }

    /// Add an ordered sequence of byte values.
    ///
    /// Sequence length and each element's boundaries are included. Reordering
    /// elements therefore changes the fingerprint.
    pub fn ordered_bytes<'a>(
        &mut self,
        label: &str,
        values: impl IntoIterator<Item = &'a [u8]>,
    ) -> &mut Self {
        let values: Vec<&[u8]> = values.into_iter().collect();

        self.write_frame(label.as_bytes());
        self.write_frame(&(values.len() as u128).to_be_bytes());

        for value in values {
            self.write_frame(value);
        }

        self.field_count = self.field_count.saturating_add(1);
        self
    }

    /// Finish the builder and return the raw SHA-256 digest.
    ///
    /// The field count is included in the final encoding.
    #[must_use]
    pub fn finish_digest(mut self) -> [u8; FINGERPRINT_LEN] {
        self.hasher.update(self.field_count.to_be_bytes());
        self.hasher.finalize().into()
    }

    fn write_frame(&mut self, bytes: &[u8]) {
        // u128 framing is independent of pointer width and avoids truncating
        // the length to u32 or u64. Rust slices cannot exceed usize::MAX.
        self.hasher
            .update((bytes.len() as u128).to_be_bytes());
        self.hasher.update(bytes);
    }
}

macro_rules! define_fingerprint {
    ($name:ident, $domain:literal, $description:literal) => {
        #[doc = $description]
        #[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        pub struct $name([u8; FINGERPRINT_LEN]);

        impl $name {
            /// Hash bytes in this fingerprint's domain.
            #[must_use]
            pub fn of_bytes(bytes: &[u8]) -> Self {
                let mut builder = FingerprintBuilder::new($domain);
                builder.field("content", bytes);
                Self(builder.finish_digest())
            }

            /// Construct this type from a digest produced by a compatible
            /// fingerprint builder.
            ///
            /// This is intended for adapting a previously calculated digest.
            /// It does not verify how that digest was produced.
            #[must_use]
            pub const fn from_digest(digest: [u8; FINGERPRINT_LEN]) -> Self {
                Self(digest)
            }

            /// Return the raw digest bytes.
            #[must_use]
            pub const fn as_bytes(&self) -> &[u8; FINGERPRINT_LEN] {
                &self.0
            }

            /// Return the canonical lowercase hexadecimal digest, prefixed
            /// with `sha256:`.
            #[must_use]
            pub fn to_hex(self) -> String {
                format!("sha256:{}", hex::encode(self.0))
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(formatter, "sha256:{}", hex::encode(self.0))
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter
                    .debug_tuple(stringify!($name))
                    .field(&self.to_hex())
                    .finish()
            }
        }
    };
}

