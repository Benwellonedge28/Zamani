/// An invalid or incomplete reproducibility identity.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReproducibilityError {
    /// A required identity field was empty.
    EmptyField(&'static str),
}

impl fmt::Display for ReproducibilityError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyField(field) => {
                write!(
                    formatter,
                    "reproducibility identity field `{field}` must not be empty"
                )
            }
        }
    }
}

impl std::error::Error for ReproducibilityError {}

/// Borrowed inputs for constructing an immutable compilation identity.
///
/// All fingerprints must have been generated using deterministic,
/// documented upstream contracts. The strings are canonical identifiers,
/// not display labels or local file paths.
#[derive(Debug, Clone, Copy)]
pub struct CompilationIdentityParts<'a> {
    /// Version of the identity contract used by the caller.
    pub schema_version: &'a str,

    /// Fingerprint of the verified input to this compilation stage.
    ///
    /// This should cover the appropriate source, IR, semantic schema, and
    /// upstream transformations for the particular stage being cached.
    pub input_fingerprint: InputFingerprint,

    /// Fingerprint of the compiler implementation and relevant version data.
    pub compiler_fingerprint: CompilerFingerprint,

    /// Stable backend implementation identifier, including its version when
    /// versions can affect generated output.
    pub backend_id: &'a str,

    /// Complete target identity, including relevant ABI and target profile.
    pub target_id: &'a str,

    /// Fingerprint of all artifact-affecting configuration.
    pub config_fingerprint: ConfigurationFingerprint,

    /// External toolchain identity, when a toolchain affects the result.
    ///
    /// `None` is distinct from a present fingerprint. Callers must not use
    /// `None` merely because toolchain identity was not collected.
    pub toolchain_fingerprint: Option<ToolchainFingerprint>,

    /// Fingerprint of all relevant dependencies and their versions.
    pub dependency_fingerprint: DependencyFingerprint,

    /// Stable artifact format or stage-output kind.
    pub artifact_kind: &'a str,
}

/// Immutable, validated identity for one backend compilation result.
///
/// All fields are private to prevent callers from mutating the identity after
/// validation. Construct a new identity whenever an artifact-affecting input
/// changes.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CompilationIdentity {
    schema_version: String,
    input_fingerprint: InputFingerprint,
    compiler_fingerprint: CompilerFingerprint,
    backend_id: String,
    target_id: String,
    config_fingerprint: ConfigurationFingerprint,
    toolchain_fingerprint: Option<ToolchainFingerprint>,
    dependency_fingerprint: DependencyFingerprint,
    artifact_kind: String,
}

impl CompilationIdentity {
    /// Validate and construct a compilation identity.
    pub fn new(
        parts: CompilationIdentityParts<'_>,
    ) -> Result<Self, ReproducibilityError> {
        for (name, value) in [
            ("schema_version", parts.schema_version),
            ("backend_id", parts.backend_id),
            ("target_id", parts.target_id),
            ("artifact_kind", parts.artifact_kind),
        ] {
            if value.trim().is_empty() {
                return Err(ReproducibilityError::EmptyField(name));
            }
        }

        Ok(Self {
            schema_version: parts.schema_version.to_owned(),
            input_fingerprint: parts.input_fingerprint,
            compiler_fingerprint: parts.compiler_fingerprint,
            backend_id: parts.backend_id.to_owned(),
            target_id: parts.target_id.to_owned(),
            config_fingerprint: parts.config_fingerprint,
            toolchain_fingerprint: parts.toolchain_fingerprint,
            dependency_fingerprint: parts.dependency_fingerprint,
            artifact_kind: parts.artifact_kind.to_owned(),
        })
    }

    /// Calculate the stable fingerprint of this complete declared identity.
    #[must_use]
    pub fn fingerprint(&self) -> BuildFingerprint {
        let mut builder = FingerprintBuilder::new("zamani.build-identity");

        builder
            .string("identity-schema", &self.schema_version)
            .field(
                "input-fingerprint",
                self.input_fingerprint.as_bytes(),
            )
            .field(
                "compiler-fingerprint",
                self.compiler_fingerprint.as_bytes(),
            )
            .string("backend-id", &self.backend_id)
            .string("target-id", &self.target_id)
            .field(
                "configuration-fingerprint",
                self.config_fingerprint.as_bytes(),
            )
            .optional_field(
                "toolchain-fingerprint",
                self.toolchain_fingerprint
                    .as_ref()
                    .map(ToolchainFingerprint::as_bytes)
                    .map(|bytes| bytes.as_slice()),
            )
            .field(
                "dependency-fingerprint",
                self.dependency_fingerprint.as_bytes(),
            )
            .string("artifact-kind", &self.artifact_kind);

        BuildFingerprint::from_digest(builder.finish_digest())
    }

    /// Build the canonical cache key using the existing backend cache API.
    ///
    /// This method deliberately reuses `CacheKey::from_parts` rather than
    /// introducing a second cache-key implementation. A caller must still
    /// validate a cache hit's artifact format and target before use.
    pub fn cache_key(&self) -> Result<CacheKey, CacheKeyError> {
        let input_fingerprint = self.input_fingerprint.to_hex();
        let compiler_fingerprint = self.compiler_fingerprint.to_hex();
        let config_fingerprint = self.config_fingerprint.to_hex();
        let dependency_fingerprint = self.dependency_fingerprint.to_hex();

        let toolchain_fingerprint = self
            .toolchain_fingerprint
            .map(ToolchainFingerprint::to_hex);

        CacheKey::from_parts(CacheKeyParts {
            schema_version: &self.schema_version,
            input_fingerprint: &input_fingerprint,
            compiler_fingerprint: &compiler_fingerprint,
            backend_id: &self.backend_id,
            target_id: &self.target_id,
            config_fingerprint: &config_fingerprint,
            toolchain_fingerprint: toolchain_fingerprint.as_deref(),
            dependency_fingerprint: &dependency_fingerprint,
            artifact_kind: &self.artifact_kind,
        })
    }

    /// Return the declared backend identifier.
    #[must_use]
    pub fn backend_id(&self) -> &str {
        &self.backend_id
    }

    /// Return the declared target identifier.
    #[must_use]
    pub fn target_id(&self) -> &str {
        &self.target_id
    }

    /// Return the declared artifact kind.
    #[must_use]
    pub fn artifact_kind(&self) -> &str {
        &self.artifact_kind
    }

    /// Return the declared input fingerprint.
    #[must_use]
    pub const fn input_fingerprint(&self) -> InputFingerprint {
        self.input_fingerprint
    }

    /// Return the declared configuration fingerprint.
    #[must_use]
    pub const fn config_fingerprint(&self) -> ConfigurationFingerprint {
        self.config_fingerprint
    }

    /// Return the declared dependency fingerprint.
    #[must_use]
    pub const fn dependency_fingerprint(&self) -> DependencyFingerprint {
        self.dependency_fingerprint
    }

    /// Return the optional toolchain fingerprint.
    #[must_use]
    pub const fn toolchain_fingerprint(&self) -> Option<ToolchainFingerprint> {
        self.toolchain_fingerprint
    }
}

/// Fingerprint a sequence whose order is semantically significant.
///
/// For example, this is suitable for an ordered transformation pipeline.
#[must_use]
pub fn fingerprint_ordered_items<'a>(
    domain: &str,
    items: impl IntoIterator<Item = &'a [u8]>,
) -> [u8; FINGERPRINT_LEN] {
    let mut builder = FingerprintBuilder::new(domain);
    builder.ordered_bytes("items", items);
    builder.finish_digest()
}

/// Fingerprint a collection whose order is explicitly declared irrelevant.
///
/// Values are sorted lexicographically by bytes before hashing. Duplicate
/// values are preserved: callers should deduplicate first only when their
/// dependency contract defines dependencies as a set.
#[must_use]
pub fn fingerprint_unordered_items<'a>(
    domain: &str,
    items: impl IntoIterator<Item = &'a [u8]>,
) -> [u8; FINGERPRINT_LEN] {
    let mut canonical: Vec<&[u8]> = items.into_iter().collect();
    canonical.sort_unstable();

    let mut builder = FingerprintBuilder::new(domain);
    builder.ordered_bytes("canonical-items", canonical);
    builder.finish_digest()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn identity(
        target_id: &str,
        toolchain: Option<ToolchainFingerprint>,
    ) -> CompilationIdentity {
        CompilationIdentity::new(CompilationIdentityParts {
            schema_version: "backend-build-v1",
            input_fingerprint: InputFingerprint::of_bytes(b"verified-ir"),
            compiler_fingerprint: CompilerFingerprint::of_bytes(b"compiler-v1"),
            backend_id: "llvm",
            target_id,
            config_fingerprint: ConfigurationFingerprint::of_bytes(b"opt-level=2"),
            toolchain_fingerprint: toolchain,
            dependency_fingerprint: DependencyFingerprint::of_bytes(b"no-dependencies"),
            artifact_kind: "llvm-ir",
        })
        .expect("test identity is valid")
    }

    #[test]
    fn identical_identity_produces_identical_fingerprints_and_cache_keys() {
        let first = identity("x86_64-unknown-linux-gnu", None);
        let second = identity("x86_64-unknown-linux-gnu", None);

        assert_eq!(first.fingerprint(), second.fingerprint());
        assert_eq!(first.cache_key().unwrap(), second.cache_key().unwrap());
    }

    #[test]
    fn changing_target_changes_identity() {
        let first = identity("x86_64-unknown-linux-gnu", None);
        let second = identity("aarch64-unknown-linux-gnu", None);

        assert_ne!(first.fingerprint(), second.fingerprint());
        assert_ne!(first.cache_key().unwrap(), second.cache_key().unwrap());
    }

    #[test]
    fn absent_and_present_toolchain_are_distinct() {
        let absent = identity("target", None);
        let present = identity(
            "target",
            Some(ToolchainFingerprint::of_bytes(b"toolchain-v1")),
        );

        assert_ne!(absent.fingerprint(), present.fingerprint());
        assert_ne!(absent.cache_key().unwrap(), present.cache_key().unwrap());
    }

    #[test]
    fn field_boundaries_are_unambiguous() {
        let mut first = FingerprintBuilder::new("test");
        first.string("a", "ab").string("b", "c");

        let mut second = FingerprintBuilder::new("test");
        second.string("a", "a").string("b", "bc");

        assert_ne!(first.finish_digest(), second.finish_digest());
    }

    #[test]
    fn optional_absence_differs_from_present_empty_value() {
        let mut absent = FingerprintBuilder::new("test");
        absent.optional_field("value", None);

        let mut present_empty = FingerprintBuilder::new("test");
        present_empty.optional_field("value", Some(&[]));

        assert_ne!(
            absent.finish_digest(),
            present_empty.finish_digest()
        );
    }

    #[test]
    fn ordered_sequences_preserve_order() {
        let first = fingerprint_ordered_items(
            "test.sequence",
            [b"alpha".as_slice(), b"beta".as_slice()],
        );
        let second = fingerprint_ordered_items(
            "test.sequence",
            [b"beta".as_slice(), b"alpha".as_slice()],
        );

        assert_ne!(first, second);
    }

    #[test]
    fn unordered_sequences_ignore_input_order() {
        let first = fingerprint_unordered_items(
            "test.dependencies",
            [b"alpha".as_slice(), b"beta".as_slice()],
        );
        let second = fingerprint_unordered_items(
            "test.dependencies",
            [b"beta".as_slice(), b"alpha".as_slice()],
        );

        assert_eq!(first, second);
    }

    #[test]
    fn empty_required_identity_fields_are_rejected() {
        let result = CompilationIdentity::new(CompilationIdentityParts {
            schema_version: "backend-build-v1",
            input_fingerprint: InputFingerprint::of_bytes(b"input"),
            compiler_fingerprint: CompilerFingerprint::of_bytes(b"compiler"),
            backend_id: "llvm",
            target_id: "target",
            config_fingerprint: ConfigurationFingerprint::of_bytes(b"config"),
            toolchain_fingerprint: None,
            dependency_fingerprint: DependencyFingerprint::of_bytes(b"deps"),
            artifact_kind: " ",
        });

        assert_eq!(
            result,
            Err(ReproducibilityError::EmptyField("artifact_kind"))
        );
    }

    #[test]
    fn artifact_bytes_have_a_stable_fingerprint() {
        let first = ArtifactFingerprint::of_bytes(b"artifact bytes");
        let second = ArtifactFingerprint::of_bytes(b"artifact bytes");
        let different = ArtifactFingerprint::of_bytes(b"changed artifact bytes");

        assert_eq!(first, second);
        assert_ne!(first, different);
    }
}
