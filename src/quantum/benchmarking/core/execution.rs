/// Generic raw execution observation.
///
/// The execution layer intentionally preserves multiple quantum-computing
/// observation models instead of forcing everything into bitstrings.
#[derive(Debug, Clone, PartialEq)]
pub enum ExecutionObservation {
    /// Classical measurement counts.
    Counts(BTreeMap<String, usize>),

    /// Classical probability distribution.
    Probabilities(BTreeMap<String, f64>),

    /// Expectation values keyed by observable identifier.
    ExpectationValues(BTreeMap<String, f64>),

    /// State-vector amplitudes represented as real/imaginary pairs.
    StateVector(Vec<(f64, f64)>),

    /// Density-matrix entries represented as row-major real/imaginary pairs.
    DensityMatrix(Vec<(f64, f64)>),

    /// Raw analog values.
    AnalogSamples(Vec<f64>),

    /// Annealing/sampling observations.
    AnnealingSamples(Vec<AnnealingSample>),

    /// Quantum-error-correction syndrome observations.
    Syndrome(SyndromeObservation),

    /// Provider-native observation.
    BackendNative {
        format: String,
        payload: Vec<u8>,
    },
}

impl ExecutionObservation {
    /// Returns the observation kind.
    pub fn kind(&self) -> ObservationKind {
        match self {
            Self::Counts(_) => ObservationKind::Counts,
            Self::Probabilities(_) => ObservationKind::Probabilities,
            Self::ExpectationValues(_) => ObservationKind::ExpectationValues,
            Self::StateVector(_) => ObservationKind::StateVector,
            Self::DensityMatrix(_) => ObservationKind::DensityMatrix,
            Self::AnalogSamples(_) => ObservationKind::AnalogSamples,
            Self::AnnealingSamples(_) => ObservationKind::AnnealingSamples,
            Self::Syndrome(_) => ObservationKind::Syndrome,
            Self::BackendNative { .. } => ObservationKind::BackendNative,
        }
    }
}

/// Stable observation classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ObservationKind {
    Counts,
    Probabilities,
    ExpectationValues,
    StateVector,
    DensityMatrix,
    AnalogSamples,
    AnnealingSamples,
    Syndrome,
    BackendNative,
}

/// One annealing/sample observation.
#[derive(Debug, Clone, PartialEq)]
pub struct AnnealingSample {
    /// Returned state representation.
    pub state: String,

    /// Optional objective/energy value.
    pub energy: Option<f64>,

    /// Optional backend-provided occurrence count.
    pub occurrences: Option<usize>,
}

/// Raw QEC syndrome observation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyndromeObservation {
    /// Syndrome samples.
    pub samples: Vec<String>,

    /// Number of rounds represented by each sample, when known.
    pub rounds: Option<usize>,
}

