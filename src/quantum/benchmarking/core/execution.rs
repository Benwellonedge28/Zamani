/// Type of quantum execution target.
///
/// The benchmarking framework must not assume that every target is a physical
/// QPU. This enum allows the same execution contract to cover the major
/// execution classes used by Zamani.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum ExecutionMode {
    /// Exact or approximate state-vector simulation.
    StateVectorSimulator,

    /// Density-matrix simulation.
    DensityMatrixSimulator,

    /// Stabilizer-oriented simulation.
    StabilizerSimulator,

    /// Tensor-network simulation.
    TensorNetworkSimulator,

    /// Hardware-emulating simulator.
    Emulator,

    /// Physical gate-model quantum processor.
    Qpu,

    /// Analog quantum execution.
    Analog,

    /// Quantum annealing execution.
    Annealing,

    /// Sampling-oriented execution.
    Sampler,

    /// Logical/fault-tolerant quantum execution.
    LogicalQpu,

    /// Repository/application-specific execution provider.
    Custom,
}

impl ExecutionMode {
    /// Returns whether this mode is expected to execute on physical quantum
    /// hardware.
    pub fn is_physical(self) -> bool {
        matches!(
            self,
            Self::Qpu | Self::Analog | Self::Annealing | Self::LogicalQpu
        )
    }

    /// Returns whether this mode is a simulator.
    pub fn is_simulator(self) -> bool {
        matches!(
            self,
            Self::StateVectorSimulator
                | Self::DensityMatrixSimulator
                | Self::StabilizerSimulator
                | Self::TensorNetworkSimulator
        )
    }

    /// Returns whether this mode is expected to return sampled observations.
    pub fn is_sampling_oriented(self) -> bool {
        matches!(
            self,
            Self::Sampler
                | Self::Qpu
                | Self::LogicalQpu
                | Self::Annealing
        )
    }
}

