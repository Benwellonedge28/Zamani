/// Validates a probability distribution.
///
/// The function deliberately does not require the probabilities to sum exactly
/// to one because floating-point serialization and backend rounding can make
/// exact equality inappropriate. The tolerance is explicit.
pub fn validate_probability_distribution(
    distribution: &BTreeMap<String, f64>,
) -> Result<(), ExecutionError> {
    if distribution.is_empty() {
        return Err(ExecutionError::MalformedResponse {
            message: "probability distribution is empty".to_owned(),
        });
    }

    let mut sum = 0.0f64;

    for probability in distribution.values() {
        if !probability.is_finite()
            || *probability < 0.0
            || *probability > 1.0
        {
            return Err(ExecutionError::InvalidProbability {
                value: *probability,
            });
        }

        sum += *probability;
    }

    const NORMALIZATION_TOLERANCE: f64 = 1.0e-9;

    if (sum - 1.0).abs() > NORMALIZATION_TOLERANCE {
        return Err(ExecutionError::MalformedResponse {
            message: format!(
                "probability distribution is not normalized: sum={}",
                sum
            ),
        });
    }

    Ok(())
}

/// Validates a count distribution and returns the total number of observations.
pub fn validate_count_distribution(
    distribution: &BTreeMap<String, usize>,
) -> Result<usize, ExecutionError> {
    if distribution.is_empty() {
        return Err(ExecutionError::MalformedResponse {
            message: "count distribution is empty".to_owned(),
        });
    }

    distribution.values().try_fold(0usize, |acc, count| {
        acc.checked_add(*count)
            .ok_or(ExecutionError::InvalidObservationCount)
    })
}

