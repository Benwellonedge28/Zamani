/// Number of repetitions requested from a backend.
///
/// This is kept separate from `ExecutionRequest` so that batching and future
/// adaptive execution can reuse the same validated type.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ShotCount(usize);

impl ShotCount {
    /// Creates a validated shot count.
    pub fn new(value: usize) -> Result<Self, ExecutionError> {
        if value == 0 {
            return Err(ExecutionError::InvalidShotCount);
        }

        Ok(Self(value))
    }

    /// Returns the number of shots.
    pub fn get(self) -> usize {
        self.0
    }
}

impl Default for ShotCount {
    fn default() -> Self {
        Self(DEFAULT_SHOTS)
    }
}

