/// Raw execution response returned by a backend executor.
///
/// This is intentionally not a benchmark result. No fidelity, error rate,
/// Quantum Volume, XEB score, or other benchmark metric belongs here.
#[derive(Debug, Clone, PartialEq)]
pub struct ExecutionResponse {
    /// Execution-contract schema version.
    pub schema_version: u32,

    /// Request that produced this response.
    pub request_id: ExecutionRequestId,

    /// Backend that produced this response.
    pub backend_id: ExecutionBackendId,

    /// Backend execution mode.
    pub execution_mode: ExecutionMode,

    /// Terminal execution status.
    pub status: ExecutionStatus,

    /// Number of shots requested.
    pub requested_shots: usize,

    /// Number of shots actually completed.
    pub completed_shots: usize,

    /// Raw observations.
    pub observations: Vec<ExecutionObservation>,

    /// Timing measurements.
    pub timing: ExecutionTiming,

    /// Backend metadata.
    pub backend_metadata: BTreeMap<String, String>,

    /// Provider-neutral response metadata.
    pub metadata: BTreeMap<String, String>,

    /// Structured warnings that do not invalidate the response.
    pub warnings: Vec<String>,
}

impl ExecutionResponse {
    /// Creates a successful response.
    pub fn completed(
        request: &ExecutionRequest,
        observations: Vec<ExecutionObservation>,
        timing: ExecutionTiming,
    ) -> Result<Self, ExecutionError> {
        let completed_shots =
            infer_completed_shots(&observations).unwrap_or(request.shots.get());

        if completed_shots > request.shots.get() {
            return Err(ExecutionError::InvalidCompletedShotCount {
                requested: request.shots.get(),
                completed: completed_shots,
            });
        }

        let status = if completed_shots == request.shots.get() {
            ExecutionStatus::Completed
        } else {
            ExecutionStatus::Partial
        };

        Ok(Self {
            schema_version: EXECUTION_RESPONSE_SCHEMA_VERSION,
            request_id: request.request_id.clone(),
            backend_id: request.backend_id.clone(),
            execution_mode: request.execution_mode,
            status,
            requested_shots: request.shots.get(),
            completed_shots,
            observations,
            timing,
            backend_metadata: BTreeMap::new(),
            metadata: BTreeMap::new(),
            warnings: Vec::new(),
        })
    }

    /// Creates an explicit cancelled response.
    pub fn cancelled(
        request: &ExecutionRequest,
        timing: ExecutionTiming,
    ) -> Self {
        Self {
            schema_version: EXECUTION_RESPONSE_SCHEMA_VERSION,
            request_id: request.request_id.clone(),
            backend_id: request.backend_id.clone(),
            execution_mode: request.execution_mode,
            status: ExecutionStatus::Cancelled,
            requested_shots: request.shots.get(),
            completed_shots: 0,
            observations: Vec::new(),
            timing,
            backend_metadata: BTreeMap::new(),
            metadata: BTreeMap::new(),
            warnings: Vec::new(),
        }
    }

    /// Validates correlation and response invariants.
    pub fn validate_against(
        &self,
        request: &ExecutionRequest,
    ) -> Result<(), ExecutionError> {
        if self.schema_version != EXECUTION_RESPONSE_SCHEMA_VERSION {
            return Err(ExecutionError::UnsupportedSchemaVersion {
                kind: SchemaKind::Response,
                version: self.schema_version,
            });
        }

        if self.request_id != request.request_id {
            return Err(ExecutionError::RequestResponseMismatch {
                expected: request.request_id.clone(),
                actual: self.request_id.clone(),
            });
        }

        if self.backend_id != request.backend_id {
            return Err(ExecutionError::BackendResponseMismatch {
                expected: request.backend_id.clone(),
                actual: self.backend_id.clone(),
            });
        }

        if self.requested_shots != request.shots.get() {
            return Err(ExecutionError::RequestedShotMismatch {
                expected: request.shots.get(),
                actual: self.requested_shots,
            });
        }

        if self.completed_shots > self.requested_shots {
            return Err(ExecutionError::InvalidCompletedShotCount {
                requested: self.requested_shots,
                completed: self.completed_shots,
            });
        }

        Ok(())
    }

    /// Adds a warning without changing execution semantics.
    pub fn with_warning(
        mut self,
        warning: impl Into<String>,
    ) -> Self {
        let warning = warning.into();

        if !warning.trim().is_empty() {
            self.warnings.push(warning);
        }

        self
    }

    /// Adds backend metadata.
    pub fn with_backend_metadata(
        mut self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> Result<Self, ExecutionError> {
        let key = validate_metadata_key(key.into())?;
        let value = validate_metadata_value(value.into())?;

        self.backend_metadata.insert(key, value);

        Ok(self)
    }

    /// Adds response metadata.
    pub fn with_metadata(
        mut self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> Result<Self, ExecutionError> {
        let key = validate_metadata_key(key.into())?;
        let value = validate_metadata_value(value.into())?;

        self.metadata.insert(key, value);

        Ok(self)
    }
}

