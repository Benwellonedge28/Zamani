/// Lightweight timing/cancellation guard for executor implementations.
///
/// It is deliberately independent of an async runtime.
#[derive(Debug)]
pub struct ExecutionGuard {
    started: Instant,
    timeout: Duration,
    cancellation: CancellationToken,
}

impl ExecutionGuard {
    /// Starts an execution guard.
    pub fn start(
        timeout: ExecutionTimeout,
        cancellation: CancellationToken,
    ) -> Self {
        Self {
            started: Instant::now(),
            timeout: timeout.duration(),
            cancellation,
        }
    }

    /// Returns elapsed execution time.
    pub fn elapsed(&self) -> Duration {
        self.started.elapsed()
    }

    /// Checks cancellation and timeout.
    pub fn check(&self) -> Result<(), ExecutionError> {
        if self.cancellation.is_cancelled() {
            return Err(ExecutionError::Cancelled);
        }

        let elapsed = self.elapsed();

        if elapsed >= self.timeout {
            return Err(ExecutionError::TimedOut {
                timeout: self.timeout,
                elapsed,
            });
        }

        Ok(())
    }

    /// Returns whether the timeout has elapsed.
    pub fn is_timed_out(&self) -> bool {
        self.elapsed() >= self.timeout
    }
}

