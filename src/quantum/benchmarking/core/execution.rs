/// Stable identifier for one execution request.
///
/// A request ID is an opaque value at this layer. It may be generated by the
/// benchmark engine, scheduler, runtime, or caller.
///
/// IDs are intentionally strings so that distributed providers can preserve
/// provider-native IDs without changing the execution contract.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ExecutionRequestId(String);

impl ExecutionRequestId {
    /// Creates an execution request ID.
    ///
    /// Empty IDs are rejected because they make correlation and provenance
    /// unreliable.
    pub fn new(value: impl Into<String>) -> Result<Self, ExecutionError> {
        let value = value.into();

        if value.trim().is_empty() {
            return Err(ExecutionError::InvalidRequestId);
        }

        Ok(Self(value))
    }

    /// Returns the identifier as a string slice.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consumes the identifier and returns its underlying string.
    pub fn into_string(self) -> String {
        self.0
    }
}

impl fmt::Display for ExecutionRequestId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

