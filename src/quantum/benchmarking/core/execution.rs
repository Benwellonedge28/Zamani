/// Timing information collected by the execution layer.
///
/// These values deliberately remain separate. Benchmark analysis can later
/// decide which timing dimensions matter.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ExecutionTiming {
    /// Time spent waiting before provider execution began.
    pub queue_time: Option<Duration>,

    /// Time spent submitting the request.
    pub submission_time: Option<Duration>,

    /// Time spent in actual provider execution.
    pub execution_time: Option<Duration>,

    /// Time spent retrieving results.
    pub result_collection_time: Option<Duration>,

    /// End-to-end wall-clock time observed by the executor.
    pub total_time: Duration,
}

impl ExecutionTiming {
    /// Creates timing information for a completed local execution.
    pub fn completed(total_time: Duration) -> Self {
        Self {
            queue_time: None,
            submission_time: None,
            execution_time: Some(total_time),
            result_collection_time: None,
            total_time,
        }
    }
}

