/// Stable production execution interface.
///
/// Implementations belong outside this module and may wrap:
///
/// - local simulators;
/// - GPU simulators;
/// - tensor-network engines;
/// - hardware SDKs;
/// - remote services;
/// - annealers;
/// - logical-QPU runtimes;
/// - custom Zamani execution providers.
///
/// The trait intentionally remains synchronous. Async execution can be
/// implemented above or below this boundary without forcing Zamani's quantum
/// benchmark core to select an async runtime.
pub trait BenchmarkExecutor {
    /// Returns executor metadata and capabilities.
    fn metadata(&self) -> &ExecutorMetadata;

    /// Performs provider-neutral request validation.
    ///
    /// Implementations may perform additional provider-specific validation
    /// after this method succeeds.
    fn validate(
        &self,
        request: &ExecutionRequest,
    ) -> Result<(), ExecutionError> {
        request.validate()?;

        if request.backend_id != self.metadata().backend_id {
            return Err(ExecutionError::BackendMismatch {
                expected: self.metadata().backend_id.clone(),
                actual: request.backend_id.clone(),
            });
        }

        if request.execution_mode != self.metadata().execution_mode {
            return Err(ExecutionError::ExecutionModeMismatch {
                expected: self.metadata().execution_mode,
                actual: request.execution_mode,
            });
        }

        Ok(())
    }

    /// Executes one benchmark request.
    ///
    /// Implementations MUST:
    ///
    /// - validate before execution;
    /// - honor cancellation where possible;
    /// - enforce timeout semantics;
    /// - preserve request identity;
    /// - preserve partial results where they are safe and meaningful;
    /// - never silently retry;
    /// - never silently alter shots or seeds;
    /// - return structured errors.
    fn execute(
        &self,
        request: &ExecutionRequest,
    ) -> Result<ExecutionResponse, ExecutionError>;

    /// Requests cancellation of an in-flight provider operation.
    ///
    /// The default implementation is cooperative cancellation only. Provider
    /// adapters with native cancellation should override this method.
    fn cancel(
        &self,
        request_id: &ExecutionRequestId,
    ) -> Result<(), ExecutionError> {
        if request_id.as_str().trim().is_empty() {
            return Err(ExecutionError::InvalidRequestId);
        }

        Ok(())
    }
}

