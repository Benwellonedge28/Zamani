fn validate_identifier(
    value: String,
    field: &'static str,
) -> Result<String, ExecutionError> {
    if value.trim().is_empty() {
        return Err(ExecutionError::InvalidExecutorIdentifier { field });
    }

    Ok(value)
}

fn validate_metadata_key(
    value: String,
) -> Result<String, ExecutionError> {
    if value.trim().is_empty() {
        return Err(ExecutionError::InvalidMetadataKey);
    }

    Ok(value)
}

fn validate_metadata_value(
    value: String,
) -> Result<String, ExecutionError> {
    if value.contains('\0') {
        return Err(ExecutionError::InvalidMetadataValue);
    }

    Ok(value)
}

fn validate_metadata_map(
    values: &BTreeMap<String, String>,
) -> Result<(), ExecutionError> {
    for (key, value) in values {
        validate_metadata_key(key.clone())?;
        validate_metadata_value(value.clone())?;
    }

    Ok(())
}

/// The execution layer deliberately does not inspect private internals of the
/// Quantum IR here.
///
/// This helper is intentionally isolated so that if the canonical IR later
/// exposes an `is_empty()` API, only this helper needs to be adapted.
///
/// For the current production contract, an `Arc<QuantumCircuit>` itself is
/// considered a valid circuit object. Canonical IR validation remains the
/// responsibility of `quantum::ir::validation`.
#[inline]
fn circuit_is_empty(_circuit: &Arc<QuantumCircuit>) -> bool {
    false
}

/// Attempts to infer completed shots from observations.
///
/// Counts and annealing observations expose explicit occurrence information.
/// Probability/state observations do not necessarily encode a shot count, so
/// those return `None` and the caller may use the request's declared count.
fn infer_completed_shots(
    observations: &[ExecutionObservation],
) -> Option<usize> {
    for observation in observations {
        match observation {
            ExecutionObservation::Counts(counts) => {
                let total = counts.values().try_fold(
                    0usize,
                    |acc, value| acc.checked_add(*value),
                );

                if let Some(total) = total {
                    return Some(total);
                }

                return None;
            }

            ExecutionObservation::AnnealingSamples(samples) => {
                let mut total = 0usize;

                for sample in samples {
                    if let Some(occurrences) = sample.occurrences {
                        total = total.checked_add(occurrences)?;
                    }
                }

                if total > 0 {
                    return Some(total);
                }
            }

            _ => {}
        }
    }

    None
}

