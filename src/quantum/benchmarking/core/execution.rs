/// Production execution request.
///
/// This is the canonical object passed to a `BenchmarkExecutor`.
///
/// The request contains a canonical Zamani Quantum IR circuit. Benchmark
/// generators produce the circuit; the execution layer consumes it.
///
/// Backend-specific providers should translate this object into their own
/// provider-native request without changing the benchmark semantics.
#[derive(Debug, Clone)]
pub struct ExecutionRequest {
    /// Execution-contract schema version.
    pub schema_version: u32,

    /// Stable request identity.
    pub request_id: ExecutionRequestId,

    /// Target backend.
    pub backend_id: ExecutionBackendId,

    /// Requested execution mode.
    pub execution_mode: ExecutionMode,

    /// Canonical Zamani Quantum IR circuit.
    pub circuit: Arc<QuantumCircuit>,

    /// Requested number of shots.
    pub shots: ShotCount,

    /// Requested observation representation.
    pub measurement_mode: MeasurementMode,

    /// Optional deterministic seed.
    ///
    /// This is a request-level seed. A backend may reject it when deterministic
    /// seeding is unsupported. The executor must never silently replace it.
    pub seed: Option<u64>,

    /// Maximum permitted execution duration.
    pub timeout: ExecutionTimeout,

    /// Cooperative cancellation token.
    pub cancellation: CancellationToken,

    /// Optional benchmark/experiment tags.
    ///
    /// Tags are metadata only. They must never change execution semantics.
    pub tags: BTreeMap<String, String>,

    /// Provider-neutral request metadata.
    pub metadata: BTreeMap<String, String>,
}

impl ExecutionRequest {
    /// Creates a request using production defaults.
    pub fn new(
        request_id: ExecutionRequestId,
        backend_id: ExecutionBackendId,
        execution_mode: ExecutionMode,
        circuit: Arc<QuantumCircuit>,
    ) -> Result<Self, ExecutionError> {
        if circuit_is_empty(&circuit) {
            return Err(ExecutionError::EmptyCircuit);
        }

        Ok(Self {
            schema_version: EXECUTION_REQUEST_SCHEMA_VERSION,
            request_id,
            backend_id,
            execution_mode,
            circuit,
            shots: ShotCount::default(),
            measurement_mode: MeasurementMode::Counts,
            seed: None,
            timeout: ExecutionTimeout::default(),
            cancellation: CancellationToken::default(),
            tags: BTreeMap::new(),
            metadata: BTreeMap::new(),
        })
    }

    /// Sets the shot count.
    pub fn with_shots(
        mut self,
        shots: usize,
    ) -> Result<Self, ExecutionError> {
        self.shots = ShotCount::new(shots)?;
        Ok(self)
    }

    /// Sets the observation mode.
    pub fn with_measurement_mode(
        mut self,
        mode: MeasurementMode,
    ) -> Self {
        self.measurement_mode = mode;
        self
    }

    /// Sets the deterministic seed.
    pub fn with_seed(mut self, seed: u64) -> Self {
        self.seed = Some(seed);
        self
    }

    /// Sets the execution timeout.
    pub fn with_timeout(
        mut self,
        timeout: Duration,
    ) -> Result<Self, ExecutionError> {
        self.timeout = ExecutionTimeout::new(timeout)?;
        Ok(self)
    }

    /// Adds an execution tag.
    pub fn with_tag(
        mut self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> Result<Self, ExecutionError> {
        let key = validate_metadata_key(key.into())?;
        let value = validate_metadata_value(value.into())?;

        self.tags.insert(key, value);

        Ok(self)
    }

    /// Adds request metadata.
    pub fn with_metadata(
        mut self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> Result<Self, ExecutionError> {
        let key = validate_metadata_key(key.into())?;
        let value = validate_metadata_value(value.into())?;

        self.metadata.insert(key, value);

        Ok(self)
    }

    /// Validates the complete request.
    ///
    /// This validation is deliberately provider-neutral. Backend capability
    /// validation belongs to the selected executor/backend.
    pub fn validate(&self) -> Result<(), ExecutionError> {
        if self.schema_version != EXECUTION_REQUEST_SCHEMA_VERSION {
            return Err(ExecutionError::UnsupportedSchemaVersion {
                kind: SchemaKind::Request,
                version: self.schema_version,
            });
        }

        if self.request_id.as_str().trim().is_empty() {
            return Err(ExecutionError::InvalidRequestId);
        }

        if self.backend_id.as_str().trim().is_empty() {
            return Err(ExecutionError::InvalidBackendId);
        }

        if circuit_is_empty(&self.circuit) {
            return Err(ExecutionError::EmptyCircuit);
        }

        if self.shots.get() == 0 {
            return Err(ExecutionError::InvalidShotCount);
        }

        if self.timeout.duration().is_zero() {
            return Err(ExecutionError::InvalidTimeout);
        }

        validate_metadata_map(&self.tags)?;
        validate_metadata_map(&self.metadata)?;

        Ok(())
    }
}

