/// Terminal or non-terminal state of an execution.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ExecutionStatus {
    /// Request accepted but execution has not begun.
    Accepted,

    /// Execution is currently running.
    Running,

    /// Execution completed successfully.
    Completed,

    /// Execution completed with only part of the requested work.
    Partial,

    /// Execution was cancelled.
    Cancelled,

    /// Execution exceeded its timeout.
    TimedOut,

    /// Execution failed.
    Failed,
}

impl ExecutionStatus {
    /// Returns whether this status represents a terminal state.
    pub fn is_terminal(self) -> bool {
        matches!(
            self,
            Self::Completed
                | Self::Partial
                | Self::Cancelled
                | Self::TimedOut
                | Self::Failed
        )
    }

    /// Returns whether observations are potentially usable.
    pub fn may_contain_observations(self) -> bool {
        matches!(
            self,
            Self::Completed | Self::Partial
        )
    }
}

