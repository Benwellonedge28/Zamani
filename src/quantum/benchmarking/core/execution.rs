/// Stable metadata exposed by an executor.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExecutorMetadata {
    /// Executor implementation identifier.
    pub id: String,

    /// Human-readable name.
    pub name: String,

    /// Executor implementation version.
    pub version: String,

    /// Backend identity.
    pub backend_id: ExecutionBackendId,

    /// Execution mode.
    pub execution_mode: ExecutionMode,

    /// Capability profile.
    pub capabilities: ExecutionCapabilities,

    /// Arbitrary provider-neutral metadata.
    pub metadata: BTreeMap<String, String>,
}

impl ExecutorMetadata {
    pub fn new(
        id: impl Into<String>,
        name: impl Into<String>,
        version: impl Into<String>,
        backend_id: ExecutionBackendId,
        execution_mode: ExecutionMode,
        capabilities: ExecutionCapabilities,
    ) -> Result<Self, ExecutionError> {
        let id = validate_identifier(id.into(), "executor ID")?;
        let name = validate_identifier(name.into(), "executor name")?;
        let version = validate_identifier(version.into(), "executor version")?;

        Ok(Self {
            id,
            name,
            version,
            backend_id,
            execution_mode,
            capabilities,
            metadata: BTreeMap::new(),
        })
    }

    pub fn with_metadata(
        mut self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> Result<Self, ExecutionError> {
        let key = validate_metadata_key(key.into())?;
        let value = validate_metadata_value(value.into())?;

        self.metadata.insert(key, value);

        Ok(self)
    }
}

