//! Zamani Quantum Benchmarking — Execution Contract
//!
//! Production execution boundary for the quantum benchmarking subsystem.
//!
//! # Purpose
//!
//! This module defines the backend-independent contract between a benchmark
//! experiment and the system that actually executes its workload.
//!
//! It deliberately does NOT:
//!
//! - generate benchmark circuits;
//! - implement Quantum Volume;
//! - implement randomized benchmarking;
//! - implement XEB;
//! - perform statistical analysis;
//! - own hardware-provider SDKs;
//! - perform network I/O;
//! - perform compilation/transpilation;
//! - perform routing;
//! - perform scheduling;
//! - contain benchmark-specific mathematics;
//! - assume that every quantum system is a gate-model QPU;
//! - assume that every backend returns bitstring counts.
//!
//! Those responsibilities belong to their owning subsystems.
//!
//! # Architectural position
//!
//! ```text
//! Zamani source / benchmark definition
//!             │
//!             ▼
//!     benchmarking::core
//!             │
//!             ▼
//!     BenchmarkExperiment
//!             │
//!             ▼
//!     BenchmarkExecutor
//!             │
//!       ┌─────┴─────┐
//!       ▼           ▼
//!   simulator      hardware
//!       │           │
//!       └─────┬─────┘
//!             ▼
//!      ExecutionResponse
//!             │
//!             ▼
//!     benchmarking::core
//!             │
//!             ▼
//!       observations
//!             │
//!             ▼
//!       statistics
//!             │
//!             ▼
//!         metrics
//!             │
//!             ▼
//!      BenchmarkResult
//! ```
//!
//! # Dependency direction
//!
//! ```text
//! benchmarking::execution
//!          │
//!          ▼
//! quantum::ir
//!
//! benchmarking::execution
//!          │
//!          ▼
//! quantum::hardware
//!
//! quantum::ir
//!      X
//!      │
//!      └────> benchmarking
//! ```
//!
//! The Quantum IR remains the canonical representation of logical quantum
//! programs. Benchmarking consumes IR; it does not redefine it.
//!
//! The hardware layer remains responsible for backend identity, capabilities,
//! topology, calibration, and hardware-specific execution adapters.
//!
//! # Production requirements
//!
//! This module is designed around the following invariants:
//!
//! 1. Every execution request has a stable request identity.
//! 2. Every response identifies the request and backend that produced it.
//! 3. A request is validated before execution.
//! 4. Invalid requests fail explicitly rather than being silently modified.
//! 5. Partial execution is represented explicitly.
//! 6. Cancellation is cooperative and observable.
//! 7. Timeouts are explicit.
//! 8. Retries are not performed implicitly by this layer.
//! 9. Backend-specific metadata is preserved rather than discarded.
//! 10. Raw observations remain available for independent re-analysis.
//! 11. Execution timing is captured independently from benchmark statistics.
//! 12. The execution layer never prints diagnostics directly.
//! 13. The execution layer has no process-global mutable state.
//! 14. No unsafe code is required.
//! 15. The API is synchronous so that Zamani does not require a particular
//!     async runtime.
//!
//! # Rust compatibility
//!
//! Target: Rust 1.97.1 / Rust 2021.
//!
//! No nightly features are required.
//! No additional crate dependency is required by this file.

