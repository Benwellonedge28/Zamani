//! Zamani Quantum Benchmarking — Canonical Benchmark Result
//!
//! Production-grade result envelope for all Zamani quantum benchmarks.
//!
//! # Architectural role
//!
//! `BenchmarkResult` is the immutable boundary between benchmark execution /
//! analysis and downstream consumers such as:
//!
//! - reporting;
//! - JSON/CSV/Markdown serialization;
//! - regression analysis;
//! - baseline comparison;
//! - reproducibility analysis;
//! - CI;
//! - the Zamani standard library;
//! - the Zamani programming language.
//!
//! The result model deliberately does NOT:
//!
//! - execute circuits;
//! - generate circuits;
//! - select hardware;
//! - compile or route circuits;
//! - calculate benchmark metrics;
//! - perform statistical fitting;
//! - implement a benchmark protocol;
//! - mutate backend state.
//!
//! Those responsibilities belong to their respective modules.
//!
//! # Canonical dependency direction
//!
//! ```text
//! quantum::frontend
//!        │
//!        ▼
//! quantum::ir
//!        │
//!        ▼
//! benchmark workload / experiment
//!        │
//!        ▼
//! execution
//!        │
//!        ▼
//! core::observation ───────┐
//!                          │
//! statistics ──────────────┤
//!                          ▼
//! metrics ───────────────► BenchmarkResult
//!                          │
//! provenance ──────────────┤
//!                          ▼
//!              reporting / analysis / CI
//! ```
//!
//! `core::result` therefore depends on foundational result components but
//! never becomes a dependency of those foundational components.
//!
//! # Production invariants
//!
//! A validated result:
//!
//! 1. has a non-empty schema version;
//! 2. has a non-empty result identity;
//! 3. has a non-empty benchmark identity;
//! 4. contains at least one metric or one observation;
//! 5. contains validated metrics;
//! 6. contains validated observations;
//! 7. contains validated provenance;
//! 8. has internally consistent execution status;
//! 9. never contains NaN or infinity through the metric model;
//! 10. never contains duplicate metric identities;
//! 11. never contains duplicate observation identities;
//! 12. records partial execution explicitly;
//! 13. preserves warnings and errors instead of silently dropping them;
//! 14. distinguishes benchmark failure from execution failure;
//! 15. can be serialized and independently re-validated;
//! 16. does not contain backend-specific execution objects;
//! 17. does not expose mutable collections;
//! 18. has a deterministic result fingerprint input;
//! 19. is safe to construct from untrusted serialized data only after
//!     validation;
//! 20. does not silently reinterpret observations as metrics.
//!
//! # Important semantic distinction
//!
//! A benchmark can execute successfully and still fail its scientific
//! acceptance criterion.
//!
//! For example:
//!
//! ```text
//! execution_status = Completed
//! benchmark_status = Failed
//! ```
//!
//! means that all requested work executed correctly but the measured quality
//! did not satisfy the benchmark threshold.
//!
//! Conversely:
//!
//! ```text
//! execution_status = Failed
//! benchmark_status = Inconclusive
//! ```
//!
//! means that the benchmark could not produce a scientifically valid decision.
//!
//! These states must never be conflated.
//!
//! # Result identity
//!
//! `BenchmarkResult` contains an explicit result ID. It is NOT automatically
//! generated from wall-clock time, process ID, hostname, or global state.
//!
//! This is intentional:
//!
//! - deterministic fixtures remain deterministic;
//! - hardware executions may supply externally assigned IDs;
//! - reproducibility does not depend on process-global state;
//! - result IDs can be generated by a higher-level experiment manager.
//!
//! # Resource safety
//!
//! Result construction enforces bounded collection sizes.
//!
//! The result layer must never become a memory-exhaustion vector merely because
//! a malicious or corrupted serialized result contains millions of metrics,
//! observations, warnings, or errors.
//!
//! # Serialization
//!
//! Serde is used for the canonical interchange representation.
//!
//! Deserialized results MUST be validated before use:
//!
//! ```text
//! deserialize
//!     ↓
//! BenchmarkResult::validate
//!     ↓
//! trusted BenchmarkResult
//! ```
//!
//! # Integration contracts
//!
//! This file consumes the following authoritative types:
//!
//! - `core::metric::Metric`
//! - `core::observation::Observation`
//! - `core::provenance::BenchmarkProvenance`
//!
//! The result layer does not redefine those concepts.
//!
//! Future modules integrate as follows:
//!
//! ```text
//! core::experiment
//!        │
//!        ▼
//! execution/*
//!        │
//!        ├──────────────► observations
//!        │
//!        ▼
//! protocols/* ─────────► metrics
//!        │
//!        ▼
//! core::result
//!        │
//!        ├── reporting/*
//!        ├── analysis/*
//!        ├── registry/*
//!        ├── validation/*
//!        └── stdlib::quantum
//! ```
//!
//! # Rust compatibility
//!
//! Target: Rust 1.97 / Rust 1.97.1.
//! Edition: Rust 2021.
//! No nightly features.
//! No unsafe code.
//!
//! ---------------------------------------------------------------------------

