// =============================================================================
// Validation helpers
// =============================================================================

fn validate_identifier(
    field: &'static str,
    value: &str,
    maximum: usize,
) -> Result<(), ResultError> {
    validate_non_empty_bounded(field, value, maximum)?;

    for character in value.chars() {
        let valid = character.is_ascii_alphanumeric()
            || matches!(
                character,
                '-' | '_' | '.' | ':' | '/' | '@' | '+'
            );

        if !valid {
            return Err(ResultError::InvalidIdentifier {
                field,
                reason: "contains unsupported identifier characters",
            });
        }
    }

    Ok(())
}

fn validate_non_empty_bounded(
    field: &'static str,
    value: &str,
    maximum: usize,
) -> Result<(), ResultError> {
    if value.trim().is_empty() {
        return Err(ResultError::InvalidString {
            field,
            reason: "must not be empty",
        });
    }

    if value.len() > maximum {
        return Err(ResultError::InvalidString {
            field,
            reason: "exceeds maximum permitted length",
        });
    }

    Ok(())
}

fn validate_finite(
    field: &'static str,
    value: f64,
) -> Result<(), ResultError> {
    if !value.is_finite() {
        return Err(ResultError::NonFiniteValue { field });
    }

    Ok(())
}

fn validate_unit_interval_closed(
    field: &'static str,
    value: f64,
) -> Result<(), ResultError> {
    validate_finite(field, value)?;

    if !(0.0..=1.0).contains(&value) {
        return Err(ResultError::InvalidProbability {
            field,
            value,
        });
    }

    Ok(())
}

fn validate_unit_interval_open(
    field: &'static str,
    value: f64,
) -> Result<(), ResultError> {
    validate_finite(field, value)?;

    if !(0.0..1.0).contains(&value) {
        return Err(ResultError::InvalidConfidenceLevel {
            field,
            value,
        });
    }

    Ok(())
}

fn validate_duration(
    field: &'static str,
    duration: Option<Duration>,
) -> Result<(), ResultError> {
    if duration.is_some_and(|value| value.as_secs() > u64::MAX / 1_000_000) {
        return Err(ResultError::InvalidDuration { field });
    }

    Ok(())
}

