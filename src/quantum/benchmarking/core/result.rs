/// Stable identifier for one benchmark result.
///
/// A result ID identifies a concrete result artifact, not merely a benchmark
/// protocol.
///
/// Example:
///
/// ```text
/// qv-20q-seed42-run-0001
/// ```
#[derive(
    Debug,
    Clone,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Hash,
    Serialize,
    Deserialize,
)]
#[serde(transparent)]
pub struct BenchmarkResultId(String);

impl BenchmarkResultId {
    /// Creates a validated result identifier.
    pub fn new(value: impl Into<String>) -> Result<Self, ResultError> {
        let value = value.into();

        validate_identifier(
            "result_id",
            &value,
            MAX_RESULT_ID_LENGTH,
        )?;

        Ok(Self(value))
    }

    /// Returns the identifier as a string slice.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Consumes the identifier.
    #[must_use]
    pub fn into_string(self) -> String {
        self.0
    }
}

impl AsRef<str> for BenchmarkResultId {
    fn as_ref(&self) -> &str {
        self.as_str()
    }
}

impl fmt::Display for BenchmarkResultId {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

