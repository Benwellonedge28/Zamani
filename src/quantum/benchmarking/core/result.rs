impl ResultExecutionSummary {
    /// Returns the number of workload items that produced an execution result.
    #[must_use]
    pub fn executed_workload_count(&self) -> u64 {
        self.completed_workloads
            .saturating_add(self.failed_workloads)
            .saturating_add(self.cancelled_workloads)
    }
}

