/// Canonical Zamani benchmark result.
///
/// This is the universal result envelope for:
///
/// - Quantum Volume;
/// - randomized benchmarking;
/// - interleaved RB;
/// - simultaneous RB;
/// - purity/leakage RB;
/// - cycle benchmarking;
/// - XEB;
/// - random circuit sampling;
/// - mirror circuits;
/// - SPAM;
/// - coherence;
/// - crosstalk;
/// - drift;
/// - tomography;
/// - volumetric benchmarking;
/// - application benchmarks;
/// - QEC benchmarks;
/// - logical-qubit benchmarks;
/// - future quantum technologies.
///
/// The result model does not assume that a benchmark is gate-model, sampled,
/// hardware-based, or even qubit-based.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BenchmarkResult {
    /// Canonical result schema version.
    pub schema_version: u16,

    /// Canonical result schema identifier.
    pub schema_id: String,

    /// Stable result identity.
    pub result_id: BenchmarkResultId,

    /// Benchmark protocol identity.
    pub benchmark: ResultBenchmarkIdentity,

    /// Scientific benchmark status.
    pub benchmark_status: BenchmarkStatus,

    /// Execution completeness/status.
    pub execution_status: ResultExecutionStatus,

    /// Validation state of this result object.
    ///
    /// This field is informational. `validate()` is authoritative.
    #[serde(default)]
    pub validation_state: ResultValidationState,

    /// Execution accounting.
    pub execution: ResultExecutionSummary,

    /// Statistical validity metadata.
    pub statistics: ResultStatistics,

    /// Canonical metrics.
    ///
    /// The metric semantics remain owned by `core::metric`.
    #[serde(default)]
    pub metrics: Vec<Metric>,

    /// Raw/normalized observations.
    ///
    /// The observation semantics remain owned by `core::observation`.
    #[serde(default)]
    pub observations: Vec<Observation>,

    /// Complete benchmark provenance.
    pub provenance: BenchmarkProvenance,

    /// Structured informational/warning/error messages.
    #[serde(default)]
    pub messages: Vec<ResultMessage>,

    /// Optional stable result fingerprint.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub fingerprint: Option<ResultFingerprint>,

    /// User/registry tags.
    #[serde(default)]
    pub tags: Vec<String>,
}

impl BenchmarkResult {
    /// Creates an empty result envelope.
    ///
    /// The returned object is deliberately `Unvalidated` and
    /// `NotExecuted`. Callers must populate metrics/observations/provenance
    /// and call `validate()` before treating it as a production result.
    pub fn new(
        result_id: BenchmarkResultId,
        benchmark: ResultBenchmarkIdentity,
        provenance: BenchmarkProvenance,
    ) -> Self {
        Self {
            schema_version: BENCHMARK_RESULT_SCHEMA_VERSION,
            schema_id: BENCHMARK_RESULT_SCHEMA_ID.to_owned(),
            result_id,
            benchmark,
            benchmark_status: BenchmarkStatus::Inconclusive,
            execution_status: ResultExecutionStatus::NotExecuted,
            validation_state: ResultValidationState::Unvalidated,
            execution: ResultExecutionSummary::default(),
            statistics: ResultStatistics::default(),
            metrics: Vec::new(),
            observations: Vec::new(),
            provenance,
            messages: Vec::new(),
            fingerprint: None,
            tags: Vec::new(),
        }
    }

    /// Adds a metric after validating it.
    ///
    /// The metric itself remains authoritative for metric-domain validation.
    pub fn add_metric(
        &mut self,
        metric: Metric,
    ) -> Result<(), ResultError> {
        if self.metrics.len() >= MAX_RESULT_METRICS {
            return Err(ResultError::LimitExceeded {
                resource: "metrics",
                requested: self.metrics.len().saturating_add(1),
                maximum: MAX_RESULT_METRICS,
            });
        }

        validate_metric(&metric)?;

        if self.metrics.iter().any(|existing| existing == &metric) {
            return Err(ResultError::DuplicateMetric);
        }

        self.metrics.push(metric);
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Adds an observation after validating it.
    pub fn add_observation(
        &mut self,
        observation: Observation,
    ) -> Result<(), ResultError> {
        if self.observations.len() >= MAX_RESULT_OBSERVATIONS {
            return Err(ResultError::LimitExceeded {
                resource: "observations",
                requested: self.observations.len().saturating_add(1),
                maximum: MAX_RESULT_OBSERVATIONS,
            });
        }

        validate_observation(&observation)?;

        if self
            .observations
            .iter()
            .any(|existing| existing == &observation)
        {
            return Err(ResultError::DuplicateObservation);
        }

        self.observations.push(observation);
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Adds a structured message.
    pub fn add_message(
        &mut self,
        message: ResultMessage,
    ) -> Result<(), ResultError> {
        message.validate()?;

        match message.severity {
            ResultMessageSeverity::Error => {
                if self.messages.len() >= MAX_RESULT_ERRORS {
                    return Err(ResultError::LimitExceeded {
                        resource: "error_messages",
                        requested: self.messages.len().saturating_add(1),
                        maximum: MAX_RESULT_ERRORS,
                    });
                }
            }

            ResultMessageSeverity::Warning
            | ResultMessageSeverity::Info => {
                if self.messages.len() >= MAX_RESULT_WARNINGS {
                    return Err(ResultError::LimitExceeded {
                        resource: "warning_messages",
                        requested: self.messages.len().saturating_add(1),
                        maximum: MAX_RESULT_WARNINGS,
                    });
                }
            }
        }

        self.messages.push(message);
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Adds a bounded tag.
    pub fn add_tag(
        &mut self,
        tag: impl Into<String>,
    ) -> Result<(), ResultError> {
        if self.tags.len() >= MAX_RESULT_TAGS {
            return Err(ResultError::LimitExceeded {
                resource: "tags",
                requested: self.tags.len().saturating_add(1),
                maximum: MAX_RESULT_TAGS,
            });
        }

        let tag = tag.into();

        validate_non_empty_bounded(
            "tag",
            &tag,
            MAX_RESULT_TAG_LENGTH,
        )?;

        if self.tags.iter().any(|existing| existing == &tag) {
            return Err(ResultError::DuplicateTag);
        }

        self.tags.push(tag);
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Sets the scientific benchmark status.
    pub fn set_benchmark_status(
        &mut self,
        status: BenchmarkStatus,
    ) {
        self.benchmark_status = status;
        self.validation_state = ResultValidationState::Unvalidated;
    }

    /// Sets execution status.
    pub fn set_execution_status(
        &mut self,
        status: ResultExecutionStatus,
    ) {
        self.execution_status = status;
        self.validation_state = ResultValidationState::Unvalidated;
    }

    /// Sets execution accounting.
    pub fn set_execution_summary(
        &mut self,
        execution: ResultExecutionSummary,
    ) -> Result<(), ResultError> {
        execution.validate()?;

        self.execution = execution;
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Sets statistical metadata.
    pub fn set_statistics(
        &mut self,
        statistics: ResultStatistics,
    ) -> Result<(), ResultError> {
        statistics.validate()?;

        self.statistics = statistics;
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Sets the result fingerprint.
    pub fn set_fingerprint(
        &mut self,
        fingerprint: ResultFingerprint,
    ) -> Result<(), ResultError> {
        self.fingerprint = Some(fingerprint);
        self.validation_state = ResultValidationState::Unvalidated;

        Ok(())
    }

    /// Validates the complete result.
    ///
    /// This method is the authoritative trust boundary after deserialization.
    pub fn validate(&self) -> Result<(), ResultError> {
        self.validate_schema()?;
        self.result_id_validate()?;
        self.benchmark.validate()?;
        self.execution.validate()?;
        self.statistics.validate()?;
        self.provenance.validate()?;

        self.validate_execution_semantics()?;
        self.validate_metrics()?;
        self.validate_observations()?;
        self.validate_messages()?;
        self.validate_tags()?;
        self.validate_result_content()?;

        Ok(())
    }

    /// Returns a validated result state without mutating the object.
    ///
    /// This is useful when callers need a proof-like validation step before
    /// passing the result to reporting or analysis.
    pub fn validated(&self) -> Result<ValidatedBenchmarkResult<'_>, ResultError> {
        self.validate()?;

        Ok(ValidatedBenchmarkResult { result: self })
    }

    /// Returns the number of metrics.
    #[must_use]
    pub fn metric_count(&self) -> usize {
        self.metrics.len()
    }

    /// Returns the number of observations.
    #[must_use]
    pub fn observation_count(&self) -> usize {
        self.observations.len()
    }

    /// Returns whether execution completed completely.
    #[must_use]
    pub fn is_execution_complete(&self) -> bool {
        self.execution_status.is_complete()
    }

    /// Returns whether the scientific benchmark passed.
    #[must_use]
    pub fn passed(&self) -> bool {
        self.benchmark_status == BenchmarkStatus::Passed
    }

    /// Returns whether the result is scientifically inconclusive.
    #[must_use]
    pub fn is_inconclusive(&self) -> bool {
        self.benchmark_status == BenchmarkStatus::Inconclusive
    }

    /// Returns whether execution was partial.
    #[must_use]
    pub fn is_partial(&self) -> bool {
        self.execution_status.is_partial()
    }

    /// Returns a metric by equality with its canonical metric identity.
    ///
    /// Metric identity semantics remain owned by `core::metric`.
    pub fn find_metric(&self, metric: &Metric) -> Option<&Metric> {
        self.metrics.iter().find(|candidate| *candidate == metric)
    }

    /// Returns all error messages.
    pub fn errors(&self) -> impl Iterator<Item = &ResultMessage> {
        self.messages
            .iter()
            .filter(|message| {
                message.severity == ResultMessageSeverity::Error
            })
    }

    /// Returns all warnings.
    pub fn warnings(&self) -> impl Iterator<Item = &ResultMessage> {
        self.messages
            .iter()
            .filter(|message| {
                message.severity == ResultMessageSeverity::Warning
            })
    }

    /// Returns a read-only view of metrics.
    #[must_use]
    pub fn metrics(&self) -> &[Metric] {
        &self.metrics
    }

    /// Returns a read-only view of observations.
    #[must_use]
    pub fn observations(&self) -> &[Observation] {
        &self.observations
    }

    /// Returns a read-only view of messages.
    #[must_use]
    pub fn messages(&self) -> &[ResultMessage] {
        &self.messages
    }

    /// Returns a read-only view of tags.
    #[must_use]
    pub fn tags(&self) -> &[String] {
        &self.tags
    }

    // -------------------------------------------------------------------------
    // Private validation
    // -------------------------------------------------------------------------

    fn validate_schema(&self) -> Result<(), ResultError> {
        if self.schema_version != BENCHMARK_RESULT_SCHEMA_VERSION {
            return Err(ResultError::UnsupportedSchemaVersion {
                found: self.schema_version,
                supported: BENCHMARK_RESULT_SCHEMA_VERSION,
            });
        }

        if self.schema_id != BENCHMARK_RESULT_SCHEMA_ID {
            return Err(ResultError::InvalidSchemaId {
                expected: BENCHMARK_RESULT_SCHEMA_ID,
                found: self.schema_id.clone(),
            });
        }

        Ok(())
    }

    fn result_id_validate(&self) -> Result<(), ResultError> {
        validate_identifier(
            "result_id",
            self.result_id.as_str(),
            MAX_RESULT_ID_LENGTH,
        )
    }

    fn validate_execution_semantics(
        &self,
    ) -> Result<(), ResultError> {
        match self.execution_status {
            ResultExecutionStatus::NotExecuted => {
                if self.execution.executed_workload_count() > 0 {
                    return Err(ResultError::InconsistentExecution {
                        reason: "not_executed result contains executed workloads",
                    });
                }

                if self.execution.executed_circuits > 0 {
                    return Err(ResultError::InconsistentExecution {
                        reason: "not_executed result contains executed circuits",
                    });
                }

                if self.execution.executed_shots > 0 {
                    return Err(ResultError::InconsistentExecution {
                        reason: "not_executed result contains executed shots",
                    });
                }
            }

            ResultExecutionStatus::Completed => {
                if self.execution.failed_workloads != 0
                    || self.execution.cancelled_workloads != 0
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "completed result contains failed or cancelled workloads",
                    });
                }

                if self.execution.requested_workloads
                    != self.execution.completed_workloads
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "completed result did not complete every requested workload",
                    });
                }

                if self.execution.requested_circuits
                    != self.execution.executed_circuits
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "completed result did not execute every requested circuit",
                    });
                }

                if self.execution.requested_shots
                    != self.execution.executed_shots
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "completed result did not execute every requested shot",
                    });
                }
            }

            ResultExecutionStatus::PartiallyCompleted => {
                if self.execution.completed_workloads == 0
                    && self.execution.executed_circuits == 0
                    && self.execution.executed_shots == 0
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "partially_completed result contains no completed execution",
                    });
                }
            }

            ResultExecutionStatus::Cancelled => {
                if self.execution.cancelled_workloads == 0
                    && self.execution.executed_circuits
                        == self.execution.requested_circuits
                    && self.execution.requested_circuits != 0
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "cancelled result appears to contain complete execution",
                    });
                }
            }

            ResultExecutionStatus::Failed => {
                if self.execution.failed_workloads == 0
                    && self.execution.executed_circuits == 0
                    && self.execution.executed_shots == 0
                    && self.messages.iter().all(|message| {
                        message.severity
                            != ResultMessageSeverity::Error
                    })
                {
                    return Err(ResultError::InconsistentExecution {
                        reason: "failed result has no execution failure evidence",
                    });
                }
            }

            ResultExecutionStatus::Running => {
                // A running artifact may contain zero observations or a
                // partial set. It is deliberately permitted.
            }
        }

        Ok(())
    }

    fn validate_metrics(&self) -> Result<(), ResultError> {
        if self.metrics.len() > MAX_RESULT_METRICS {
            return Err(ResultError::LimitExceeded {
                resource: "metrics",
                requested: self.metrics.len(),
                maximum: MAX_RESULT_METRICS,
            });
        }

        let mut identities = BTreeSet::new();

        for metric in &self.metrics {
            validate_metric(metric)?;

            let identity = metric_identity(metric);

            if !identities.insert(identity) {
                return Err(ResultError::DuplicateMetric);
            }
        }

        Ok(())
    }

    fn validate_observations(&self) -> Result<(), ResultError> {
        if self.observations.len() > MAX_RESULT_OBSERVATIONS {
            return Err(ResultError::LimitExceeded {
                resource: "observations",
                requested: self.observations.len(),
                maximum: MAX_RESULT_OBSERVATIONS,
            });
        }

        let mut identities = BTreeSet::new();

        for observation in &self.observations {
            validate_observation(observation)?;

            let identity = observation_identity(observation);

            if !identities.insert(identity) {
                return Err(ResultError::DuplicateObservation);
            }
        }

        Ok(())
    }

    fn validate_messages(&self) -> Result<(), ResultError> {
        let mut error_count = 0usize;
        let mut warning_count = 0usize;

        for message in &self.messages {
            message.validate()?;

            match message.severity {
                ResultMessageSeverity::Error => {
                    error_count = error_count.saturating_add(1);

                    if error_count > MAX_RESULT_ERRORS {
                        return Err(ResultError::LimitExceeded {
                            resource: "error_messages",
                            requested: error_count,
                            maximum: MAX_RESULT_ERRORS,
                        });
                    }
                }

                ResultMessageSeverity::Warning
                | ResultMessageSeverity::Info => {
                    warning_count = warning_count.saturating_add(1);

                    if warning_count > MAX_RESULT_WARNINGS {
                        return Err(ResultError::LimitExceeded {
                            resource: "warning_messages",
                            requested: warning_count,
                            maximum: MAX_RESULT_WARNINGS,
                        });
                    }
                }
            }
        }

        Ok(())
    }

    fn validate_tags(&self) -> Result<(), ResultError> {
        if self.tags.len() > MAX_RESULT_TAGS {
            return Err(ResultError::LimitExceeded {
                resource: "tags",
                requested: self.tags.len(),
                maximum: MAX_RESULT_TAGS,
            });
        }

        let mut tags = BTreeSet::new();

        for tag in &self.tags {
            validate_non_empty_bounded(
                "tag",
                tag,
                MAX_RESULT_TAG_LENGTH,
            )?;

            if !tags.insert(tag) {
                return Err(ResultError::DuplicateTag);
            }
        }

        Ok(())
    }

    fn validate_result_content(&self) -> Result<(), ResultError> {
        let has_metrics = !self.metrics.is_empty();
        let has_observations = !self.observations.is_empty();

        match self.execution_status {
            ResultExecutionStatus::NotExecuted => {
                // Generate-only or externally analysed results may have neither
                // observations nor metrics yet. Such an object is not useful
                // as a completed scientific result but is structurally valid.
                return Ok(());
            }

            ResultExecutionStatus::Running => {
                // Partial execution may legitimately contain no observations
                // immediately after submission.
                return Ok(());
            }

            _ => {}
        }

        if !has_metrics && !has_observations {
            return Err(ResultError::EmptyResultContent);
        }

        Ok(())
    }
}

