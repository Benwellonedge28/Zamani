/// Stable result fingerprint.
///
/// This is an identifier for the result artifact, not a digital signature and
/// not proof of authorship.
///
/// The actual cryptographic hashing policy belongs to provenance/reproducibility
/// infrastructure. This type exists so the result schema can represent a
/// fingerprint without embedding a hashing implementation.
#[derive(
    Debug,
    Clone,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Hash,
    Serialize,
    Deserialize,
)]
#[serde(transparent)]
pub struct ResultFingerprint(String);

impl ResultFingerprint {
    /// Creates a validated fingerprint string.
    ///
    /// Hexadecimal SHA-256 is the preferred representation, but the result
    /// layer deliberately permits another explicitly versioned fingerprint
    /// format for future algorithms.
    pub fn new(value: impl Into<String>) -> Result<Self, ResultError> {
        let value = value.into();

        validate_non_empty_bounded(
            "result_fingerprint",
            &value,
            256,
        )?;

        Ok(Self(value))
    }

    /// Returns the fingerprint.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for ResultFingerprint {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

