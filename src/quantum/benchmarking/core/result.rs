/// Scientific interpretation of a benchmark result.
///
/// This is deliberately separate from [`ResultExecutionStatus`].
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Hash,
    Serialize,
    Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum BenchmarkStatus {
    /// No scientific decision has been made.
    Inconclusive,

    /// The benchmark acceptance criterion was satisfied.
    Passed,

    /// The benchmark acceptance criterion was not satisfied.
    Failed,

    /// The benchmark was explicitly not applicable to the workload/backend.
    NotApplicable,
}

impl BenchmarkStatus {
    /// Returns whether a scientific decision was made.
    #[must_use]
    pub const fn is_decisive(self) -> bool {
        matches!(
            self,
            Self::Passed
                | Self::Failed
                | Self::NotApplicable
        )
    }
}

impl Default for BenchmarkStatus {
    fn default() -> Self {
        Self::Inconclusive
    }
}

