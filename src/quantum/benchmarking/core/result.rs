/// Current canonical benchmark-result schema version.
///
/// Increment this when the serialized meaning of the result envelope changes
/// incompatibly.
pub const BENCHMARK_RESULT_SCHEMA_VERSION: u16 = 1;

/// Stable machine-readable schema identifier.
pub const BENCHMARK_RESULT_SCHEMA_ID: &str =
    "zamani.quantum.benchmark.result";

/// Maximum result identifier length in bytes.
pub const MAX_RESULT_ID_LENGTH: usize = 256;

/// Maximum benchmark identifier length in bytes.
///
/// This is deliberately bounded independently of the benchmark registry.
pub const MAX_BENCHMARK_ID_LENGTH: usize = 256;

/// Maximum benchmark version length.
pub const MAX_BENCHMARK_VERSION_LENGTH: usize = 128;

/// Maximum number of metrics in one result.
pub const MAX_RESULT_METRICS: usize = 16_384;

/// Maximum number of observations in one result.
pub const MAX_RESULT_OBSERVATIONS: usize = 16_384;

/// Maximum number of warnings in one result.
pub const MAX_RESULT_WARNINGS: usize = 4_096;

/// Maximum number of errors in one result.
pub const MAX_RESULT_ERRORS: usize = 4_096;

/// Maximum warning/error message length.
pub const MAX_RESULT_MESSAGE_LENGTH: usize = 16 * 1024;

/// Maximum number of result tags.
pub const MAX_RESULT_TAGS: usize = 256;

/// Maximum result tag length.
pub const MAX_RESULT_TAG_LENGTH: usize = 256;

