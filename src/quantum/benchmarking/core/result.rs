/// Errors produced by the canonical benchmark-result boundary.
#[derive(Debug, Clone, PartialEq)]
pub enum ResultError {
    /// Result schema version is unsupported.
    UnsupportedSchemaVersion {
        found: u16,
        supported: u16,
    },

    /// Result schema identifier is incorrect.
    InvalidSchemaId {
        expected: &'static str,
        found: String,
    },

    /// A bounded identifier/message field is invalid.
    InvalidIdentifier {
        field: &'static str,
        reason: &'static str,
    },

    /// A bounded string field is invalid.
    InvalidString {
        field: &'static str,
        reason: &'static str,
    },

    /// A result message is invalid.
    InvalidMessage {
        field: &'static str,
        reason: &'static str,
    },

    /// A metric failed validation.
    InvalidMetric {
        reason: String,
    },

    /// An observation failed validation.
    InvalidObservation {
        reason: String,
    },

    /// Provenance failed validation.
    InvalidProvenance {
        reason: String,
    },

    /// Two metrics have the same result identity.
    DuplicateMetric,

    /// Two observations have the same result identity.
    DuplicateObservation,

    /// Two tags are identical.
    DuplicateTag,

    /// A collection exceeded its production limit.
    LimitExceeded {
        resource: &'static str,
        requested: usize,
        maximum: usize,
    },

    /// Execution accounting is internally inconsistent.
    InconsistentExecution {
        reason: &'static str,
    },

    /// A duration is invalid.
    InvalidDuration {
        field: &'static str,
    },

    /// A floating-point value is not finite.
    NonFiniteValue {
        field: &'static str,
    },

    /// A probability/statistical value is outside the permitted domain.
    InvalidProbability {
        field: &'static str,
        value: f64,
    },

    /// Confidence level must be in `(0, 1)`.
    InvalidConfidenceLevel {
        field: &'static str,
        value: f64,
    },

    /// A completed result has no scientific content.
    EmptyResultContent,
}

impl fmt::Display for ResultError {
    fn fmt(
        &self,
        formatter: &mut fmt::Formatter<'_>,
    ) -> fmt::Result {
        match self {
            Self::UnsupportedSchemaVersion {
                found,
                supported,
            } => write!(
                formatter,
                "unsupported benchmark-result schema version {found}; \
                 supported version is {supported}"
            ),

            Self::InvalidSchemaId { expected, found } => {
                write!(
                    formatter,
                    "invalid benchmark-result schema ID '{found}'; \
                     expected '{expected}'"
                )
            }

            Self::InvalidIdentifier { field, reason } => {
                write!(formatter, "invalid {field}: {reason}")
            }

            Self::InvalidString { field, reason } => {
                write!(formatter, "invalid {field}: {reason}")
            }

            Self::InvalidMessage { field, reason } => {
                write!(formatter, "invalid result message {field}: {reason}")
            }

            Self::InvalidMetric { reason } => {
                write!(formatter, "invalid benchmark metric: {reason}")
            }

            Self::InvalidObservation { reason } => {
                write!(
                    formatter,
                    "invalid benchmark observation: {reason}"
                )
            }

            Self::InvalidProvenance { reason } => {
                write!(
                    formatter,
                    "invalid benchmark provenance: {reason}"
                )
            }

            Self::DuplicateMetric => {
                write!(
                    formatter,
                    "benchmark result contains duplicate metric identities"
                )
            }

            Self::DuplicateObservation => {
                write!(
                    formatter,
                    "benchmark result contains duplicate observation identities"
                )
            }

            Self::DuplicateTag => {
                write!(
                    formatter,
                    "benchmark result contains duplicate tags"
                )
            }

            Self::LimitExceeded {
                resource,
                requested,
                maximum,
            } => write!(
                formatter,
                "result resource '{resource}' exceeds limit: \
                 requested {requested}, maximum {maximum}"
            ),

            Self::InconsistentExecution { reason } => {
                write!(formatter, "inconsistent benchmark execution: {reason}")
            }

            Self::InvalidDuration { field } => {
                write!(formatter, "{field} contains an invalid duration")
            }

            Self::NonFiniteValue { field } => {
                write!(formatter, "{field} must be finite")
            }

            Self::InvalidProbability { field, value } => {
                write!(
                    formatter,
                    "{field} must be in [0, 1], got {value}"
                )
            }

            Self::InvalidConfidenceLevel { field, value } => {
                write!(
                    formatter,
                    "{field} must be in (0, 1), got {value}"
                )
            }

            Self::EmptyResultContent => {
                write!(
                    formatter,
                    "completed benchmark result contains neither \
                     metrics nor observations"
                )
            }
        }
    }
}

