/// Severity of a structured result message.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Hash,
    Serialize,
    Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum ResultMessageSeverity {
    /// Informational message.
    Info,

    /// Warning that does not invalidate the result.
    Warning,

    /// Error indicating a result/execution problem.
    Error,
}

/// Structured warning/error information.
///
/// Messages are retained in the result rather than printed or logged by the
/// result model.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ResultMessage {
    /// Severity.
    pub severity: ResultMessageSeverity,

    /// Stable machine-readable message code.
    pub code: String,

    /// Human-readable message.
    pub message: String,

    /// Optional workload/circuit identifier.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub scope: Option<String>,
}

impl ResultMessage {
    /// Creates a validated message.
    pub fn new(
        severity: ResultMessageSeverity,
        code: impl Into<String>,
        message: impl Into<String>,
    ) -> Result<Self, ResultError> {
        let value = Self {
            severity,
            code: code.into(),
            message: message.into(),
            scope: None,
        };

        value.validate()?;

        Ok(value)
    }

    /// Associates the message with a workload/circuit scope.
    pub fn with_scope(
        mut self,
        scope: impl Into<String>,
    ) -> Result<Self, ResultError> {
        let scope = scope.into();

        if scope.trim().is_empty() {
            return Err(ResultError::InvalidMessage {
                field: "scope",
                reason: "scope must not be empty",
            });
        }

        self.scope = Some(scope);
        self.validate()?;

        Ok(self)
    }

    /// Validates the message.
    pub fn validate(&self) -> Result<(), ResultError> {
        validate_identifier(
            "message.code",
            &self.code,
            MAX_RESULT_MESSAGE_LENGTH,
        )?;

        validate_non_empty_bounded(
            "message.message",
            &self.message,
            MAX_RESULT_MESSAGE_LENGTH,
        )?;

        if let Some(scope) = &self.scope {
            validate_non_empty_bounded(
                "message.scope",
                scope,
                MAX_RESULT_MESSAGE_LENGTH,
            )?;
        }

        Ok(())
    }
}

