/// Statistical information attached to a benchmark result.
///
/// Protocol-specific fitting remains outside this structure. This is only the
/// common result envelope for statistical validity metadata.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ResultStatistics {
    /// Number of observations/samples used in the principal analysis.
    pub sample_count: u64,

    /// Optional confidence level in `(0, 1)`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub confidence_level: Option<f64>,

    /// Statistical interval method, e.g. `wilson`, `bootstrap`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub interval_method: Option<String>,

    /// Optional goodness-of-fit statistic.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub goodness_of_fit: Option<f64>,

    /// Optional p-value.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub p_value: Option<f64>,

    /// Whether the principal statistical analysis was considered valid.
    pub analysis_valid: bool,
}

impl Default for ResultStatistics {
    fn default() -> Self {
        Self {
            sample_count: 0,
            confidence_level: None,
            interval_method: None,
            goodness_of_fit: None,
            p_value: None,
            analysis_valid: false,
        }
    }
}

impl ResultStatistics {
    /// Validates statistical metadata.
    pub fn validate(&self) -> Result<(), ResultError> {
        if let Some(confidence) = self.confidence_level {
            validate_unit_interval_open(
                "statistics.confidence_level",
                confidence,
            )?;
        }

        if let Some(gof) = self.goodness_of_fit {
            validate_finite(
                "statistics.goodness_of_fit",
                gof,
            )?;
        }

        if let Some(p_value) = self.p_value {
            validate_unit_interval_closed(
                "statistics.p_value",
                p_value,
            )?;
        }

        if let Some(method) = &self.interval_method {
            validate_non_empty_bounded(
                "statistics.interval_method",
                method,
                256,
            )?;
        }

        Ok(())
    }
}

