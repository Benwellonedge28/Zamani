/// Stable identity of the benchmark protocol that produced a result.
///
/// This intentionally remains local to the result envelope instead of
/// depending on the registry. Registry metadata can be unavailable when a
/// result is deserialized years later.
#[derive(
    Debug,
    Clone,
    PartialEq,
    Eq,
    PartialOrd,
    Ord,
    Hash,
    Serialize,
    Deserialize,
)]
pub struct ResultBenchmarkIdentity {
    /// Stable benchmark protocol identifier.
    pub benchmark_id: String,

    /// Protocol/schema version used for this result.
    pub benchmark_version: String,
}

impl ResultBenchmarkIdentity {
    /// Creates a validated benchmark identity.
    pub fn new(
        benchmark_id: impl Into<String>,
        benchmark_version: impl Into<String>,
    ) -> Result<Self, ResultError> {
        let identity = Self {
            benchmark_id: benchmark_id.into(),
            benchmark_version: benchmark_version.into(),
        };

        identity.validate()?;

        Ok(identity)
    }

    /// Validates the identity.
    pub fn validate(&self) -> Result<(), ResultError> {
        validate_identifier(
            "benchmark_id",
            &self.benchmark_id,
            MAX_BENCHMARK_ID_LENGTH,
        )?;

        validate_non_empty_bounded(
            "benchmark_version",
            &self.benchmark_version,
            MAX_BENCHMARK_VERSION_LENGTH,
        )
    }
}

// =============================================================================
// Execution status
// =============================================================================

/// Execution state recorded in a benchmark result.
///
/// This describes execution completeness, not scientific benchmark success.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Hash,
    Serialize,
    Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum ResultExecutionStatus {
    /// No execution was attempted.
    NotExecuted,

    /// Execution is represented by a partial/intermediate artifact.
    Running,

    /// All requested workload items completed successfully.
    Completed,

    /// Execution completed but one or more workload items failed.
    PartiallyCompleted,

    /// Execution was cancelled.
    Cancelled,

    /// Execution failed before producing a complete result.
    Failed,
}

impl ResultExecutionStatus {
    /// Returns whether the execution is terminal.
    #[must_use]
    pub const fn is_terminal(self) -> bool {
        matches!(
            self,
            Self::NotExecuted
                | Self::Completed
                | Self::PartiallyCompleted
                | Self::Cancelled
                | Self::Failed
        )
    }

    /// Returns whether execution produced all requested observations.
    #[must_use]
    pub const fn is_complete(self) -> bool {
        matches!(self, Self::Completed)
    }

    /// Returns whether the result contains only partial execution.
    #[must_use]
    pub const fn is_partial(self) -> bool {
        matches!(
            self,
            Self::Running | Self::PartiallyCompleted
        )
    }

    /// Returns whether execution itself failed.
    #[must_use]
    pub const fn is_failure(self) -> bool {
        matches!(
            self,
            Self::Cancelled
                | Self::PartiallyCompleted
                | Self::Failed
        )
    }
}

impl Default for ResultExecutionStatus {
    fn default() -> Self {
        Self::NotExecuted
    }
}

