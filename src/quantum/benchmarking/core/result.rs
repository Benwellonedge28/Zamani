/// Execution accounting information.
///
/// This records what actually happened without duplicating backend execution
/// objects.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Serialize,
    Deserialize,
)]
pub struct ResultExecutionSummary {
    /// Number of workload items requested.
    pub requested_workloads: u64,

    /// Number of workload items completed successfully.
    pub completed_workloads: u64,

    /// Number of workload items that failed.
    pub failed_workloads: u64,

    /// Number of workload items cancelled.
    pub cancelled_workloads: u64,

    /// Total number of circuits requested.
    pub requested_circuits: u64,

    /// Total number of circuits actually executed.
    pub executed_circuits: u64,

    /// Total requested shots.
    pub requested_shots: u64,

    /// Total executed shots.
    pub executed_shots: u64,

    /// Total execution wall time, excluding compilation unless the executor
    /// explicitly defines otherwise.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub execution_time: Option<Duration>,

    /// End-to-end wall time when measured.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub total_wall_time: Option<Duration>,
}

impl Default for ResultExecutionSummary {
    fn default() -> Self {
        Self {
            requested_workloads: 0,
            completed_workloads: 0,
            failed_workloads: 0,
            cancelled_workloads: 0,
            requested_circuits: 0,
            executed_circuits: 0,
            requested_shots: 0,
            executed_shots: 0,
            execution_time: None,
            total_wall_time: None,
        }
    }
}

impl ResultExecutionSummary {
    /// Validates execution accounting.
    pub fn validate(&self) -> Result<(), ResultError> {
        if self.completed_workloads
            .saturating_add(self.failed_workloads)
            .saturating_add(self.cancelled_workloads)
            > self.requested_workloads
        {
            return Err(ResultError::InconsistentExecution {
                reason: "completed + failed + cancelled workloads exceed requested workloads",
            });
        }

        if self.executed_circuits > self.requested_circuits {
            return Err(ResultError::InconsistentExecution {
                reason: "executed circuits exceed requested circuits",
            });
        }

        if self.executed_shots > self.requested_shots {
            return Err(ResultError::InconsistentExecution {
                reason: "executed shots exceed requested shots",
            });
        }

        validate_duration(
            "execution_time",
            self.execution_time,
        )?;

        validate_duration(
            "total_wall_time",
            self.total_wall_time,
        )?;

        Ok(())
    }
}

