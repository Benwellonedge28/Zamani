//! Human- and machine-readable benchmark summaries.
//!
//! # Purpose
//!
//! `summary.rs` is the presentation-level summary model for Zamani's quantum
//! benchmarking subsystem. It converts already-computed benchmark metrics and
//! validation information into a deterministic, bounded, serializable summary.
//!
//! This module deliberately does NOT:
//!
//! - execute quantum circuits;
//! - generate benchmark circuits;
//! - perform statistical inference;
//! - recompute benchmark metrics;
//! - access quantum hardware;
//! - depend on a particular quantum technology;
//! - depend on a particular benchmark protocol;
//! - depend on `core::result`.
//!
//! Those responsibilities belong to the core, execution, statistics, metrics,
//! protocol, and result layers respectively.
//!
//! # Architectural position
//!
//! ```text
//!                         Quantum Benchmark
//!                                │
//!                                ▼
//!                         BenchmarkResult
//!                                │
//!                    normalized metrics/warnings
//!                                │
//!                                ▼
//!                  reporting::summary::BenchmarkSummary
//!                         │             │
//!              ┌──────────┘             └──────────┐
//!              ▼                                   ▼
//!        reporting::report                  markdown/json/csv
//!        reporting orchestration            serializers
//! ```
//!
//! The important dependency direction is:
//!
//! ```text
//! core::metric ───────► reporting::summary
//!                         ▲
//!                         │
//! core::result ──adapter──┘
//! ```
//!
//! `summary.rs` must never depend on `report.rs`, protocol implementations,
//! execution backends, or the Zamani runtime.
//!
//! # Integration contract
//!
//! The stable integration point is:
//!
//! [`BenchmarkSummary::from_metrics`]
//!
//! and the [`SummaryInput`] builder.
//!
//! A future `report.rs` or `core::result` implementation can construct a
//! `SummaryInput` from `BenchmarkResult` without modifying this file.
//!
//! # Determinism
//!
//! Summary output is deterministic:
//!
//! - metric order is preserved from the supplied input;
//! - duplicate metric IDs are rejected;
//! - warnings and recommendations retain insertion order;
//! - no `HashMap` is used for externally visible ordering;
//! - floating-point values are rejected when non-finite;
//! - no timestamps are generated by this module;
//! - no random values are generated by this module.
//!
//! # Resource safety
//!
//! This module does not allocate based on untrusted quantum-result dimensions
//! without bounds. The configurable limits are applied to:
//!
//! - number of metrics;
//! - number of warnings;
//! - number of recommendations;
//! - identifier lengths;
//! - textual field lengths.
//!
//! # Rust compatibility
//!
//! Designed for Rust 1.97 / Rust 1.97.1.
//!
//! # Serialization
//!
//! `serde` is used because it is already part of Zamani's benchmarking
//! foundation. JSON serialization itself belongs in `reporting::json`.
//!
//! # Integration with `core::metric`
//!
//! The canonical metric representation is:
//!
//! `quantum::benchmarking::core::metric::Metric`
//!
//! That type already carries semantic kind, unit, value, uncertainty,
//! confidence, sample counts, quality, direction, provenance and metadata.
//! This module consumes those fields; it does not duplicate them.
//!
//! See also:
//!
//! - `core::metric`
//! - `core::result`
//! - `reporting::report`
//! - `reporting::json`
//! - `reporting::markdown`
//! - `reporting::csv`
//! - `analysis::compare`
//! - `analysis::baseline`
//! - `analysis::regression`
//! - `validation::statistical`
//! - `validation::physical`

use serde::{Deserialize, Serialize};
use std::fmt;

