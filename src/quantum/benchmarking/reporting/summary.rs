/// Configuration controlling summary resource bounds.
///
/// The defaults are intentionally conservative enough for a library API while
/// still allowing large application benchmark suites.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct SummaryLimits {
    /// Maximum number of metrics.
    pub max_metrics: usize,

    /// Maximum number of findings.
    pub max_findings: usize,

    /// Maximum number of recommendations.
    pub max_recommendations: usize,

    /// Maximum identifier length.
    pub max_identifier_length: usize,

    /// Maximum human-readable text length.
    pub max_text_length: usize,
}

impl Default for SummaryLimits {
    fn default() -> Self {
        Self {
            max_metrics: DEFAULT_MAX_METRICS,
            max_findings: DEFAULT_MAX_WARNINGS,
            max_recommendations: DEFAULT_MAX_RECOMMENDATIONS,
            max_identifier_length: DEFAULT_MAX_IDENTIFIER_LENGTH,
            max_text_length: DEFAULT_MAX_TEXT_LENGTH,
        }
    }
}

impl SummaryLimits {
    /// Validates the limits themselves.
    pub fn validate(&self) -> SummaryResult<()> {
        if self.max_metrics == 0 {
            return Err(SummaryError::InvalidLimit {
                field: "max_metrics",
            });
        }

        if self.max_findings == 0 {
            return Err(SummaryError::InvalidLimit {
                field: "max_findings",
            });
        }

        if self.max_recommendations == 0 {
            return Err(SummaryError::InvalidLimit {
                field: "max_recommendations",
            });
        }

        if self.max_identifier_length == 0 {
            return Err(SummaryError::InvalidLimit {
                field: "max_identifier_length",
            });
        }

        if self.max_text_length == 0 {
            return Err(SummaryError::InvalidLimit {
                field: "max_text_length",
            });
        }

        Ok(())
    }
}

/// Input used to build a [`BenchmarkSummary`].
///
/// This is the primary integration boundary for `report.rs`.
///
/// A future `BenchmarkResult` adapter should populate this structure and call
/// [`BenchmarkSummary::from_input`]. No changes to this module should then be
/// necessary when `core::result` evolves.
#[derive(Debug, Clone)]
pub struct SummaryInput {
    /// Benchmark identity.
    pub identity: SummaryIdentity,

    /// Final benchmark status.
    pub status: SummaryStatus,

    /// Optional concise headline supplied by the protocol/analyzer.
    pub headline: Option<String>,

    /// Optional detailed description.
    pub description: Option<String>,

    /// Canonical metrics.
    pub metrics: Vec<Metric>,

    /// Validation/execution/analysis findings.
    pub findings: Vec<SummaryFinding>,

    /// Optional execution environment.
    pub environment: SummaryEnvironment,

    /// Optional explicit recommendations.
    pub recommendations: Vec<String>,

    /// Summary resource limits.
    pub limits: SummaryLimits,
}

impl SummaryInput {
    /// Creates the minimum valid input.
    pub fn new(
        identity: SummaryIdentity,
        status: SummaryStatus,
        metrics: Vec<Metric>,
    ) -> Self {
        Self {
            identity,
            status,
            headline: None,
            description: None,
            metrics,
            findings: Vec::new(),
            environment: SummaryEnvironment::default(),
            recommendations: Vec::new(),
            limits: SummaryLimits::default(),
        }
    }

    /// Sets the headline.
    pub fn with_headline(mut self, headline: impl Into<String>) -> SummaryResult<Self> {
        let headline = headline.into();
        validate_text("headline", &headline)?;
        self.headline = Some(headline);
        Ok(self)
    }

    /// Sets the description.
    pub fn with_description(
        mut self,
        description: impl Into<String>,
    ) -> SummaryResult<Self> {
        let description = description.into();
        validate_text("description", &description)?;
        self.description = Some(description);
        Ok(self)
    }

    /// Sets findings.
    pub fn with_findings(mut self, findings: Vec<SummaryFinding>) -> Self {
        self.findings = findings;
        self
    }

    /// Sets the environment.
    pub fn with_environment(mut self, environment: SummaryEnvironment) -> Self {
        self.environment = environment;
        self
    }

    /// Sets explicit recommendations.
    pub fn with_recommendations(
        mut self,
        recommendations: Vec<String>,
    ) -> SummaryResult<Self> {
        for recommendation in &recommendations {
            validate_text("recommendation", recommendation)?;
        }

        self.recommendations = recommendations;
        Ok(self)
    }

    /// Sets resource limits.
    pub fn with_limits(mut self, limits: SummaryLimits) -> SummaryResult<Self> {
        limits.validate()?;
        self.limits = limits;
        Ok(self)
    }
}

/// Canonical benchmark summary.
///
/// This is the primary output of this module.
///
/// It is deliberately smaller than a complete `BenchmarkResult`. The result
/// contains scientific observations and provenance; the summary contains the
/// decision-ready view of those results.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BenchmarkSummary {
    /// Summary schema version.
    pub schema_version: String,

    /// Benchmark identity.
    pub identity: SummaryIdentity,

    /// Overall benchmark status.
    pub status: SummaryStatus,

    /// Human-readable headline.
    pub headline: String,

    /// Optional detailed description.
    pub description: Option<String>,

    /// Metrics selected for summary presentation.
    pub metrics: Vec<SummaryMetric>,

    /// Validation and execution findings.
    pub findings: Vec<SummaryFinding>,

    /// Execution environment.
    pub environment: SummaryEnvironment,

    /// Recommendations generated or supplied by the analysis layer.
    pub recommendations: Vec<String>,

    /// Number of metrics represented.
    pub metric_count: usize,

    /// Number of findings represented.
    pub finding_count: usize,

    /// Number of error-severity findings.
    pub error_count: usize,

    /// Number of warning-severity findings.
    pub warning_count: usize,

    /// Number of informational findings.
    pub info_count: usize,

    /// Whether the summary represents a successful benchmark completion.
    pub successful: bool,
}

impl BenchmarkSummary {
    /// Builds a summary from a normalized [`SummaryInput`].
    ///
    /// This is the preferred construction path.
    pub fn from_input(input: SummaryInput) -> SummaryResult<Self> {
        input.limits.validate()?;

        validate_identity(&input.identity)?;

        if let Some(ref headline) = input.headline {
            validate_text_with_limit(
                "headline",
                headline,
                input.limits.max_text_length,
            )?;
        }

        if let Some(ref description) = input.description {
            validate_text_with_limit(
                "description",
                description,
                input.limits.max_text_length,
            )?;
        }

        if input.metrics.len() > input.limits.max_metrics {
            return Err(SummaryError::LimitExceeded {
                field: "metrics",
                limit: input.limits.max_metrics,
                actual: input.metrics.len(),
            });
        }

        if input.findings.len() > input.limits.max_findings {
            return Err(SummaryError::LimitExceeded {
                field: "findings",
                limit: input.limits.max_findings,
                actual: input.findings.len(),
            });
        }

        if input.recommendations.len() > input.limits.max_recommendations {
            return Err(SummaryError::LimitExceeded {
                field: "recommendations",
                limit: input.limits.max_recommendations,
                actual: input.recommendations.len(),
            });
        }

        let mut metrics = Vec::with_capacity(input.metrics.len());
        let mut seen_metric_ids: Vec<String> = Vec::with_capacity(input.metrics.len());

        for metric in &input.metrics {
            let summary_metric = SummaryMetric::from_metric(metric)?;

            if seen_metric_ids
                .iter()
                .any(|existing| existing == &summary_metric.id)
            {
                return Err(SummaryError::DuplicateMetric {
                    metric_id: summary_metric.id,
                });
            }

            seen_metric_ids.push(summary_metric.id.clone());
            metrics.push(summary_metric);
        }

        validate_findings(&input.findings, &input.limits)?;
        validate_recommendations(&input.recommendations, &input.limits)?;

        let finding_count = input.findings.len();

        let error_count = input
            .findings
            .iter()
            .filter(|finding| finding.severity == SummarySeverity::Error)
            .count();

        let warning_count = input
            .findings
            .iter()
            .filter(|finding| finding.severity == SummarySeverity::Warning)
            .count();

        let info_count = input
            .findings
            .iter()
            .filter(|finding| finding.severity == SummarySeverity::Info)
            .count();

        let successful = input.status.is_successful() && error_count == 0;

        let headline = input
            .headline
            .unwrap_or_else(|| generate_headline(&input.identity, input.status, &metrics));

        let recommendations = if input.recommendations.is_empty() {
            generate_recommendations(input.status, &metrics, &input.findings)
        } else {
            input.recommendations
        };

        Ok(Self {
            schema_version: SUMMARY_SCHEMA_VERSION.to_string(),
            identity: input.identity,
            status: input.status,
            headline,
            description: input.description,
            metrics,
            findings: input.findings,
            environment: input.environment,
            recommendations,
            metric_count: metrics.len(),
            finding_count,
            error_count,
            warning_count,
            info_count,
            successful,
        })
    }

    /// Convenience constructor for consumers that already have canonical
    /// metrics and do not yet have a `BenchmarkResult` adapter.
    pub fn from_metrics(
        benchmark_id: impl Into<String>,
        status: SummaryStatus,
        metrics: Vec<Metric>,
    ) -> SummaryResult<Self> {
        let identity = SummaryIdentity::new(benchmark_id)?;
        let input = SummaryInput::new(identity, status, metrics);
        Self::from_input(input)
    }

    /// Adds a finding without mutating the canonical summary in an invalid
    /// state.
    ///
    /// This method returns a new validated summary. It is useful for report
    /// adapters that discover presentation-level warnings after construction.
    pub fn with_finding(mut self, finding: SummaryFinding) -> SummaryResult<Self> {
        self.findings.push(finding);

        if self.findings.len() > DEFAULT_MAX_WARNINGS {
            return Err(SummaryError::LimitExceeded {
                field: "findings",
                limit: DEFAULT_MAX_WARNINGS,
                actual: self.findings.len(),
            });
        }

        self.recalculate_counters();
        Ok(self)
    }

    /// Returns a metric by its stable ID.
    pub fn metric(&self, metric_id: &str) -> Option<&SummaryMetric> {
        self.metrics.iter().find(|metric| metric.id == metric_id)
    }

    /// Returns all metrics with a given direction.
    pub fn metrics_with_direction(
        &self,
        direction: MetricDirection,
    ) -> Vec<&SummaryMetric> {
        self.metrics
            .iter()
            .filter(|metric| metric.direction == direction)
            .collect()
    }

    /// Returns whether a metric exists.
    pub fn contains_metric(&self, metric_id: &str) -> bool {
        self.metric(metric_id).is_some()
    }

    /// Returns the highest-quality metric classification present.
    ///
    /// Quality is ordered conservatively:
    ///
    /// Observed > Derived > Estimated > Fitted > Approximate > Uncertain >
    /// Invalid.
    pub fn minimum_quality(&self) -> Option<MetricQuality> {
        self.metrics
            .iter()
            .map(|metric| metric.quality)
            .min_by_key(metric_quality_rank)
    }

    /// Returns whether the summary contains invalid metrics.
    pub fn has_invalid_metrics(&self) -> bool {
        self.metrics
            .iter()
            .any(|metric| metric.quality == MetricQuality::Invalid)
    }

    /// Returns whether the summary contains warning or error findings.
    pub fn has_findings(&self) -> bool {
        !self.findings.is_empty()
    }

    /// Returns the number of metrics with confidence intervals.
    pub fn metrics_with_confidence(&self) -> usize {
        self.metrics
            .iter()
            .filter(|metric| metric.confidence.is_some())
            .count()
    }

    /// Returns a concise one-line representation.
    ///
    /// This method does not perform serialization and is safe for CLI/logging
    /// use.
    pub fn one_line(&self) -> String {
        format!(
            "{} [{}] metrics={} findings={} successful={}",
            self.identity.benchmark_id,
            self.status.id(),
            self.metric_count,
            self.finding_count,
            self.successful
        )
    }

    /// Produces deterministic Markdown suitable for GitHub/CI reports.
    ///
    /// This method intentionally lives here because Markdown summary rendering
    /// requires only the summary model. The dedicated `reporting::markdown`
    /// module can call this method or provide richer document composition.
    pub fn to_markdown(&self) -> String {
        let mut output = String::new();

        output.push_str("# Benchmark Summary\n\n");

        output.push_str("## Overview\n\n");
        output.push_str("| Field | Value |\n");
        output.push_str("|---|---|\n");
        output.push_str(&format!(
            "| Benchmark | `{}` |\n",
            escape_markdown(&self.identity.benchmark_id)
        ));
        output.push_str(&format!(
            "| Status | `{}` |\n",
            self.status.id()
        ));
        output.push_str(&format!(
            "| Successful | `{}` |\n",
            self.successful
        ));
        output.push_str(&format!(
            "| Metrics | {} |\n",
            self.metric_count
        ));
        output.push_str(&format!(
            "| Findings | {} |\n",
            self.finding_count
        ));

        if let Some(ref version) = self.identity.benchmark_version {
            output.push_str(&format!(
                "| Benchmark version | `{}` |\n",
                escape_markdown(version)
            ));
        }

        if let Some(ref experiment_id) = self.identity.experiment_id {
            output.push_str(&format!(
                "| Experiment | `{}` |\n",
                escape_markdown(experiment_id)
            ));
        }

        output.push('\n');

        output.push_str("## Headline\n\n");
        output.push_str(&self.headline);
        output.push_str("\n\n");

        if let Some(ref description) = self.description {
            output.push_str("## Description\n\n");
            output.push_str(description);
            output.push_str("\n\n");
        }

        if !self.metrics.is_empty() {
            output.push_str("## Metrics\n\n");
            output.push_str(
                "| Metric | Value | Unit | Quality | Uncertainty | Confidence |\n",
            );
            output.push_str(
                "|---|---:|---|---|---:|---|\n",
            );

            for metric in &self.metrics {
                let uncertainty = metric
                    .uncertainty
                    .map(format_f64)
                    .unwrap_or_else(|| "—".to_string());

                let confidence = metric
                    .confidence
                    .as_ref()
                    .map(format_confidence)
                    .unwrap_or_else(|| "—".to_string());

                output.push_str(&format!(
                    "| {} | {} | `{}` | `{}` | {} | {} |\n",
                    escape_markdown(&metric.name),
                    format_f64(metric.value),
                    escape_markdown(&metric.unit),
                    quality_id(metric.quality),
                    uncertainty,
                    confidence
                ));
            }

            output.push('\n');
        }

        if !self.findings.is_empty() {
            output.push_str("## Findings\n\n");

            for finding in &self.findings {
                output.push_str(&format!(
                    "- **{}** `{}`: {}",
                    finding.severity.id(),
                    escape_markdown(&finding.code),
                    finding.message
                ));

                if let Some(ref metric_id) = finding.metric_id {
                    output.push_str(&format!(
                        " (metric `{}`)",
                        escape_markdown(metric_id)
                    ));
                }

                output.push('\n');
            }

            output.push('\n');
        }

        if !self.recommendations.is_empty() {
            output.push_str("## Recommendations\n\n");

            for recommendation in &self.recommendations {
                output.push_str("- ");
                output.push_str(recommendation);
                output.push('\n');
            }

            output.push('\n');
        }

        output
    }

    /// Recomputes counters after a controlled mutation.
    fn recalculate_counters(&mut self) {
        self.finding_count = self.findings.len();

        self.error_count = self
            .findings
            .iter()
            .filter(|finding| finding.severity == SummarySeverity::Error)
            .count();

        self.warning_count = self
            .findings
            .iter()
            .filter(|finding| finding.severity == SummarySeverity::Warning)
            .count();

        self.info_count = self
            .findings
            .iter()
            .filter(|finding| finding.severity == SummarySeverity::Info)
            .count();

        self.successful = self.status.is_successful()
            && self.error_count == 0
            && !self.has_invalid_metrics();
    }
}

/// Errors produced by summary construction and validation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SummaryError {
    /// An identifier is empty.
    EmptyIdentifier {
        /// Field that was empty.
        field: &'static str,
    },

    /// Text was empty.
    EmptyText {
        /// Field that was empty.
        field: &'static str,
    },

    /// Identifier exceeded the configured limit.
    IdentifierTooLong {
        /// Field name.
        field: &'static str,

        /// Maximum permitted length.
        limit: usize,

        /// Actual length.
        actual: usize,
    },

    /// Text exceeded the configured limit.
    TextTooLong {
        /// Field name.
        field: &'static str,

        /// Maximum permitted length.
        limit: usize,

        /// Actual length.
        actual: usize,
    },

    /// A floating-point value was not finite.
    NonFiniteValue {
        /// Field name.
        field: &'static str,
    },

    /// Negative uncertainty was supplied.
    InvalidUncertainty {
        /// Invalid uncertainty.
        value: f64,
    },

    /// Confidence level is outside the open interval (0, 1).
    InvalidConfidenceLevel {
        /// Invalid confidence level.
        level: f64,
    },

    /// Confidence interval lower bound exceeds upper bound.
    InvalidConfidenceInterval {
        /// Lower bound.
        lower: f64,

        /// Upper bound.
        upper: f64,
    },

    /// A configurable limit itself is invalid.
    InvalidLimit {
        /// Field name.
        field: &'static str,
    },

    /// A configured collection limit was exceeded.
    LimitExceeded {
        /// Collection name.
        field: &'static str,

        /// Maximum permitted number of elements.
        limit: usize,

        /// Actual number of elements.
        actual: usize,
    },

    /// Two metrics have the same stable identifier.
    DuplicateMetric {
        /// Duplicate identifier.
        metric_id: String,
    },

    /// A finding has an invalid severity/code/message combination.
    InvalidFinding {
        /// Finding code.
        code: String,
    },
}

impl fmt::Display for SummaryError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyIdentifier { field } => {
                write!(formatter, "{field} must not be empty")
            }

            Self::EmptyText { field } => {
                write!(formatter, "{field} must not be empty")
            }

            Self::IdentifierTooLong {
                field,
                limit,
                actual,
            } => write!(
                formatter,
                "{field} exceeds maximum length {limit}: actual length {actual}"
            ),

            Self::TextTooLong {
                field,
                limit,
                actual,
            } => write!(
                formatter,
                "{field} exceeds maximum length {limit}: actual length {actual}"
            ),

            Self::NonFiniteValue { field } => {
                write!(formatter, "{field} must be finite")
            }

            Self::InvalidUncertainty { value } => {
                write!(formatter, "uncertainty must be non-negative: {value}")
            }

            Self::InvalidConfidenceLevel { level } => {
                write!(
                    formatter,
                    "confidence level must be strictly between 0 and 1: {level}"
                )
            }

            Self::InvalidConfidenceInterval { lower, upper } => {
                write!(
                    formatter,
                    "confidence interval is invalid: lower={lower}, upper={upper}"
                )
            }

            Self::InvalidLimit { field } => {
                write!(formatter, "{field} must be greater than zero")
            }

            Self::LimitExceeded {
                field,
                limit,
                actual,
            } => write!(
                formatter,
                "{field} exceeds configured limit {limit}: actual {actual}"
            ),

            Self::DuplicateMetric { metric_id } => {
                write!(formatter, "duplicate metric identifier: {metric_id}")
            }

            Self::InvalidFinding { code } => {
                write!(formatter, "invalid benchmark finding: {code}")
            }
        }
    }
}

impl std::error::Error for SummaryError {}

/// Validates a benchmark identity.
fn validate_identity(identity: &SummaryIdentity) -> SummaryResult<()> {
    validate_identifier("benchmark_id", &identity.benchmark_id)?;

    if let Some(ref value) = identity.benchmark_version {
        validate_identifier("benchmark_version", value)?;
    }

    if let Some(ref value) = identity.experiment_id {
        validate_identifier("experiment_id", value)?;
    }

    if let Some(ref value) = identity.workload_id {
        validate_identifier("workload_id", value)?;
    }

    Ok(())
}

/// Validates findings.
fn validate_findings(
    findings: &[SummaryFinding],
    limits: &SummaryLimits,
) -> SummaryResult<()> {
    if findings.len() > limits.max_findings {
        return Err(SummaryError::LimitExceeded {
            field: "findings",
            limit: limits.max_findings,
            actual: findings.len(),
        });
    }

    for finding in findings {
        validate_identifier_with_limit(
            "finding.code",
            &finding.code,
            limits.max_identifier_length,
        )?;

        validate_text_with_limit(
            "finding.message",
            &finding.message,
            limits.max_text_length,
        )?;

        if let Some(ref metric_id) = finding.metric_id {
            validate_identifier_with_limit(
                "finding.metric_id",
                metric_id,
                limits.max_identifier_length,
            )?;
        }
    }

    Ok(())
}

/// Validates recommendations.
fn validate_recommendations(
    recommendations: &[String],
    limits: &SummaryLimits,
) -> SummaryResult<()> {
    if recommendations.len() > limits.max_recommendations {
        return Err(SummaryError::LimitExceeded {
            field: "recommendations",
            limit: limits.max_recommendations,
            actual: recommendations.len(),
        });
    }

    for recommendation in recommendations {
        validate_text_with_limit(
            "recommendation",
            recommendation,
            limits.max_text_length,
        )?;
    }

    Ok(())
}

/// Generates a conservative default headline.
///
/// Protocol-specific analysis should provide a richer headline when one is
/// available. This fallback never makes scientific claims that are not encoded
/// in the supplied status.
fn generate_headline(
    identity: &SummaryIdentity,
    status: SummaryStatus,
    metrics: &[SummaryMetric],
) -> String {
    match status {
        SummaryStatus::Complete => format!(
            "{} completed successfully with {} reported metric{}.",
            identity.benchmark_id,
            metrics.len(),
            plural_suffix(metrics.len())
        ),

        SummaryStatus::CompleteWithWarnings => format!(
            "{} completed with warnings and {} reported metric{}.",
            identity.benchmark_id,
            metrics.len(),
            plural_suffix(metrics.len())
        ),

        SummaryStatus::Failed => {
            format!("{} failed.", identity.benchmark_id)
        }

        SummaryStatus::Inconclusive => {
            format!("{} produced an inconclusive result.", identity.benchmark_id)
        }

        SummaryStatus::NotApplicable => {
            format!("{} is not applicable to the selected target.", identity.benchmark_id)
        }

        SummaryStatus::Cancelled => {
            format!("{} was cancelled before completion.", identity.benchmark_id)
        }

        SummaryStatus::TimedOut => {
            format!("{} exceeded its execution deadline.", identity.benchmark_id)
        }
    }
}

/// Generates conservative recommendations from summary-level evidence.
///
/// This deliberately avoids domain-specific scientific conclusions. Protocol
/// analyzers should supply protocol-specific recommendations through
/// `SummaryInput::with_recommendations`.
fn generate_recommendations(
    status: SummaryStatus,
    metrics: &[SummaryMetric],
    findings: &[SummaryFinding],
) -> Vec<String> {
    let mut recommendations = Vec::new();

    if matches!(status, SummaryStatus::Failed | SummaryStatus::TimedOut) {
        recommendations.push(
            "Inspect execution and validation findings before comparing this result with a baseline."
                .to_string(),
        );
    }

    if matches!(status, SummaryStatus::Cancelled) {
        recommendations.push(
            "Re-run the benchmark if a complete measurement is required.".to_string(),
        );
    }

    if matches!(status, SummaryStatus::Inconclusive) {
        recommendations.push(
            "Increase or correct the available evidence before making a performance comparison."
                .to_string(),
        );
    }

    if metrics.iter().any(|metric| {
        matches!(
            metric.quality,
            MetricQuality::Uncertain | MetricQuality::Invalid
        )
    }) {
        recommendations.push(
            "Review uncertain or invalid metrics before using the summary for regression decisions."
                .to_string(),
        );
    }

    if metrics.iter().any(|metric| metric.confidence.is_none()) {
        recommendations.push(
            "Metrics without confidence information should not be treated as statistically equivalent to metrics with explicit uncertainty."
                .to_string(),
        );
    }

    if findings
        .iter()
        .any(|finding| finding.severity == SummarySeverity::Warning)
    {
        recommendations.push(
            "Review benchmark warnings and preserve them with any exported result."
                .to_string(),
        );
    }

    recommendations
}

