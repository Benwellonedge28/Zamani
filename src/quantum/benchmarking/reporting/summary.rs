/// Maximum number of metrics that may be placed into one summary.
///
/// This is deliberately finite so a malformed or adversarial benchmark result
/// cannot cause an unbounded reporting allocation.
pub const DEFAULT_MAX_METRICS: usize = 4_096;

/// Maximum number of warnings in a summary.
pub const DEFAULT_MAX_WARNINGS: usize = 1_024;

/// Maximum number of recommendations in a summary.
pub const DEFAULT_MAX_RECOMMENDATIONS: usize = 512;

/// Maximum length of a benchmark identifier.
pub const DEFAULT_MAX_IDENTIFIER_LENGTH: usize = 512;

/// Maximum length of a human-readable summary field.
pub const DEFAULT_MAX_TEXT_LENGTH: usize = 16 * 1024;

/// Current summary schema version.
///
/// This is independent from the benchmark protocol version and from the
/// repository/package version.
pub const SUMMARY_SCHEMA_VERSION: &str = "1.0";

/// Result type used by summary construction and validation.
pub type SummaryResult<T> = Result<T, SummaryError>;

/// Severity of a summary finding.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SummarySeverity {
    /// Informational finding.
    Info,

    /// Something requires attention but does not invalidate the result.
    Warning,

    /// The summary or underlying benchmark result cannot be trusted.
    Error,
}

impl SummarySeverity {
    /// Returns a stable machine-readable identifier.
    pub const fn id(self) -> &'static str {
        match self {
            Self::Info => "info",
            Self::Warning => "warning",
            Self::Error => "error",
        }
    }
}

/// Overall status of a benchmark summary.
///
/// This is deliberately separate from a benchmark protocol's pass/fail
/// semantics. For example, a benchmark can be successfully executed but fail
/// its scientific success criterion.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SummaryStatus {
    /// Benchmark completed and produced valid results.
    Complete,

    /// Benchmark completed, but some results require caution.
    CompleteWithWarnings,

    /// Benchmark execution or analysis failed.
    Failed,

    /// Benchmark did not have enough information to make a determination.
    Inconclusive,

    /// Benchmark was intentionally not applicable to the target.
    NotApplicable,

    /// Benchmark execution was cancelled.
    Cancelled,

    /// Benchmark execution exceeded its configured deadline.
    TimedOut,
}

impl SummaryStatus {
    /// Returns a stable machine-readable identifier.
    pub const fn id(self) -> &'static str {
        match self {
            Self::Complete => "complete",
            Self::CompleteWithWarnings => "complete_with_warnings",
            Self::Failed => "failed",
            Self::Inconclusive => "inconclusive",
            Self::NotApplicable => "not_applicable",
            Self::Cancelled => "cancelled",
            Self::TimedOut => "timed_out",
        }
    }

    /// Whether the status represents a usable completed benchmark.
    pub const fn is_successful(self) -> bool {
        matches!(self, Self::Complete | Self::CompleteWithWarnings)
    }

    /// Whether the status indicates that the benchmark cannot currently be
    /// treated as a valid completed measurement.
    pub const fn is_terminal_failure(self) -> bool {
        matches!(
            self,
            Self::Failed | Self::Cancelled | Self::TimedOut
        )
    }
}

/// A single summary finding.
///
/// Findings are intentionally independent of the validation subsystem. The
/// validation layer decides what happened; this type only carries the result
/// into reporting.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SummaryFinding {
    /// Finding severity.
    pub severity: SummarySeverity,

    /// Stable machine-readable code.
    pub code: String,

    /// Human-readable message.
    pub message: String,

    /// Optional metric identifier associated with the finding.
    pub metric_id: Option<String>,
}

impl SummaryFinding {
    /// Creates a finding.
    pub fn new(
        severity: SummarySeverity,
        code: impl Into<String>,
        message: impl Into<String>,
    ) -> SummaryResult<Self> {
        let code = code.into();
        let message = message.into();

        validate_identifier("finding.code", &code)?;
        validate_text("finding.message", &message)?;

        Ok(Self {
            severity,
            code,
            message,
            metric_id: None,
        })
    }

    /// Associates a finding with a metric.
    pub fn with_metric_id(mut self, metric_id: impl Into<String>) -> SummaryResult<Self> {
        let metric_id = metric_id.into();

        validate_identifier("finding.metric_id", &metric_id)?;

        self.metric_id = Some(metric_id);
        Ok(self)
    }
}

/// A concise metric entry intended for summary presentation.
///
/// The complete `Metric` remains the canonical measurement object. This type
/// intentionally contains only information useful to a summary and therefore
/// avoids leaking protocol implementation details into reporting.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SummaryMetric {
    /// Stable metric identifier.
    pub id: String,

    /// Human-readable metric name.
    pub name: String,

    /// Metric value.
    pub value: f64,

    /// Stable unit identifier.
    pub unit: String,

    /// Generic optimization direction.
    pub direction: MetricDirection,

    /// Statistical/semantic quality.
    pub quality: MetricQuality,

    /// Optional uncertainty.
    pub uncertainty: Option<f64>,

    /// Optional confidence interval.
    pub confidence: Option<SummaryConfidence>,

    /// Number of observations.
    pub sample_count: Option<u64>,

    /// Number of shots.
    pub shot_count: Option<u64>,

    /// Number of circuits.
    pub circuit_count: Option<u64>,

    /// Optional human-readable description.
    pub description: Option<String>,
}

impl SummaryMetric {
    /// Creates a summary metric from the canonical benchmark metric.
    pub fn from_metric(metric: &Metric) -> SummaryResult<Self> {
        let id = metric.kind.id();

        validate_identifier("metric.id", &id)?;

        let name = human_metric_name(&metric.kind);

        let uncertainty = metric.uncertainty.map(|value| value.get());

        if let Some(value) = uncertainty {
            validate_finite("metric.uncertainty", value)?;
            if value < 0.0 {
                return Err(SummaryError::InvalidUncertainty { value });
            }
        }

        let confidence = metric
            .confidence
            .as_ref()
            .map(SummaryConfidence::from_metric_confidence)
            .transpose()?;

        let description = metric.description.clone();

        if let Some(ref value) = description {
            validate_text("metric.description", value)?;
        }

        Ok(Self {
            id,
            name,
            value: metric.value.get(),
            unit: metric.unit.id(),
            direction: metric.direction,
            quality: metric.quality,
            uncertainty,
            confidence,
            sample_count: metric.sample_count,
            shot_count: metric.shot_count,
            circuit_count: metric.circuit_count,
            description,
        })
    }
}

/// Confidence interval representation suitable for summary output.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SummaryConfidence {
    /// Confidence level as a fraction, e.g. 0.95.
    pub level: f64,

    /// Lower confidence bound.
    pub lower: f64,

    /// Upper confidence bound.
    pub upper: f64,

    /// Stable confidence-method identifier.
    pub method: String,

    /// Width of the interval.
    pub width: f64,
}

impl SummaryConfidence {
    fn from_metric_confidence(
        confidence: &crate::quantum::benchmarking::core::metric::MetricConfidence,
    ) -> SummaryResult<Self> {
        let level = confidence.level.get();
        let lower = confidence.lower.get();
        let upper = confidence.upper.get();

        validate_finite("confidence.level", level)?;
        validate_finite("confidence.lower", lower)?;
        validate_finite("confidence.upper", upper)?;

        if !(0.0 < level && level < 1.0) {
            return Err(SummaryError::InvalidConfidenceLevel { level });
        }

        if lower > upper {
            return Err(SummaryError::InvalidConfidenceInterval { lower, upper });
        }

        let width = upper - lower;

        Ok(Self {
            level,
            lower,
            upper,
            method: confidence_method_id(&confidence.method),
            width,
        })
    }
}

