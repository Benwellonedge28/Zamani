/// Serializes a validated benchmark result to compact canonical JSON.
///
/// This function validates the result before serialization.
///
/// # Errors
///
/// Returns an error if:
///
/// - the options are invalid;
/// - the benchmark result is invalid;
/// - serialization fails;
/// - the serialized output exceeds the configured limit.
pub fn to_json(
    result: &BenchmarkResult,
) -> Result<String, JsonReportError> {
    to_json_with_options(result, JsonSerializeOptions::compact())
}

/// Serializes a validated benchmark result to pretty JSON.
///
/// Pretty output is intended for humans, GitHub reports and diagnostics.
/// It remains a complete canonical result representation.
pub fn to_json_pretty(
    result: &BenchmarkResult,
) -> Result<String, JsonReportError> {
    to_json_with_options(result, JsonSerializeOptions::pretty())
}

/// Serializes a benchmark result using explicit options.
pub fn to_json_with_options(
    result: &BenchmarkResult,
    options: JsonSerializeOptions,
) -> Result<String, JsonReportError> {
    options.validate()?;

    validate_result(result)?;

    let json = match options.format {
        JsonFormat::Compact => {
            serde_json::to_string(result)
                .map_err(JsonReportError::Serialization)?
        }

        JsonFormat::Pretty => {
            serde_json::to_string_pretty(result)
                .map_err(JsonReportError::Serialization)?
        }
    };

    ensure_output_size(json.len(), options.limits.max_output_bytes)?;

    Ok(json)
}

/// Serializes a validated benchmark result into UTF-8 JSON bytes.
pub fn to_json_bytes(
    result: &BenchmarkResult,
) -> Result<Vec<u8>, JsonReportError> {
    to_json_bytes_with_options(result, JsonSerializeOptions::compact())
}

/// Serializes a validated benchmark result into pretty UTF-8 JSON bytes.
pub fn to_json_pretty_bytes(
    result: &BenchmarkResult,
) -> Result<Vec<u8>, JsonReportError> {
    to_json_bytes_with_options(result, JsonSerializeOptions::pretty())
}

/// Serializes a benchmark result into bytes using explicit options.
pub fn to_json_bytes_with_options(
    result: &BenchmarkResult,
    options: JsonSerializeOptions,
) -> Result<Vec<u8>, JsonReportError> {
    options.validate()?;

    validate_result(result)?;

    let bytes = match options.format {
        JsonFormat::Compact => {
            serde_json::to_vec(result)
                .map_err(JsonReportError::Serialization)?
        }

        JsonFormat::Pretty => {
            serde_json::to_vec_pretty(result)
                .map_err(JsonReportError::Serialization)?
        }
    };

    ensure_output_size(
        bytes.len(),
        options.limits.max_output_bytes,
    )?;

    Ok(bytes)
}

