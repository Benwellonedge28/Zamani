//! Zamani Quantum Benchmarking — Canonical JSON Reporting
//!
//! Production-grade JSON serialization and deserialization for
//! `quantum::benchmarking::core::BenchmarkResult`.
//!
//! # Architectural role
//!
//! This module is the JSON interchange boundary for the complete Zamani
//! quantum-benchmarking result model.
//!
//! ```text
//! benchmark execution / analysis
//!             │
//!             ▼
//!     core::BenchmarkResult
//!             │
//!             ▼
//!     reporting::json
//!        ┌────┴────┐
//!        ▼         ▼
//!      JSON      JSONL
//!        │
//!        ▼
//! external tools / CI / storage / Zamani stdlib
//! ```
//!
//! This module deliberately does NOT:
//!
//! - execute quantum circuits;
//! - generate circuits;
//! - calculate metrics;
//! - perform statistical analysis;
//! - select hardware;
//! - compile or route circuits;
//! - modify benchmark results;
//! - contain protocol-specific serialization;
//! - depend on a particular backend;
//! - write files;
//! - print diagnostics;
//! - maintain global state.
//!
//! The caller owns I/O. This module converts trusted in-memory benchmark
//! results to/from JSON bytes/strings.
//!
//! # Important security invariant
//!
//! JSON received from an untrusted source is NEVER considered trusted merely
//! because `serde_json` successfully deserialized it.
//!
//! The required flow is:
//!
//! ```text
//! untrusted JSON
//!       │
//!       ▼
//! serde_json::from_...
//!       │
//!       ▼
//! BenchmarkResult::validate()
//!       │
//!       ├── failure ──► JsonReportError
//!       │
//!       ▼
//! trusted BenchmarkResult
//! ```
//!
//! This module therefore provides both:
//!
//! - raw deserialization for callers that explicitly need it;
//! - validated deserialization for normal production use.
//!
//! Production consumers should use the validated APIs.
//!
//! # Canonical representation
//!
//! JSON generated by this module is the canonical interchange representation
//! of `BenchmarkResult`.
//!
//! The canonical object contains the complete serialized result model rather
//! than a presentation-only summary. This means JSON output can be:
//!
//! - archived;
//! - independently re-read;
//! - re-validated;
//! - compared between benchmark runs;
//! - consumed by CI;
//! - imported into analysis tools;
//! - converted to CSV/Markdown by other reporting modules;
//! - used by future Zamani tooling;
//! - retained as scientific provenance.
//!
//! # Determinism
//!
//! `serde_json` serializes Rust maps according to their underlying map
//! representation. The canonical benchmark result model uses deterministic
//! collections where ordering is semantically relevant.
//!
//! This module additionally provides compact and pretty serialization.
//! Formatting is not part of the scientific identity of a result.
//!
//! Callers MUST use the result/provenance fingerprint mechanisms for scientific
//! identity rather than hashing arbitrary pretty-printed JSON.
//!
//! # Numeric safety
//!
//! JSON has a number model that is less expressive than Rust's type system.
//! In particular, JSON has no representation for:
//!
//! - NaN;
//! - positive infinity;
//! - negative infinity.
//!
//! The benchmark result model already protects metrics through its finite
//! numeric representation. This module additionally rejects serialization
//! failures rather than emitting non-standard JSON.
//!
//! # Resource safety
//!
//! JSON serialization can produce large allocations. This module therefore
//! provides:
//!
//! - configurable output-size limits;
//! - explicit byte-oriented APIs;
//! - no hidden filesystem writes;
//! - no unbounded recursive processing controlled by this module;
//! - bounded input/output convenience helpers.
//!
//! The limits here complement, rather than replace, the limits enforced by
//! `core::result` and `core::limits`.
//!
//! # JSON Lines
//!
//! Benchmark infrastructure frequently processes many independent results.
//! JSON Lines support is therefore included without introducing a streaming
//! parser dependency.
//!
//! Each JSONL record represents exactly one complete `BenchmarkResult`.
//!
//! The JSONL APIs:
//!
//! - reject blank records;
//! - validate every result;
//! - preserve record ordering;
//! - report the failing record index;
//! - never silently skip malformed records.
//!
//! # Versioning
//!
//! The result model owns the authoritative schema version:
//!
//! `core::result::BENCHMARK_RESULT_SCHEMA_VERSION`
//!
//! This module must not invent a second incompatible result schema.
//!
//! Future schema migration belongs in a dedicated migration layer. This file
//! only validates that the deserialized result is acceptable to the currently
//! linked result model.
//!
//! # Integration contract
//!
//! This file depends only on:
//!
//! - `core::result::BenchmarkResult`;
//! - `core::result::ResultError`;
//! - `serde_json`;
//! - the Rust standard library.
//!
//! It does NOT depend on:
//!
//! - protocols;
//! - generators;
//! - execution;
//! - statistics;
//! - metrics;
//! - hardware;
//! - applications;
//! - QEC;
//! - analysis;
//! - CSV reporting;
//! - Markdown reporting.
//!
//! Therefore this file can be completed before those modules are finished.
//!
//! Downstream integration is one-way:
//!
//! ```text
//! core::result
//!      │
//!      ▼
//! reporting::json
//!      │
//!      ├── reporting::csv
//!      ├── reporting::markdown
//!      ├── analysis
//!      ├── CI
//!      └── stdlib::quantum
//! ```
//!
//! `core::result` must never depend on this module.
//!
//! # Rust compatibility
//!
//! Target:
//!
//! - Rust 1.97
//! - Rust 1.97.1
//! - Rust 2021
//!
//! No nightly features.
//! No unsafe code.
//!
//! ---------------------------------------------------------------------------

