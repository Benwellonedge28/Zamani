/// Options controlling JSON deserialization.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct JsonDeserializeOptions {
    /// Resource limits.
    pub limits: JsonLimits,

    /// Whether the result must pass semantic validation before being returned.
    pub validate_result: bool,
}

impl JsonDeserializeOptions {
    /// Production-safe defaults.
    ///
    /// Validation is enabled by default because serialized benchmark results
    /// are an untrusted data boundary.
    #[must_use]
    pub const fn production() -> Self {
        Self {
            limits: JsonLimits::production(),
            validate_result: true,
        }
    }

    /// Explicitly disables semantic result validation.
    ///
    /// This is provided only for migration/debugging tools. Normal application
    /// code should not use it.
    #[must_use]
    pub const fn unvalidated() -> Self {
        Self {
            limits: JsonLimits::production(),
            validate_result: false,
        }
    }

    /// Validates the options.
    pub fn validate(&self) -> Result<(), JsonReportError> {
        self.limits.validate()
    }
}

impl Default for JsonDeserializeOptions {
    fn default() -> Self {
        Self::production()
    }
}

