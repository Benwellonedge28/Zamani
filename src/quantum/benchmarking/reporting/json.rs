/// Writes any serde-compatible value as one compact JSON document.
pub fn write_json_value<W, T>(
    writer: &mut W,
    value: &T,
) -> Result<(), JsonReportError>
where
    W: Write,
    T: Serialize + ?Sized,
{
    let json = to_value_json(value)?;
    writer.write_all(json.as_bytes())?;
    Ok(())
}

/// Reads one complete JSON value from a string.
///
/// This helper exists primarily for reporting extensions. It does not perform
/// benchmark-result validation.
pub fn read_json_value<T>(
    json: &str,
) -> Result<T, JsonReportError>
where
    T: DeserializeOwned,
{
    from_value_json(json)
}

// =============================================================================
// Validation boundary
// =============================================================================

/// Validates a benchmark result through its authoritative result model.
///
/// Keeping this function here prevents the JSON reporter from duplicating
/// result invariants.
pub fn validate_result(
    result: &BenchmarkResult,
) -> Result<(), JsonReportError> {
    result
        .validate()
        .map_err(JsonReportError::ResultValidation)
}

// =============================================================================
// Input/output guards
// =============================================================================

fn ensure_input_size(
    actual_bytes: usize,
    maximum_bytes: usize,
) -> Result<(), JsonReportError> {
    if actual_bytes > maximum_bytes {
        return Err(JsonReportError::InputTooLarge {
            actual_bytes,
            maximum_bytes,
        });
    }

    Ok(())
}

fn ensure_output_size(
    actual_bytes: usize,
    maximum_bytes: usize,
) -> Result<(), JsonReportError> {
    if actual_bytes > maximum_bytes {
        return Err(JsonReportError::OutputTooLarge {
            actual_bytes,
            maximum_bytes,
        });
    }

    Ok(())
}

// =============================================================================
// Serde error classification
// =============================================================================

/// Returns whether a serde_json error represents malformed JSON syntax.
///
/// This is exposed so callers implementing higher-level diagnostics can
/// distinguish malformed JSON from semantic result validation failures.
#[must_use]
pub fn is_syntax_error(error: &serde_json::Error) -> bool {
    error.classify() == Category::Syntax
}

/// Returns whether a serde_json error represents a type/data mismatch.
#[must_use]
pub fn is_data_error(error: &serde_json::Error) -> bool {
    error.classify() == Category::Data
}

/// Returns whether a serde_json error represents an I/O error.
#[must_use]
pub fn is_io_error(error: &serde_json::Error) -> bool {
    error.classify() == Category::Io
}

/// Returns whether a serde_json error represents an EOF/truncation condition.
#[must_use]
pub fn is_eof_error(error: &serde_json::Error) -> bool {
    error.classify() == Category::Eof
}

