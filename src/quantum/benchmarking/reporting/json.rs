/// Serializes any serde-compatible value using the production output limit.
///
/// This helper is intentionally separate from `BenchmarkResult` serialization
/// so reporting infrastructure can reuse the same bounded JSON boundary for
/// auxiliary metadata.
pub fn to_value_json<T>(
    value: &T,
) -> Result<String, JsonReportError>
where
    T: Serialize + ?Sized,
{
    let json = serde_json::to_string(value)
        .map_err(JsonReportError::Serialization)?;

    ensure_output_size(
        json.len(),
        DEFAULT_MAX_OUTPUT_BYTES,
    )?;

    Ok(json)
}

/// Serializes any serde-compatible value to pretty JSON using the production
/// output limit.
pub fn to_value_json_pretty<T>(
    value: &T,
) -> Result<String, JsonReportError>
where
    T: Serialize + ?Sized,
{
    let json = serde_json::to_string_pretty(value)
        .map_err(JsonReportError::Serialization)?;

    ensure_output_size(
        json.len(),
        DEFAULT_MAX_OUTPUT_BYTES,
    )?;

    Ok(json)
}

/// Deserializes a generic serde-compatible value with an explicit input limit.
///
/// This function does not perform domain-specific validation because the
/// generic type owns its own invariants.
pub fn from_value_json<T>(
    json: &str,
) -> Result<T, JsonReportError>
where
    T: DeserializeOwned,
{
    ensure_input_size(
        json.len(),
        DEFAULT_MAX_INPUT_BYTES,
    )?;

    serde_json::from_str(json)
        .map_err(JsonReportError::Deserialization)
}

// =============================================================================
// JSONL serialization
