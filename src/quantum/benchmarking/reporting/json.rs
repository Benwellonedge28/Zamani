/// Errors raised by the JSON reporting boundary.
#[derive(Debug)]
pub enum JsonReportError {
    /// JSON serialization failed.
    Serialization(serde_json::Error),

    /// JSON deserialization failed.
    Deserialization(serde_json::Error),

    /// The resulting benchmark object failed semantic validation.
    ResultValidation(ResultError),

    /// Input exceeded the configured resource limit.
    InputTooLarge {
        actual_bytes: usize,
        maximum_bytes: usize,
    },

    /// Output exceeded the configured resource limit.
    OutputTooLarge {
        actual_bytes: usize,
        maximum_bytes: usize,
    },

    /// JSONL contained too many records.
    TooManyRecords {
        actual_records: usize,
        maximum_records: usize,
    },

    /// One JSONL record exceeded the configured limit.
    JsonlRecordTooLarge {
        record_index: usize,
        actual_bytes: usize,
        maximum_bytes: usize,
    },

    /// A JSONL record was empty or whitespace-only.
    EmptyJsonlRecord {
        record_index: usize,
    },

    /// I/O failed while reading or writing JSONL.
    Io(io::Error),

    /// The supplied JSON configuration is internally invalid.
    InvalidLimits {
        field: &'static str,
    },

    /// JSONL contained more data than the configured record buffer can hold.
    JsonlRecordBufferOverflow {
        record_index: usize,
        maximum_bytes: usize,
    },

    /// A JSON value was syntactically valid but not a complete JSON document.
    TrailingJsonData,

    /// The requested JSON operation is not supported by the current format
    /// implementation.
    UnsupportedOperation {
        operation: &'static str,
    },
}

impl fmt::Display for JsonReportError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Serialization(error) => {
                write!(formatter, "JSON serialization failed: {}", error)
            }

            Self::Deserialization(error) => {
                write!(formatter, "JSON deserialization failed: {}", error)
            }

            Self::ResultValidation(error) => {
                write!(
                    formatter,
                    "benchmark result failed semantic validation: {}",
                    error
                )
            }

            Self::InputTooLarge {
                actual_bytes,
                maximum_bytes,
            } => {
                write!(
                    formatter,
                    "JSON input is {} bytes, exceeding the configured limit of {} bytes",
                    actual_bytes,
                    maximum_bytes
                )
            }

            Self::OutputTooLarge {
                actual_bytes,
                maximum_bytes,
            } => {
                write!(
                    formatter,
                    "JSON output is {} bytes, exceeding the configured limit of {} bytes",
                    actual_bytes,
                    maximum_bytes
                )
            }

            Self::TooManyRecords {
                actual_records,
                maximum_records,
            } => {
                write!(
                    formatter,
                    "JSONL contains at least {} records, exceeding the configured limit of {}",
                    actual_records,
                    maximum_records
                )
            }

            Self::JsonlRecordTooLarge {
                record_index,
                actual_bytes,
                maximum_bytes,
            } => {
                write!(
                    formatter,
                    "JSONL record {} is {} bytes, exceeding the configured limit of {} bytes",
                    record_index,
                    actual_bytes,
                    maximum_bytes
                )
            }

            Self::EmptyJsonlRecord { record_index } => {
                write!(
                    formatter,
                    "JSONL record {} is empty",
                    record_index
                )
            }

            Self::Io(error) => {
                write!(formatter, "JSONL I/O failed: {}", error)
            }

            Self::InvalidLimits { field } => {
                write!(
                    formatter,
                    "JSON reporting limit `{}` must be greater than zero",
                    field
                )
            }

            Self::JsonlRecordBufferOverflow {
                record_index,
                maximum_bytes,
            } => {
                write!(
                    formatter,
                    "JSONL record {} exceeded the configured {} byte buffer",
                    record_index,
                    maximum_bytes
                )
            }

            Self::TrailingJsonData => {
                write!(
                    formatter,
                    "JSON document contains trailing data after the root value"
                )
            }

            Self::UnsupportedOperation { operation } => {
                write!(
                    formatter,
                    "JSON reporting operation `{}` is unsupported",
                    operation
                )
            }
        }
    }
}

impl std::error::Error for JsonReportError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Serialization(error) => Some(error),
            Self::Deserialization(error) => Some(error),
            Self::ResultValidation(error) => Some(error),
            Self::Io(error) => Some(error),
            _ => None,
        }
    }
}

impl From<serde_json::Error> for JsonReportError {
    fn from(error: serde_json::Error) -> Self {
        if error.is_data() {
            Self::Deserialization(error)
        } else {
            Self::Serialization(error)
        }
    }
}

impl From<io::Error> for JsonReportError {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

