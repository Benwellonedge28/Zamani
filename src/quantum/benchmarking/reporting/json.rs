/// JSON formatting mode.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum JsonFormat {
    /// Compact JSON without insignificant whitespace.
    Compact,

    /// Human-readable pretty-printed JSON.
    Pretty,
}

impl Default for JsonFormat {
    fn default() -> Self {
        Self::Compact
    }
}

/// Options controlling JSON serialization.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct JsonSerializeOptions {
    /// Compact or pretty representation.
    pub format: JsonFormat,

    /// Resource limits.
    pub limits: JsonLimits,
}

impl JsonSerializeOptions {
    /// Production compact serialization.
    #[must_use]
    pub const fn compact() -> Self {
        Self {
            format: JsonFormat::Compact,
            limits: JsonLimits::production(),
        }
    }

    /// Production pretty serialization.
    #[must_use]
    pub const fn pretty() -> Self {
        Self {
            format: JsonFormat::Pretty,
            limits: JsonLimits::production(),
        }
    }

    /// Validates the options.
    pub fn validate(&self) -> Result<(), JsonReportError> {
        self.limits.validate()
    }
}

impl Default for JsonSerializeOptions {
    fn default() -> Self {
        Self::compact()
    }
}

