/// Serializes one benchmark result as one JSONL record.
///
/// The resulting string contains exactly one JSON value followed by `\n`.
pub fn to_jsonl_record(
    result: &BenchmarkResult,
) -> Result<String, JsonReportError> {
    let json = to_json(result)?;
    let mut record = String::with_capacity(json.len() + 1);
    record.push_str(&json);
    record.push('\n');

    ensure_output_size(
        record.len(),
        DEFAULT_MAX_JSONL_RECORD_BYTES,
    )?;

    Ok(record)
}

/// Serializes multiple benchmark results into JSON Lines.
///
/// Every result is independently validated before being emitted.
pub fn to_jsonl(
    results: &[BenchmarkResult],
) -> Result<String, JsonReportError> {
    to_jsonl_with_limits(results, JsonLimits::production())
}

/// Serializes multiple benchmark results into bounded JSON Lines.
pub fn to_jsonl_with_limits(
    results: &[BenchmarkResult],
    limits: JsonLimits,
) -> Result<String, JsonReportError> {
    limits.validate()?;

    if results.len() > limits.max_jsonl_records {
        return Err(JsonReportError::TooManyRecords {
            actual_records: results.len(),
            maximum_records: limits.max_jsonl_records,
        });
    }

    let mut output = String::new();

    for (index, result) in results.iter().enumerate() {
        let json = to_json_with_options(
            result,
            JsonSerializeOptions {
                format: JsonFormat::Compact,
                limits,
            },
        )?;

        if json.len() > limits.max_jsonl_record_bytes {
            return Err(JsonReportError::JsonlRecordTooLarge {
                record_index: index,
                actual_bytes: json.len(),
                maximum_bytes: limits.max_jsonl_record_bytes,
            });
        }

        let next_length = output
            .len()
            .checked_add(json.len())
            .and_then(|value| value.checked_add(1))
            .ok_or(JsonReportError::OutputTooLarge {
                actual_bytes: usize::MAX,
                maximum_bytes: limits.max_output_bytes,
            })?;

        if next_length > limits.max_output_bytes {
            return Err(JsonReportError::OutputTooLarge {
                actual_bytes: next_length,
                maximum_bytes: limits.max_output_bytes,
            });
        }

        output.push_str(&json);
        output.push('\n');
    }

    Ok(output)
}

/// Parses JSONL containing benchmark results.
///
/// Empty lines are rejected rather than silently skipped. This makes corrupted
/// or truncated benchmark artifacts detectable.
pub fn from_jsonl(
    input: &str,
) -> Result<Vec<BenchmarkResult>, JsonReportError> {
    from_jsonl_with_limits(
        input,
        JsonLimits::production(),
    )
}

/// Parses bounded JSONL containing benchmark results.
pub fn from_jsonl_with_limits(
    input: &str,
    limits: JsonLimits,
) -> Result<Vec<BenchmarkResult>, JsonReportError> {
    limits.validate()?;

    ensure_input_size(
        input.len(),
        limits.max_input_bytes,
    )?;

    let mut results = Vec::new();

    for (index, line) in input.lines().enumerate() {
        if line.trim().is_empty() {
            return Err(JsonReportError::EmptyJsonlRecord {
                record_index: index,
            });
        }

        if line.len() > limits.max_jsonl_record_bytes {
            return Err(JsonReportError::JsonlRecordTooLarge {
                record_index: index,
                actual_bytes: line.len(),
                maximum_bytes: limits.max_jsonl_record_bytes,
            });
        }

        if results.len() >= limits.max_jsonl_records {
            return Err(JsonReportError::TooManyRecords {
                actual_records: results.len() + 1,
                maximum_records: limits.max_jsonl_records,
            });
        }

        let result = from_json_with_options(
            line,
            JsonDeserializeOptions {
                limits,
                validate_result: true,
            },
        )
        .map_err(|error| {
            // Preserve the original error. The record index is encoded by the
            // caller's iteration context and should not be hidden by string
            // rewriting.
            error
        })?;

        results.push(result);
    }

    Ok(results)
}

// =============================================================================
// Streaming JSONL serialization
// =============================================================================

/// Writes one benchmark result as one JSONL record to a writer.
///
/// The writer remains owned by the caller.
pub fn write_jsonl_record<W>(
    writer: &mut W,
    result: &BenchmarkResult,
) -> Result<(), JsonReportError>
where
    W: Write,
{
    let record = to_jsonl_record(result)?;
    writer.write_all(record.as_bytes())?;
    Ok(())
}

/// Writes multiple benchmark results as JSONL.
///
/// Results are validated individually and are never silently omitted.
pub fn write_jsonl<W>(
    writer: &mut W,
    results: &[BenchmarkResult],
) -> Result<(), JsonReportError>
where
    W: Write,
{
    let limits = JsonLimits::production();
    limits.validate()?;

    if results.len() > limits.max_jsonl_records {
        return Err(JsonReportError::TooManyRecords {
            actual_records: results.len(),
            maximum_records: limits.max_jsonl_records,
        });
    }

    let mut total_bytes = 0usize;

    for (index, result) in results.iter().enumerate() {
        let record = to_jsonl_record(result)?;

        if record.len() > limits.max_jsonl_record_bytes {
            return Err(JsonReportError::JsonlRecordTooLarge {
                record_index: index,
                actual_bytes: record.len(),
                maximum_bytes: limits.max_jsonl_record_bytes,
            });
        }

        total_bytes = total_bytes
            .checked_add(record.len())
            .ok_or(JsonReportError::OutputTooLarge {
                actual_bytes: usize::MAX,
                maximum_bytes: limits.max_output_bytes,
            })?;

        if total_bytes > limits.max_output_bytes {
            return Err(JsonReportError::OutputTooLarge {
                actual_bytes: total_bytes,
                maximum_bytes: limits.max_output_bytes,
            });
        }

        writer.write_all(record.as_bytes())?;
    }

    writer.flush()?;

    Ok(())
}

/// Reads JSONL results from a buffered reader.
///
/// This function intentionally processes one record at a time, avoiding the
/// need to load the entire JSONL document into memory.
pub fn read_jsonl<R>(
    reader: &mut R,
) -> Result<Vec<BenchmarkResult>, JsonReportError>
where
    R: BufRead,
{
    let limits = JsonLimits::production();
    limits.validate()?;

    let mut results = Vec::new();
    let mut buffer = String::new();

    loop {
        buffer.clear();

        let bytes_read = reader.read_line(&mut buffer)?;

        if bytes_read == 0 {
            break;
        }

        let record_index = results.len();

        if record_index >= limits.max_jsonl_records {
            return Err(JsonReportError::TooManyRecords {
                actual_records: record_index + 1,
                maximum_records: limits.max_jsonl_records,
            });
        }

        if bytes_read > limits.max_jsonl_record_bytes {
            return Err(JsonReportError::JsonlRecordTooLarge {
                record_index,
                actual_bytes: bytes_read,
                maximum_bytes: limits.max_jsonl_record_bytes,
            });
        }

        if buffer.trim().is_empty() {
            return Err(JsonReportError::EmptyJsonlRecord {
                record_index,
            });
        }

        let result = from_json_with_options(
            buffer.trim_end_matches(['\r', '\n']),
            JsonDeserializeOptions {
                limits,
                validate_result: true,
            },
        )?;

        results.push(result);
    }

    Ok(results)
}

