/// Deserializes and validates a benchmark result from JSON.
///
/// This is the preferred production API.
pub fn from_json(
    json: &str,
) -> Result<BenchmarkResult, JsonReportError> {
    from_json_with_options(json, JsonDeserializeOptions::production())
}

/// Deserializes and validates a benchmark result from UTF-8 bytes.
///
/// This is the preferred production API for persisted artifacts.
pub fn from_json_bytes(
    bytes: &[u8],
) -> Result<BenchmarkResult, JsonReportError> {
    from_json_bytes_with_options(
        bytes,
        JsonDeserializeOptions::production(),
    )
}

/// Deserializes a benchmark result using explicit options.
///
/// With `validate_result = true`, the returned object has passed the canonical
/// result validator and is safe to pass to trusted benchmark consumers.
pub fn from_json_with_options(
    json: &str,
    options: JsonDeserializeOptions,
) -> Result<BenchmarkResult, JsonReportError> {
    options.validate()?;

    ensure_input_size(
        json.len(),
        options.limits.max_input_bytes,
    )?;

    let result = serde_json::from_str::<BenchmarkResult>(json)
        .map_err(JsonReportError::Deserialization)?;

    if options.validate_result {
        validate_result(&result)?;
    }

    Ok(result)
}

/// Deserializes a benchmark result from UTF-8 bytes using explicit options.
pub fn from_json_bytes_with_options(
    bytes: &[u8],
    options: JsonDeserializeOptions,
) -> Result<BenchmarkResult, JsonReportError> {
    options.validate()?;

    ensure_input_size(
        bytes.len(),
        options.limits.max_input_bytes,
    )?;

    let result = serde_json::from_slice::<BenchmarkResult>(bytes)
        .map_err(JsonReportError::Deserialization)?;

    if options.validate_result {
        validate_result(&result)?;
    }

    Ok(result)
}

/// Deserializes JSON without semantic result validation.
///
/// This is intentionally explicit and should only be used by migration or
/// forensic tooling.
pub fn from_json_unvalidated(
    json: &str,
) -> Result<BenchmarkResult, JsonReportError> {
    from_json_with_options(
        json,
        JsonDeserializeOptions::unvalidated(),
    )
}

