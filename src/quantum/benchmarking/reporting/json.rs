/// Stable identifier for the JSON reporting format.
pub const JSON_REPORT_FORMAT_ID: &str =
    "zamani.quantum.benchmark.json";

/// Current JSON reporting format version.
///
/// This describes this reporting layer, not the benchmark-result schema.
/// The result schema itself remains owned by `core::result`.
pub const JSON_REPORT_FORMAT_VERSION: u16 = 1;

/// Maximum number of bytes accepted by bounded string/byte deserialization.
pub const DEFAULT_MAX_INPUT_BYTES: usize = 64 * 1024 * 1024;

/// Maximum number of bytes produced by bounded serialization.
pub const DEFAULT_MAX_OUTPUT_BYTES: usize = 64 * 1024 * 1024;

/// Maximum JSONL record size accepted by the bounded JSONL reader.
pub const DEFAULT_MAX_JSONL_RECORD_BYTES: usize = 16 * 1024 * 1024;

/// Maximum number of JSONL records accepted by the bounded multi-record API.
pub const DEFAULT_MAX_JSONL_RECORDS: usize = 1_000_000;

// =============================================================================
// Configuration
// =============================================================================

/// Resource limits for JSON reporting.
///
/// These limits protect callers from accidentally or maliciously attempting
/// to serialize/deserialize arbitrarily large benchmark artifacts.
///
/// The limits are deliberately local to the serialization boundary. The
/// canonical result model has its own semantic collection limits.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct JsonLimits {
    /// Maximum input JSON size in bytes.
    pub max_input_bytes: usize,

    /// Maximum output JSON size in bytes.
    pub max_output_bytes: usize,

    /// Maximum individual JSONL record size in bytes.
    pub max_jsonl_record_bytes: usize,

    /// Maximum number of JSONL records accepted by a batch operation.
    pub max_jsonl_records: usize,
}

impl JsonLimits {
    /// Creates the production default limits.
    #[must_use]
    pub const fn production() -> Self {
        Self {
            max_input_bytes: DEFAULT_MAX_INPUT_BYTES,
            max_output_bytes: DEFAULT_MAX_OUTPUT_BYTES,
            max_jsonl_record_bytes: DEFAULT_MAX_JSONL_RECORD_BYTES,
            max_jsonl_records: DEFAULT_MAX_JSONL_RECORDS,
        }
    }

    /// Creates limits suitable for unit tests and small fixtures.
    #[must_use]
    pub const fn small() -> Self {
        Self {
            max_input_bytes: 1024 * 1024,
            max_output_bytes: 1024 * 1024,
            max_jsonl_record_bytes: 256 * 1024,
            max_jsonl_records: 10_000,
        }
    }

    /// Validates the limits themselves.
    pub fn validate(&self) -> Result<(), JsonReportError> {
        if self.max_input_bytes == 0 {
            return Err(JsonReportError::InvalidLimits {
                field: "max_input_bytes",
            });
        }

        if self.max_output_bytes == 0 {
            return Err(JsonReportError::InvalidLimits {
                field: "max_output_bytes",
            });
        }

        if self.max_jsonl_record_bytes == 0 {
            return Err(JsonReportError::InvalidLimits {
                field: "max_jsonl_record_bytes",
            });
        }

        if self.max_jsonl_records == 0 {
            return Err(JsonReportError::InvalidLimits {
                field: "max_jsonl_records",
            });
        }

        Ok(())
    }
}

impl Default for JsonLimits {
    fn default() -> Self {
        Self::production()
    }
}

