/// Stable CSV schema identifier.
///
/// This version describes the shape of the CSV document, not the benchmark
/// protocol version and not the Zamani package version.
pub const CSV_SCHEMA_VERSION: &str = "1.0";

/// Default maximum number of data rows.
///
/// A summary row is always included, followed by metric, finding and
/// recommendation rows.
pub const DEFAULT_MAX_ROWS: usize = 1_000_000;

/// Default maximum UTF-8 byte length of one CSV field.
pub const DEFAULT_MAX_FIELD_BYTES: usize = 1 << 20; // 1 MiB

/// Default maximum UTF-8 byte length of the complete CSV document.
pub const DEFAULT_MAX_OUTPUT_BYTES: usize = 256 << 20; // 256 MiB

/// Maximum number of fields in every emitted row.
pub const CSV_FIELD_COUNT: usize = 23;

/// Number of decimal places used for floating-point values.
///
/// This is deliberately fixed so two serializations of the same
/// `BenchmarkSummary` are byte-for-byte deterministic.
pub const DEFAULT_FLOAT_DECIMAL_PLACES: usize = 17;

/// Result type returned by CSV serialization.
pub type CsvResult<T> = Result<T, CsvError>;

/// Configuration controlling CSV serialization.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CsvOptions {
    /// Maximum number of rows permitted in the output.
    pub max_rows: usize,

    /// Maximum number of UTF-8 bytes allowed in one field.
    pub max_field_bytes: usize,

    /// Maximum number of UTF-8 bytes allowed in the final CSV document.
    pub max_output_bytes: usize,

    /// Whether spreadsheet-formula injection protection is enabled.
    ///
    /// When enabled, textual cells beginning with a potentially executable
    /// spreadsheet formula character are prefixed with `'`.
    pub spreadsheet_safe: bool,

    /// Whether a UTF-8 BOM should be emitted.
    ///
    /// This is disabled by default because BOM-free UTF-8 is the preferred
    /// machine-interchange representation.
    pub utf8_bom: bool,
}

impl Default for CsvOptions {
    fn default() -> Self {
        Self {
            max_rows: DEFAULT_MAX_ROWS,
            max_field_bytes: DEFAULT_MAX_FIELD_BYTES,
            max_output_bytes: DEFAULT_MAX_OUTPUT_BYTES,
            spreadsheet_safe: true,
            utf8_bom: false,
        }
    }
}

impl CsvOptions {
    /// Validates the serialization limits.
    pub fn validate(&self) -> CsvResult<()> {
        if self.max_rows == 0 {
            return Err(CsvError::InvalidLimit {
                field: "max_rows",
            });
        }

        if self.max_field_bytes == 0 {
            return Err(CsvError::InvalidLimit {
                field: "max_field_bytes",
            });
        }

        if self.max_output_bytes == 0 {
            return Err(CsvError::InvalidLimit {
                field: "max_output_bytes",
            });
        }

        if self.max_output_bytes < self.max_field_bytes {
            return Err(CsvError::InvalidConfiguration {
                message: "max_output_bytes must be greater than or equal to max_field_bytes",
            });
        }

        Ok(())
    }
}

/// CSV serialization errors.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CsvError {
    /// A serializer limit is zero or otherwise invalid.
    InvalidLimit {
        /// Name of the invalid limit.
        field: &'static str,
    },

    /// The serializer configuration is internally inconsistent.
    InvalidConfiguration {
        /// Stable human-readable description.
        message: &'static str,
    },

    /// The benchmark summary contains an invalid UTF-8 field.
    ///
    /// Rust `String` values are always valid UTF-8, so this variant is
    /// currently reserved for future byte-oriented extensions.
    InvalidText {
        /// Field name.
        field: &'static str,
    },

    /// A field exceeded the configured size.
    FieldTooLarge {
        /// Field name.
        field: &'static str,

        /// Actual UTF-8 byte length.
        actual: usize,

        /// Maximum permitted byte length.
        limit: usize,
    },

    /// The resulting document would exceed the configured output size.
    OutputTooLarge {
        /// Current/projected UTF-8 byte length.
        actual: usize,

        /// Maximum permitted byte length.
        limit: usize,
    },

    /// The result contains a non-finite floating-point value.
    NonFiniteFloat {
        /// Field name.
        field: &'static str,
    },

    /// A serde representation could not be converted into a stable scalar.
    Serialization {
        /// Stable description of the serialization problem.
        message: String,
    },
}

impl fmt::Display for CsvError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidLimit { field } => {
                write!(formatter, "invalid CSV limit: {field}")
            }
            Self::InvalidConfiguration { message } => {
                write!(formatter, "invalid CSV configuration: {message}")
            }
            Self::InvalidText { field } => {
                write!(formatter, "invalid CSV text in field: {field}")
            }
            Self::FieldTooLarge {
                field,
                actual,
                limit,
            } => {
                write!(
                    formatter,
                    "CSV field '{field}' is too large: {actual} bytes exceeds {limit}"
                )
            }
            Self::OutputTooLarge { actual, limit } => {
                write!(
                    formatter,
                    "CSV output is too large: {actual} bytes exceeds {limit}"
                )
            }
            Self::NonFiniteFloat { field } => {
                write!(formatter, "non-finite floating-point value in CSV field: {field}")
            }
            Self::Serialization { message } => {
                write!(formatter, "CSV serialization error: {message}")
            }
        }
    }
}

impl std::error::Error for CsvError {}

