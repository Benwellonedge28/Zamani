fn write_row<'a, I>(
    output: &mut String,
    values: I,
    options: CsvOptions,
) -> CsvResult<()>
where
    I: IntoIterator<Item = &'a str>,
{
    let values: Vec<&str> = values.into_iter().collect();

    if values.len() != TOTAL_FIELD_COUNT {
        return Err(CsvError::InvalidConfiguration {
            message: "internal CSV row does not match the canonical column count",
        });
    }

    for (index, value) in values.iter().enumerate() {
        if index != 0 {
            output.push(',');
        }

        write_csv_field(
            output,
            value,
            options,
        )?;
    }

    output.push('\n');

    enforce_output_limit(output, options.max_output_bytes)
}

fn write_csv_field(
    output: &mut String,
    value: &str,
    options: CsvOptions,
) -> CsvResult<()> {
    let value = if options.spreadsheet_safe {
        spreadsheet_safe_value(value)
    } else {
        value.to_string()
    };

    validate_text_field("csv_field", &value, options.max_field_bytes)?;

    let needs_quotes = value
        .bytes()
        .any(|byte| matches!(byte, b',' | b'"' | b'\n' | b'\r'));

    if needs_quotes {
        output.push('"');

        for character in value.chars() {
            if character == '"' {
                output.push('"');
                output.push('"');
            } else {
                output.push(character);
            }
        }

        output.push('"');
    } else {
        output.push_str(&value);
    }

    Ok(())
}

/// Applies spreadsheet formula-injection protection.
///
/// A leading tab/newline is also treated as dangerous because spreadsheet
/// applications may normalize whitespace before interpreting a formula.
fn spreadsheet_safe_value(value: &str) -> String {
    let trimmed = value.trim_start_matches([' ', '\t', '\r', '\n']);

    let dangerous = matches!(
        trimmed.chars().next(),
        Some('=' | '+' | '-' | '@')
    );

    if dangerous {
        let mut safe = String::with_capacity(value.len() + 1);
        safe.push('\'');
        safe.push_str(value);
        safe
    } else {
        value.to_string()
    }
}

fn optional_string(value: Option<&str>) -> String {
    value.unwrap_or_default().to_string()
}

fn bool_string(value: bool) -> String {
    if value {
        "true".to_string()
    } else {
        "false".to_string()
    }
}

fn optional_u64(value: Option<u64>) -> String {
    value.map(|number| number.to_string()).unwrap_or_default()
}

fn optional_float(field: &'static str, value: Option<f64>) -> CsvResult<String> {
    value
        .map(|number| format_float(field, number))
        .transpose()
        .map(|value| value.unwrap_or_default())
}

fn format_float(field: &'static str, value: f64) -> CsvResult<String> {
    validate_finite(field, value)?;

    let mut output = String::new();

    // `17` significant decimal places are sufficient for a deterministic
    // human-readable representation while remaining portable across normal
    // IEEE-754 f64 consumers.
    //
    // Scientific notation is permitted by CSV and is preferable to producing
    // huge strings for very small/large values.
    write!(&mut output, "{value:.17e}")
        .map_err(|_| CsvError::Serialization {
            message: format!("failed to format floating-point field '{field}'"),
        })?;

    Ok(output)
}

/// Serializes a serde value into a stable scalar string.
///
/// This is used for enum-like fields from `summary.rs`. The summary layer
/// already owns their semantic representation; this helper avoids requiring
/// CSV to duplicate enum-to-string mappings that would become stale when the
/// core metric vocabulary evolves.
fn enum_id<T>(value: &T) -> CsvResult<String>
where
    T: serde::Serialize,
{
    let serialized = serde_json::to_value(value).map_err(|error| {
        CsvError::Serialization {
            message: error.to_string(),
        }
    })?;

    match serialized {
        Value::String(value) => Ok(value),

        Value::Number(value) => Ok(value.to_string()),

        Value::Bool(value) => Ok(bool_string(value)),

        Value::Null => Ok(String::new()),

        Value::Array(_) | Value::Object(_) => {
            Err(CsvError::Serialization {
                message:
                    "CSV enum field serialized to a non-scalar JSON value"
                        .to_string(),
            })
        }
    }
}

fn enforce_output_limit(
    output: &str,
    limit: usize,
) -> CsvResult<()> {
    let actual = output.len();

    if actual > limit {
        return Err(CsvError::OutputTooLarge { actual, limit });
    }

    Ok(())
}

