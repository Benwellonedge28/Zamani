//! Deterministic, production-grade CSV serialization for quantum benchmark
//! summaries.
//!
//! # Purpose
//!
//! `csv.rs` is the machine-readable tabular serializer for
//! `quantum::benchmarking::reporting::BenchmarkSummary`.
//!
//! It deliberately does NOT:
//!
//! - execute quantum circuits;
//! - generate benchmark circuits;
//! - calculate benchmark metrics;
//! - perform statistical inference;
//! - access hardware;
//! - inspect backend-specific implementation details;
//! - modify `BenchmarkSummary`;
//! - depend on individual benchmark protocols;
//! - depend on `core::result`;
//! - depend on `analysis`;
//! - depend on `validation`.
//!
//! Those responsibilities belong to the owning benchmarking layers.
//!
//! # Architectural position
//!
//! ```text
//! BenchmarkResult
//!      │
//!      ▼
//! reporting::summary::BenchmarkSummary
//!      │
//!      ├──────────────► reporting::json
//!      │
//!      ├──────────────► reporting::markdown
//!      │
//!      └──────────────► reporting::csv
//!                               │
//!                               ▼
//!                         UTF-8 CSV bytes
//! ```
//!
//! `BenchmarkSummary` is the only semantic input to this module.
//!
//! # Why CSV is a separate representation
//!
//! CSV is useful for:
//!
//! - spreadsheets;
//! - scientific data analysis;
//! - R;
//! - Python/pandas;
//! - command-line processing;
//! - CI artifacts;
//! - benchmark history databases;
//! - regression pipelines;
//! - plotting tools;
//! - external research workflows.
//!
//! However, CSV is inherently tabular and cannot naturally represent the
//! complete nested structure of a benchmark result. Therefore this module uses
//! a documented, deterministic **long-form record schema**.
//!
//! Each output row has a `record_type`:
//!
//! - `summary`         — one row describing the benchmark summary;
//! - `metric`          — one row for every benchmark metric;
//! - `finding`         — one row for every finding;
//! - `recommendation`  — one row for every recommendation.
//!
//! The schema is intentionally stable and machine-readable.
//!
//! # CSV guarantees
//!
//! This implementation guarantees:
//!
//! - UTF-8 output;
//! - deterministic column ordering;
//! - deterministic row ordering;
//! - RFC 4180-compatible quoting rules;
//! - correct escaping of commas;
//! - correct escaping of quotes;
//! - correct preservation of newlines;
//! - correct preservation of carriage returns;
//! - no trailing separator;
//! - exactly one header row;
//! - explicit schema version;
//! - bounded output allocation;
//! - rejection of invalid configuration;
//! - rejection of oversized output;
//! - rejection of non-finite floating-point values;
//! - no `unwrap()`;
//! - no `expect()`;
//! - no panic-based validation;
//! - no logging side effects;
//! - no timestamps generated by the serializer;
//! - no random values;
//! - no dependence on filesystem APIs;
//! - no dependency on a third-party CSV crate.
//!
//! # Security
//!
//! CSV has a well-known spreadsheet-formula injection problem. A benchmark
//! identifier, backend identifier, metric description, finding message, or
//! recommendation could theoretically begin with a spreadsheet formula such
//! as `=`, `+`, `-`, or `@`.
//!
//! This serializer therefore provides an explicit formula-injection policy.
//! By default, potentially executable spreadsheet cells are prefixed with a
//! single quote when exporting for spreadsheet consumption.
//!
//! Raw machine-oriented CSV can be requested through
//! [`CsvOptions::spreadsheet_safe`].
//!
//! The default is `true` because benchmark output is frequently opened in
//! spreadsheet software.
//!
//! # Resource safety
//!
//! The serializer validates:
//!
//! - maximum rows;
//! - maximum fields per row;
//! - maximum field length;
//! - maximum total output bytes.
//!
//! These limits protect callers from accidentally materializing an enormous
//! CSV document in memory.
//!
//! # Integration contract
//!
//! This module is intentionally stable against changes in the underlying
//! benchmark implementation.
//!
//! The integration point is:
//!
//! ```text
//! BenchmarkSummary
//!       │
//!       ▼
//! CsvReport::from_summary()
//!       │
//!       ▼
//! CsvReport::to_string()
//! ```
//!
//! Therefore future changes to `core::result`, individual benchmark protocols,
//! hardware backends, or statistical implementations do not require this file
//! to be rewritten as long as `BenchmarkSummary` remains the reporting
//! contract.
//!
//! # Rust compatibility
//!
//! Target:
//!
//! - Rust 1.97;
//! - Rust 1.97.1;
//! - Rust 2021 edition;
//! - stable Rust only.
//!
//! No nightly features are required.
//!
//! # Dependencies
//!
//! The implementation intentionally uses only:
//!
//! - Rust standard library;
//! - `serde_json`, already used by the Zamani benchmarking/reporting layer.
//!
//! No dedicated CSV dependency is required.
//!
//! # Integration with reporting::summary
//!
//! The current summary layer defines:
//!
//! - `BenchmarkSummary`;
//! - `SummaryMetric`;
//! - `SummaryFinding`;
//! - `SummaryEnvironment`;
//! - `SummaryConfidence`;
//! - `SummarySeverity`;
//! - `SummaryStatus`.
//!
//! This serializer consumes those public types and does not duplicate their
//! semantic definitions.
//!
//! # Future reporting modules
//!
//! `report.rs` should orchestrate report generation and may call this module.
//! `json.rs` should provide the lossless structured representation.
//! `markdown.rs` should provide human-readable presentation.
//!
//! CSV should remain a serializer, not become the reporting orchestrator.
//!
//! # Important path correction
//!
//! The repository architecture uses:
//!
//! ```text
//! src/quantum/benchmarking/reporting/
//! ```
//!
//! Therefore this file belongs at:
//!
//! ```text
//! src/quantum/benchmarking/reporting/csv.rs
//! ```
//!
//! not:
//!
//! ```text
//! src/quantum/benchmarking/reposting/csv.rs
//! ```
//!
//! Do not create a second `reposting` subsystem merely because of a spelling
//! mistake in a task description.

