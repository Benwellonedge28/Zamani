/// Errors produced by the leakage randomized-benchmarking protocol.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum LeakageRbError {
    /// No sequence lengths were provided.
    EmptySequenceLengths,

    /// A sequence length was zero.
    InvalidSequenceLength {
        /// Invalid length.
        length: usize,
    },

    /// Too many sequence lengths were requested.
    TooManySequenceLengths {
        /// Requested count.
        requested: usize,

        /// Maximum permitted.
        maximum: usize,
    },

    /// Duplicate sequence length.
    DuplicateSequenceLength {
        /// Duplicated value.
        length: usize,
    },

    /// Sequence lengths were not strictly increasing.
    UnsortedSequenceLengths,

    /// Too few sequence lengths exist for the requested model.
    InsufficientSequenceLengths {
        /// Number supplied.
        supplied: usize,

        /// Minimum required.
        minimum: usize,
    },

    /// Invalid number of sequences per length.
    InvalidSequencesPerLength {
        /// Requested count.
        requested: usize,

        /// Maximum allowed.
        maximum: usize,
    },

    /// Invalid shot count.
    InvalidShots {
        /// Requested count.
        requested: usize,

        /// Maximum allowed.
        maximum: usize,
    },

    /// Total-shot budget was exceeded.
    TotalShotLimitExceeded {
        /// Requested total.
        requested: u128,

        /// Maximum.
        maximum: u128,
    },

    /// Arithmetic overflow occurred.
    ResourceCalculationOverflow,

    /// Invalid confidence level.
    InvalidConfidenceLevel {
        /// Invalid level.
        value: f64,
    },

    /// Invalid seed.
    InvalidSeed,

    /// Invalid computational-subspace dimension.
    InvalidComputationalDimension,

    /// Invalid leakage-subspace dimension.
    InvalidLeakageDimension,

    /// Computational and leakage dimensions overflowed.
    HilbertDimensionOverflow,

    /// Invalid measurement mode.
    InvalidMeasurementMode,

    /// A measurement had impossible counts.
    InvalidObservationCounts {
        /// Sequence length.
        length: usize,

        /// Computational count.
        computational: u64,

        /// Leakage count.
        leakage: u64,

        /// Unclassified count.
        unclassified: u64,

        /// Total shots.
        shots: u64,
    },

    /// A probability was non-finite.
    NonFiniteProbability {
        /// Field name.
        field: &'static str,
    },

    /// A probability was outside [0,1].
    ProbabilityOutOfRange {
        /// Field name.
        field: &'static str,

        /// Invalid value.
        value: f64,
    },

    /// The same sequence was observed more than once.
    DuplicateSequenceObservation {
        /// Sequence length.
        length: usize,

        /// Sequence index.
        sequence_index: usize,
    },

    /// An observation belonged to a sequence length not in the experiment.
    UnexpectedSequenceLength {
        /// Sequence length.
        length: usize,
    },

    /// No usable observations exist.
    NoObservations,

    /// The fit could not identify the decay.
    FitFailed,

    /// The decay parameter was not physically valid.
    InvalidDecayParameter {
        /// Fitted lambda.
        value: f64,
    },

    /// A fitted parameter is non-finite.
    NonFiniteFitParameter {
        /// Parameter name.
        parameter: &'static str,
    },

    /// A fit violated probability constraints.
    InvalidPhysicalFit,

    /// The fit is too close to a degenerate boundary.
    BoundaryFit,

    /// A requested grid/refinement configuration is invalid.
    InvalidFitConfiguration,

    /// The requested bootstrap count is invalid.
    InvalidBootstrapCount,

    /// Bootstrap resource budget was exceeded.
    BootstrapLimitExceeded {
        /// Requested operations.
        requested: u128,

        /// Maximum.
        maximum: u128,
    },
}

impl fmt::Display for LeakageRbError {
    fn fmt(
        &self,
        formatter: &mut fmt::Formatter<'_>,
    ) -> fmt::Result {
        match self {
            Self::EmptySequenceLengths => {
                write!(
                    formatter,
                    "leakage RB requires at least one sequence length"
                )
            }

            Self::InvalidSequenceLength { length } => {
                write!(
                    formatter,
                    "leakage RB sequence length must be greater than zero, got {length}"
                )
            }

            Self::TooManySequenceLengths {
                requested,
                maximum,
            } => {
                write!(
                    formatter,
                    "requested {requested} leakage RB sequence lengths; maximum is {maximum}"
                )
            }

            Self::DuplicateSequenceLength { length } => {
                write!(
                    formatter,
                    "leakage RB sequence length {length} occurs more than once"
                )
            }

            Self::UnsortedSequenceLengths => {
                write!(
                    formatter,
                    "leakage RB sequence lengths must be strictly increasing"
                )
            }

            Self::InsufficientSequenceLengths {
                supplied,
                minimum,
            } => {
                write!(
                    formatter,
                    "leakage RB requires at least {minimum} distinct sequence lengths, got {supplied}"
                )
            }

            Self::InvalidSequencesPerLength {
                requested,
                maximum,
            } => {
                write!(
                    formatter,
                    "requested {requested} sequences per length; maximum is {maximum}"
                )
            }

            Self::InvalidShots {
                requested,
                maximum,
            } => {
                write!(
                    formatter,
                    "requested {requested} shots per sequence; maximum is {maximum}"
                )
            }

            Self::TotalShotLimitExceeded {
                requested,
                maximum,
            } => {
                write!(
                    formatter,
                    "requested {requested} total shots; maximum is {maximum}"
                )
            }

            Self::ResourceCalculationOverflow => {
                write!(
                    formatter,
                    "leakage RB resource calculation overflowed"
                )
            }

            Self::InvalidConfidenceLevel { value } => {
                write!(
                    formatter,
                    "confidence level must be finite and in (0,1), got {value}"
                )
            }

            Self::InvalidSeed => {
                write!(
                    formatter,
                    "leakage RB experiment seed must be non-zero"
                )
            }

            Self::InvalidComputationalDimension => {
                write!(
                    formatter,
                    "computational-subspace dimension must be greater than zero"
                )
            }

            Self::InvalidLeakageDimension => {
                write!(
                    formatter,
                    "leakage-subspace dimension must be greater than zero"
                )
            }

            Self::HilbertDimensionOverflow => {
                write!(
                    formatter,
                    "computational plus leakage dimension overflowed"
                )
            }

            Self::InvalidMeasurementMode => {
                write!(
                    formatter,
                    "invalid leakage RB measurement mode"
                )
            }

            Self::InvalidObservationCounts {
                length,
                computational,
                leakage,
                unclassified,
                shots,
            } => {
                write!(
                    formatter,
                    "invalid leakage RB counts at length {length}: computational={computational}, leakage={leakage}, unclassified={unclassified}, shots={shots}"
                )
            }

            Self::NonFiniteProbability { field } => {
                write!(
                    formatter,
                    "non-finite leakage RB probability in {field}"
                )
            }

            Self::ProbabilityOutOfRange { field, value } => {
                write!(
                    formatter,
                    "leakage RB probability {field}={value} is outside [0,1]"
                )
            }

            Self::DuplicateSequenceObservation {
                length,
                sequence_index,
            } => {
                write!(
                    formatter,
                    "duplicate leakage RB observation for length {length}, sequence {sequence_index}"
                )
            }

            Self::UnexpectedSequenceLength { length } => {
                write!(
                    formatter,
                    "observation uses sequence length {length}, which is not in the configured experiment"
                )
            }

            Self::NoObservations => {
                write!(
                    formatter,
                    "leakage RB analysis requires observations"
                )
            }

            Self::FitFailed => {
                write!(
                    formatter,
                    "leakage RB exponential fit failed"
                )
            }

            Self::InvalidDecayParameter { value } => {
                write!(
                    formatter,
                    "leakage RB decay parameter {value} is outside [0,1]"
                )
            }

            Self::NonFiniteFitParameter { parameter } => {
                write!(
                    formatter,
                    "leakage RB fit parameter {parameter} is non-finite"
                )
            }

            Self::InvalidPhysicalFit => {
                write!(
                    formatter,
                    "leakage RB fit violates physical probability constraints"
                )
            }

            Self::BoundaryFit => {
                write!(
                    formatter,
                    "leakage RB fit is numerically dominated by a physical boundary"
                )
            }

            Self::InvalidFitConfiguration => {
                write!(
                    formatter,
                    "invalid leakage RB fitting configuration"
                )
            }

            Self::InvalidBootstrapCount => {
                write!(
                    formatter,
                    "leakage RB bootstrap count is invalid"
                )
            }

            Self::BootstrapLimitExceeded {
                requested,
                maximum,
            } => {
                write!(
                    formatter,
                    "leakage RB bootstrap workload {requested} exceeds maximum {maximum}"
                )
            }
        }
    }
}

