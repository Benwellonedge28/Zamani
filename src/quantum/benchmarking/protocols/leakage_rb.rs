/// Aggregated observations for one sequence length.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Serialize,
    Deserialize,
)]
pub struct LeakageRbLengthObservation {
    /// Sequence length.
    pub sequence_length: usize,

    /// Number of independent sequences contributing data.
    pub sequence_count: usize,

    /// Total shots.
    pub shots: u64,

    /// Computational-subspace outcomes.
    pub computational_count: u64,

    /// Leakage outcomes.
    pub leakage_count: u64,

    /// Unclassified outcomes.
    pub unclassified_count: u64,

    /// Computational-subspace probability.
    pub computational_probability: f64,

    /// Leakage probability.
    pub leakage_probability: f64,

    /// Unclassified probability.
    pub unclassified_probability: f64,
}

impl LeakageRbLengthObservation {
    /// Creates an empty accumulator.
    fn empty(sequence_length: usize) -> Self {
        Self {
            sequence_length,
            sequence_count: 0,
            shots: 0,
            computational_count: 0,
            leakage_count: 0,
            unclassified_count: 0,
            computational_probability: 0.0,
            leakage_probability: 0.0,
            unclassified_probability: 0.0,
        }
    }

    /// Adds one observation.
    fn add(
        &mut self,
        observation: LeakageRbObservation,
    ) -> LeakageRbResult<()> {
        self.sequence_count = self
            .sequence_count
            .checked_add(1)
            .ok_or(
                LeakageRbError::ResourceCalculationOverflow,
            )?;

        self.shots = self
            .shots
            .checked_add(observation.shots)
            .ok_or(
                LeakageRbError::ResourceCalculationOverflow,
            )?;

        self.computational_count = self
            .computational_count
            .checked_add(
                observation.computational_count,
            )
            .ok_or(
                LeakageRbError::ResourceCalculationOverflow,
            )?;

        self.leakage_count = self
            .leakage_count
            .checked_add(observation.leakage_count)
            .ok_or(
                LeakageRbError::ResourceCalculationOverflow,
            )?;

        self.unclassified_count = self
            .unclassified_count
            .checked_add(
                observation.unclassified_count,
            )
            .ok_or(
                LeakageRbError::ResourceCalculationOverflow,
            )?;

        self.recalculate_probabilities()
    }

    fn recalculate_probabilities(
        &mut self,
    ) -> LeakageRbResult<()> {
        if self.shots == 0 {
            return Err(LeakageRbError::NoObservations);
        }

        self.computational_probability =
            self.computational_count as f64
                / self.shots as f64;

        self.leakage_probability =
            self.leakage_count as f64
                / self.shots as f64;

        self.unclassified_probability =
            self.unclassified_count as f64
                / self.shots as f64;

        validate_probability(
            "computational_probability",
            self.computational_probability,
        )?;

        validate_probability(
            "leakage_probability",
            self.leakage_probability,
        )?;

        validate_probability(
            "unclassified_probability",
            self.unclassified_probability,
        )?;

        Ok(())
    }
}

