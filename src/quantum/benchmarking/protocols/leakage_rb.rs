/// Measurement strategy used to determine leakage.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Hash,
    Serialize,
    Deserialize,
)]
pub enum LeakageMeasurementMode {
    /// Measure the probability of remaining in the computational subspace.
    ComputationalSubspace,

    /// Directly measure the leakage subspace.
    DirectLeakage,

    /// Measure both computational and leakage populations.
    Both,
}

impl LeakageMeasurementMode {
    /// Stable identifier.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::ComputationalSubspace => {
                "computational_subspace"
            }
            Self::DirectLeakage => "direct_leakage",
            Self::Both => "both",
        }
    }

    /// Returns whether computational-subspace population is required.
    pub const fn requires_computational(self) -> bool {
        matches!(
            self,
            Self::ComputationalSubspace | Self::Both
        )
    }

    /// Returns whether direct leakage population is required.
    pub const fn requires_leakage(self) -> bool {
        matches!(
            self,
            Self::DirectLeakage | Self::Both
        )
    }
}

