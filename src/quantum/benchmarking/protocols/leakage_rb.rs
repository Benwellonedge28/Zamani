// =============================================================================
// Observation aggregation
// =============================================================================

fn aggregate_observations(
    config: &LeakageRbConfig,
    observations: &[LeakageRbObservation],
) -> LeakageRbResult<Vec<LeakageRbLengthObservation>> {
    let mut result: Vec<LeakageRbLengthObservation> =
        config
            .sequence_lengths
            .iter()
            .copied()
            .map(LeakageRbLengthObservation::empty)
            .collect();

    let mut seen: Vec<(usize, usize)> =
        Vec::with_capacity(observations.len());

    for &observation in observations {
        observation.validate()?;

        if !config
            .sequence_lengths
            .contains(&observation.sequence_length)
        {
            return Err(
                LeakageRbError::UnexpectedSequenceLength {
                    length: observation.sequence_length,
                },
            );
        }

        if seen.iter().any(|(length, index)| {
            *length == observation.sequence_length
                && *index == observation.sequence_index
        }) {
            return Err(
                LeakageRbError::DuplicateSequenceObservation {
                    length: observation.sequence_length,
                    sequence_index:
                        observation.sequence_index,
                },
            );
        }

        seen.push((
            observation.sequence_length,
            observation.sequence_index,
        ));

        let position = config
            .sequence_lengths
            .iter()
            .position(|length| {
                *length == observation.sequence_length
            })
            .ok_or(
                LeakageRbError::UnexpectedSequenceLength {
                    length: observation.sequence_length,
                },
            )?;

        result[position].add(observation)?;
    }

    if result.iter().any(|observation| {
        observation.sequence_count == 0
    }) {
        return Err(
            LeakageRbError::NoObservations,
        );
    }

    for observation in &mut result {
        if observation.sequence_count < 2 {
            // The warning is generated later. One sequence is still
            // mathematically analyzable.
        }

        match config.measurement_mode {
            LeakageMeasurementMode::ComputationalSubspace => {}

            LeakageMeasurementMode::DirectLeakage => {
                // Convert directly measured leakage population into the
                // complementary computational population only when the
                // measurement is complete. Unclassified outcomes make that
                // complement invalid as a normalized computational probability.
                if observation.unclassified_count == 0 {
                    observation.computational_probability =
                        1.0 - observation.leakage_probability;

                    validate_probability(
                        "derived_computational_probability",
                        observation.computational_probability,
                    )?;
                }
            }

            LeakageMeasurementMode::Both => {
                let classified = observation
                    .computational_probability
                    + observation.leakage_probability;

                if observation.unclassified_count == 0
                    && (classified - 1.0).abs()
                        > PROBABILITY_EPSILON
                {
                    return Err(
                        LeakageRbError::InvalidPhysicalFit,
                    );
                }
            }
        }
    }

    Ok(result)
}

