fn validate_sequence_lengths(
    sequence_lengths: &[usize],
    maximum_count: usize,
    maximum_length: usize,
) -> LeakageRbResult<()> {
    if sequence_lengths.is_empty() {
        return Err(
            LeakageRbError::EmptySequenceLengths,
        );
    }

    if sequence_lengths.len()
        > maximum_count
    {
        return Err(
            LeakageRbError::TooManySequenceLengths {
                requested:
                    sequence_lengths.len(),
                maximum: maximum_count,
            },
        );
    }

    let mut previous = 0usize;

    for (index, &length) in
        sequence_lengths.iter().enumerate()
    {
        if length == 0
            || length > maximum_length
        {
            return Err(
                LeakageRbError::InvalidSequenceLength {
                    length,
                },
            );
        }

        if index > 0 {
            if length == previous {
                return Err(
                    LeakageRbError::DuplicateSequenceLength {
                        length,
                    },
                );
            }

            if length < previous {
                return Err(
                    LeakageRbError::UnsortedSequenceLengths,
                );
            }
        }

        previous = length;
    }

    Ok(())
}

fn validate_probability(
    field: &'static str,
    value: f64,
) -> LeakageRbResult<()> {
    if !value.is_finite() {
        return Err(
            LeakageRbError::NonFiniteProbability {
                field,
            },
        );
    }

    if value < -PROBABILITY_EPSILON
        || value > 1.0 + PROBABILITY_EPSILON
    {
        return Err(
            LeakageRbError::ProbabilityOutOfRange {
                field,
                value,
            },
        );
    }

    Ok(())
}

fn validate_rate(
    field: &'static str,
    value: f64,
) -> LeakageRbResult<()> {
    validate_probability(field, value)
}

fn count_distinct_x(
    observations: &[(f64, f64, f64)],
) -> usize {
    let mut values: Vec<f64> =
        observations
            .iter()
            .map(|(x, _, _)| *x)
            .collect();

    values.sort_by(|a, b| {
        a.partial_cmp(b)
            .unwrap_or(
                std::cmp::Ordering::Equal,
            )
    });

    values.dedup_by(|a, b| {
        (*a - *b).abs()
            <= f64::EPSILON
                * a.abs().max(b.abs()).max(1.0)
                * 16.0
    });

    values.len()
}

fn weighted_mean(
    observations: &[(f64, f64, f64)],
) -> f64 {
    let mut numerator = 0.0;
    let mut denominator = 0.0;

    for (_, y, weight) in observations {
        numerator += *weight * *y;
        denominator += *weight;
    }

    if denominator > 0.0 {
        numerator / denominator
    } else {
        0.0
    }
}

