/// Production LRB analyzer.
///
/// The analyzer is stateless and deterministic.
///
/// It can be used for:
///
/// - live execution results;
/// - archived hardware results;
/// - simulator fixtures;
/// - regression tests;
/// - independent scientific re-analysis.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct LeakageRbAnalyzer {
    /// Fit grid points.
    pub fit_grid_points: usize,

    /// Maximum local refinement iterations.
    pub fit_refinement_iterations: usize,

    /// Fit tolerance.
    pub fit_tolerance: f64,
}

impl LeakageRbAnalyzer {
    /// Creates an analyzer from configuration.
    pub fn from_config(
        config: &LeakageRbConfig,
    ) -> LeakageRbResult<Self> {
        config.validate()?;

        Ok(Self {
            fit_grid_points:
                config.fit_grid_points,
            fit_refinement_iterations:
                config.fit_refinement_iterations,
            fit_tolerance:
                config.fit_tolerance,
        })
    }

    /// Analyzes captured observations.
    pub fn analyze(
        &self,
        config: &LeakageRbConfig,
        observations: &[LeakageRbObservation],
    ) -> LeakageRbResult<LeakageRbResult> {
        config.validate()?;

        if observations.is_empty() {
            return Err(LeakageRbError::NoObservations);
        }

        let aggregated =
            aggregate_observations(
                config,
                observations,
            )?;

        let fit_observations: Vec<(f64, f64, f64)> =
            aggregated
                .iter()
                .map(|observation| {
                    (
                        observation.sequence_length
                            as f64,
                        observation
                            .computational_probability,
                        observation.shots as f64,
                    )
                })
                .collect();

        let fit = fit_decay(
            &fit_observations,
            self.fit_grid_points,
            self.fit_refinement_iterations,
            self.fit_tolerance,
        )?;

        let leakage_rate =
            fit.leakage_rate();

        let seepage_rate =
            fit.seepage_rate();

        validate_rate(
            "leakage_rate",
            leakage_rate,
        )?;

        validate_rate(
            "seepage_rate",
            seepage_rate,
        )?;

        let combined_transfer_rate =
            leakage_rate + seepage_rate;

        if combined_transfer_rate
            > 1.0 + PROBABILITY_EPSILON
        {
            return Err(
                LeakageRbError::InvalidPhysicalFit,
            );
        }

        let total_shots =
            observations.iter().try_fold(
                0u128,
                |accumulator, observation| {
                    accumulator
                        .checked_add(
                            observation.shots as u128
                        )
                        .ok_or(
                            LeakageRbError::
                                ResourceCalculationOverflow,
                        )
                },
            )?;

        let total_sequences =
            observations.len() as u128;

        let warnings =
            build_warnings(
                config,
                &aggregated,
                &fit,
                leakage_rate,
                seepage_rate,
            );

        Ok(LeakageRbResult {
            schema_version:
                LEAKAGE_RB_SCHEMA_VERSION,
            benchmark_id:
                LEAKAGE_RB_BENCHMARK_ID.to_owned(),
            algorithm_id:
                LEAKAGE_RB_ALGORITHM_ID.to_owned(),
            measurement_mode:
                config.measurement_mode,
            computational_dimension:
                config.computational_dimension,
            leakage_dimension:
                config.leakage_dimension,
            total_dimension:
                config.total_dimension()?,
            experiment_seed:
                config.experiment_seed,
            sequence_lengths:
                config.sequence_lengths.clone(),
            observations: aggregated,
            fit,
            leakage_rate,
            seepage_rate,
            combined_transfer_rate,
            total_shots,
            total_sequences,
            assumptions:
                config.assumptions,
            warnings,
        })
    }
}

