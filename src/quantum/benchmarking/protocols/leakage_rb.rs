/// Fits:
///
/// ```text
/// y = A + B * lambda^m
/// ```
///
/// subject to:
///
/// ```text
/// 0 <= lambda <= 1
/// A >= 0
/// B >= 0
/// A + B <= 1
/// ```
fn fit_decay(
    observations: &[(f64, f64, f64)],
    grid_points: usize,
    max_iterations: usize,
    tolerance: f64,
) -> LeakageRbResult<LeakageDecayFit> {
    if observations.len() < MIN_SEQUENCE_LENGTHS
        || grid_points < 8
        || max_iterations == 0
        || !tolerance.is_finite()
        || tolerance <= 0.0
    {
        return Err(
            LeakageRbError::InvalidFitConfiguration,
        );
    }

    let distinct =
        count_distinct_x(observations);

    if distinct < MIN_SEQUENCE_LENGTHS {
        return Err(
            LeakageRbError::InsufficientSequenceLengths {
                supplied: distinct,
                minimum: MIN_SEQUENCE_LENGTHS,
            },
        );
    }

    let mut best:
        Option<ConstrainedFitCandidate> = None;

    let denominator =
        (grid_points - 1) as f64;

    for index in 0..grid_points {
        let lambda =
            index as f64 / denominator;

        if let Some(candidate) =
            fit_at_lambda(observations, lambda)
        {
            if best
                .as_ref()
                .map(|current| {
                    candidate.sse
                        < current.sse
                })
                .unwrap_or(true)
            {
                best = Some(candidate);
            }
        }
    }

    let best =
        best.ok_or(LeakageRbError::FitFailed)?;

    let best_lambda =
        best.lambda;

    let grid_step =
        1.0 / denominator;

    let mut left =
        (best_lambda - grid_step)
            .max(MIN_LAMBDA);

    let mut right =
        (best_lambda + grid_step)
            .min(MAX_LAMBDA);

    let boundary =
        best_lambda <= FIT_EPSILON
            || best_lambda
                >= 1.0 - FIT_EPSILON;

    let mut iterations = 0usize;
    let mut current = best;

    if !boundary && right > left {
        // Golden-section refinement.
        let golden =
            0.618_033_988_749_894_9_f64;

        let mut x1 =
            right - golden * (right - left);
        let mut x2 =
            left + golden * (right - left);

        let mut f1 =
            fit_at_lambda(
                observations,
                x1,
            )
            .map(|fit| fit.sse)
            .unwrap_or(f64::INFINITY);

        let mut f2 =
            fit_at_lambda(
                observations,
                x2,
            )
            .map(|fit| fit.sse)
            .unwrap_or(f64::INFINITY);

        while iterations
            < max_iterations
            && (right - left)
                > tolerance
        {
            iterations += 1;

            if f1 > f2 {
                left = x1;
                x1 = x2;
                f1 = f2;

                x2 =
                    left + golden
                        * (right - left);

                f2 =
                    fit_at_lambda(
                        observations,
                        x2,
                    )
                    .map(|fit| fit.sse)
                    .unwrap_or(
                        f64::INFINITY,
                    );
            } else {
                right = x2;
                x2 = x1;
                f2 = f1;

                x1 =
                    right - golden
                        * (right - left);

                f1 =
                    fit_at_lambda(
                        observations,
                        x1,
                    )
                    .map(|fit| fit.sse)
                    .unwrap_or(
                        f64::INFINITY,
                    );
            }
        }

        let candidate_lambda =
            0.5 * (left + right);

        if let Some(candidate) =
            fit_at_lambda(
                observations,
                candidate_lambda,
            )
        {
            if candidate.sse
                < current.sse
            {
                current = candidate;
            }
        }
    }

    let predicted: Vec<f64> =
        observations
            .iter()
            .map(|(x, _, _)| {
                current.amplitude
                    + current.transient_amplitude
                        * current
                            .lambda
                            .powf(*x)
            })
            .collect();

    let mean_y =
        weighted_mean(observations);

    let mut sse = 0.0;
    let mut total = 0.0;

    for (index, (_, y, weight)) in
        observations.iter().enumerate()
    {
        let residual =
            *y - predicted[index];

        sse +=
            *weight * residual * residual;

        let centered =
            *y - mean_y;

        total +=
            *weight * centered * centered;
    }

    if !sse.is_finite() {
        return Err(
            LeakageRbError::FitFailed,
        );
    }

    let r_squared =
        if total > 0.0 && total.is_finite() {
            Some(
                (1.0 - sse / total)
                    .clamp(0.0, 1.0),
            )
        } else {
            None
        };

    let rmse =
        (sse / observations.len() as f64)
            .sqrt();

    if !rmse.is_finite() {
        return Err(
            LeakageRbError::FitFailed,
        );
    }

    let decay =
        current.lambda;

    let total_transfer =
        1.0 - decay;

    if !decay.is_finite()
        || decay < MIN_LAMBDA
        || decay > MAX_LAMBDA
    {
        return Err(
            LeakageRbError::InvalidDecayParameter {
                value: decay,
            },
        );
    }

    Ok(LeakageDecayFit {
        amplitude:
            current.amplitude,
        transient_amplitude:
            current.transient_amplitude,
        decay_parameter:
            decay,
        total_transfer_rate:
            total_transfer,
        weighted_residual_sum_of_squares:
            sse,
        rmse,
        r_squared,
        boundary_solution:
            boundary
                || current.amplitude <= FIT_EPSILON
                || current.transient_amplitude
                    <= FIT_EPSILON
                || (current.amplitude
                    + current.transient_amplitude)
                    >= 1.0 - FIT_EPSILON,
        converged:
            boundary
                || iterations < max_iterations
                || (right - left) <= tolerance,
        refinement_iterations:
            iterations,
    })
}

/// Internal constrained fit for a fixed lambda.
#[derive(
    Debug,
    Clone,
    Copy,
)]
struct ConstrainedFitCandidate {
    amplitude: f64,
    transient_amplitude: f64,
    lambda: f64,
    sse: f64,
}

/// Solves the constrained A/B problem at a fixed lambda.
///
/// The feasible region is the simplex:
///
/// ```text
/// A >= 0
/// B >= 0
/// A + B <= 1
/// ```
///
/// Because this is a two-parameter quadratic problem, the global constrained
/// optimum is obtained by evaluating the unconstrained solution and all
/// boundary faces.
fn fit_at_lambda(
    observations: &[(f64, f64, f64)],
    lambda: f64,
) -> Option<ConstrainedFitCandidate> {
    if !lambda.is_finite()
        || !(MIN_LAMBDA..=MAX_LAMBDA)
            .contains(&lambda)
    {
        return None;
    }

    let mut candidates =
        Vec::with_capacity(8);

    // ---------------------------------------------------------------------
    // Interior / unconstrained solution.
    // ---------------------------------------------------------------------

    let mut s_zz = 0.0;
    let mut s_z = 0.0;
    let mut s_1 = 0.0;
    let mut s_zy = 0.0;
    let mut s_y = 0.0;

    for (x, y, weight) in observations {
        let z =
            lambda.powf(*x);

        if !z.is_finite()
            || !weight.is_finite()
            || *weight <= 0.0
        {
            return None;
        }

        s_zz += *weight * z * z;
        s_z += *weight * z;
        s_1 += *weight;
        s_zy += *weight * z * *y;
        s_y += *weight * *y;
    }

    let determinant =
        s_zz * s_1 - s_z * s_z;

    if determinant.abs()
        > f64::EPSILON
            * (s_zz.abs()
                * s_1.abs()
                + s_z.abs() * s_z.abs()
                + 1.0)
    {
        let amplitude =
            (s_zy * s_1 - s_z * s_y)
                / determinant;

        let transient =
            (s_zz * s_y - s_z * s_zy)
                / determinant;

        if is_feasible(
            amplitude,
            transient,
        ) {
            candidates.push(
                candidate_for(
                    observations,
                    lambda,
                    amplitude,
                    transient,
                ),
            );
        }
    }

    // ---------------------------------------------------------------------
    // Face A = 0.
    // ---------------------------------------------------------------------

    if s_1 > 0.0 {
        let b =
            (s_y / s_1).clamp(0.0, 1.0);

        candidates.push(
            candidate_for(
                observations,
                lambda,
                0.0,
                b,
            ),
        );
    }

    // ---------------------------------------------------------------------
    // Face B = 0.
    // ---------------------------------------------------------------------

    if s_zz > 0.0 {
        let a =
            (s_zy / s_zz).clamp(0.0, 1.0);

        candidates.push(
            candidate_for(
                observations,
                lambda,
                a,
                0.0,
            ),
        );
    }

    // ---------------------------------------------------------------------
    // Face A + B = 1.
    //
    // y = 1 + B*(z - 1)
    // ---------------------------------------------------------------------

    let mut numerator = 0.0;
    let mut denominator = 0.0;

    for (x, y, weight) in observations {
        let z =
            lambda.powf(*x);

        let basis =
            z - 1.0;

        numerator +=
            *weight * basis * (*y - 1.0);

        denominator +=
            *weight * basis * basis;
    }

    if denominator > 0.0 {
        let b =
            (numerator / denominator)
                .clamp(0.0, 1.0);

        let a =
            1.0 - b;

        candidates.push(
            candidate_for(
                observations,
                lambda,
                a,
                b,
            ),
        );
    }

    // ---------------------------------------------------------------------
    // Vertices.
    // ---------------------------------------------------------------------

    candidates.push(
        candidate_for(
            observations,
            lambda,
            0.0,
            0.0,
        ),
    );

    candidates.push(
        candidate_for(
            observations,
            lambda,
            1.0,
            0.0,
        ),
    );

    candidates.push(
        candidate_for(
            observations,
            lambda,
            0.0,
            1.0,
        ),
    );

    candidates
        .into_iter()
        .filter(|candidate| {
            candidate.sse.is_finite()
        })
        .min_by(|left, right| {
            left.sse
                .partial_cmp(&right.sse)
                .unwrap_or(
                    std::cmp::Ordering::Equal,
                )
        })
}

fn candidate_for(
    observations: &[(f64, f64, f64)],
    lambda: f64,
    amplitude: f64,
    transient_amplitude: f64,
) -> ConstrainedFitCandidate {
    let mut sse = 0.0;

    for (x, y, weight) in observations {
        let prediction =
            amplitude
                + transient_amplitude
                    * lambda.powf(*x);

        let residual =
            *y - prediction;

        sse +=
            *weight * residual * residual;
    }

    ConstrainedFitCandidate {
        amplitude,
        transient_amplitude,
        lambda,
        sse,
    }
}

fn is_feasible(
    amplitude: f64,
    transient_amplitude: f64,
) -> bool {
    amplitude.is_finite()
        && transient_amplitude.is_finite()
        && amplitude >= -FIT_EPSILON
        && transient_amplitude
            >= -FIT_EPSILON
        && amplitude
            + transient_amplitude
            <= 1.0 + FIT_EPSILON
}

