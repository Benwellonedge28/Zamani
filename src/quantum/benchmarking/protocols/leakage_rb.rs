impl LeakageRbConfig {
    /// Returns a production configuration.
    pub fn production() -> Self {
        Self::default()
    }

    /// Validates the complete configuration.
    pub fn validate(&self) -> LeakageRbResult<()> {
        validate_sequence_lengths(
            &self.sequence_lengths,
            self.max_sequence_lengths,
            self.max_sequence_length,
        )?;

        if self.sequence_lengths.len()
            < MIN_SEQUENCE_LENGTHS
        {
            return Err(
                LeakageRbError::InsufficientSequenceLengths {
                    supplied: self.sequence_lengths.len(),
                    minimum: MIN_SEQUENCE_LENGTHS,
                },
            );
        }

        if self.sequences_per_length == 0
            || self.sequences_per_length
                > self.max_sequences_per_length
        {
            return Err(
                LeakageRbError::InvalidSequencesPerLength {
                    requested: self.sequences_per_length,
                    maximum: self.max_sequences_per_length,
                },
            );
        }

        if self.shots_per_sequence == 0
            || self.shots_per_sequence
                > self.max_shots_per_sequence
        {
            return Err(LeakageRbError::InvalidShots {
                requested: self.shots_per_sequence,
                maximum: self.max_shots_per_sequence,
            });
        }

        if self.computational_dimension == 0 {
            return Err(
                LeakageRbError::InvalidComputationalDimension,
            );
        }

        if self.leakage_dimension == 0 {
            return Err(
                LeakageRbError::InvalidLeakageDimension,
            );
        }

        self.computational_dimension
            .checked_add(self.leakage_dimension)
            .ok_or(
                LeakageRbError::HilbertDimensionOverflow,
            )?;

        if self.experiment_seed == 0 {
            return Err(LeakageRbError::InvalidSeed);
        }

        if !self.confidence_level.is_finite()
            || self.confidence_level <= 0.0
            || self.confidence_level >= 1.0
        {
            return Err(
                LeakageRbError::InvalidConfidenceLevel {
                    value: self.confidence_level,
                },
            );
        }

        if self.fit_grid_points < 8
            || self.fit_refinement_iterations == 0
            || !self.fit_tolerance.is_finite()
            || self.fit_tolerance <= 0.0
        {
            return Err(
                LeakageRbError::InvalidFitConfiguration,
            );
        }

        if self.max_total_shots == 0 {
            return Err(
                LeakageRbError::TotalShotLimitExceeded {
                    requested: 0,
                    maximum: 0,
                },
            );
        }

        let total_shots = self.total_shots()?;

        if total_shots < DEFAULT_MIN_TOTAL_SHOTS
            || total_shots > self.max_total_shots
        {
            return Err(
                LeakageRbError::TotalShotLimitExceeded {
                    requested: total_shots,
                    maximum: self.max_total_shots,
                },
            );
        }

        Ok(())
    }

    /// Returns the number of planned sequences.
    pub fn total_sequences(&self) -> LeakageRbResult<u128> {
        let lengths =
            self.sequence_lengths.len() as u128;

        lengths
            .checked_mul(self.sequences_per_length as u128)
            .ok_or(LeakageRbError::ResourceCalculationOverflow)
    }

    /// Returns the total planned shot count.
    pub fn total_shots(&self) -> LeakageRbResult<u128> {
        self.total_sequences()?
            .checked_mul(self.shots_per_sequence as u128)
            .ok_or(LeakageRbError::ResourceCalculationOverflow)
    }

    /// Returns the total computational Hilbert-space dimension.
    pub fn total_dimension(&self) -> LeakageRbResult<usize> {
        self.computational_dimension
            .checked_add(self.leakage_dimension)
            .ok_or(
                LeakageRbError::HilbertDimensionOverflow,
            )
    }
}

