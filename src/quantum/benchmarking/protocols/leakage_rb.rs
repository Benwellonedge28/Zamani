/// One captured LRB sequence observation.
///
/// Counts are preferred over probabilities because counts retain the original
/// experimental information and permit exact aggregation.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Serialize,
    Deserialize,
)]
pub struct LeakageRbObservation {
    /// Sequence length.
    pub sequence_length: usize,

    /// Sequence index within this length.
    pub sequence_index: usize,

    /// Number of computational-subspace outcomes.
    pub computational_count: u64,

    /// Number of leakage-subspace outcomes.
    pub leakage_count: u64,

    /// Number of outcomes not classified into either subspace.
    ///
    /// This permits measurement adapters to preserve incomplete classification
    /// instead of silently assigning events to a physical subspace.
    pub unclassified_count: u64,

    /// Total shots.
    pub shots: u64,
}

impl LeakageRbObservation {
    /// Constructs an observation using computational and leakage counts.
    pub fn new(
        sequence_length: usize,
        sequence_index: usize,
        computational_count: u64,
        leakage_count: u64,
        unclassified_count: u64,
        shots: u64,
    ) -> LeakageRbResult<Self> {
        let observation = Self {
            sequence_length,
            sequence_index,
            computational_count,
            leakage_count,
            unclassified_count,
            shots,
        };

        observation.validate()?;

        Ok(observation)
    }

    /// Constructs a computational-subspace observation.
    ///
    /// `computational_count` is the number of shots classified as remaining
    /// inside the computational subspace.
    pub fn computational_only(
        sequence_length: usize,
        sequence_index: usize,
        computational_count: u64,
        shots: u64,
    ) -> LeakageRbResult<Self> {
        Self::new(
            sequence_length,
            sequence_index,
            computational_count,
            0,
            shots
                .checked_sub(computational_count)
                .ok_or(
                    LeakageRbError::InvalidObservationCounts {
                        length: sequence_length,
                        computational:
                            computational_count,
                        leakage: 0,
                        unclassified: 0,
                        shots,
                    },
                )?,
            shots,
        )
    }

    /// Constructs a direct-leakage observation.
    pub fn leakage_only(
        sequence_length: usize,
        sequence_index: usize,
        leakage_count: u64,
        shots: u64,
    ) -> LeakageRbResult<Self> {
        Self::new(
            sequence_length,
            sequence_index,
            0,
            leakage_count,
            shots
                .checked_sub(leakage_count)
                .ok_or(
                    LeakageRbError::InvalidObservationCounts {
                        length: sequence_length,
                        computational: 0,
                        leakage: leakage_count,
                        unclassified: 0,
                        shots,
                    },
                )?,
            shots,
        )
    }

    /// Validates count conservation and probability domains.
    pub fn validate(&self) -> LeakageRbResult<()> {
        if self.sequence_length == 0 {
            return Err(
                LeakageRbError::InvalidSequenceLength {
                    length: self.sequence_length,
                },
            );
        }

        let classified = self
            .computational_count
            .checked_add(self.leakage_count)
            .and_then(|value| {
                value.checked_add(self.unclassified_count)
            })
            .ok_or(
                LeakageRbError::ResourceCalculationOverflow,
            )?;

        if self.shots == 0
            || classified != self.shots
        {
            return Err(
                LeakageRbError::InvalidObservationCounts {
                    length: self.sequence_length,
                    computational:
                        self.computational_count,
                    leakage: self.leakage_count,
                    unclassified:
                        self.unclassified_count,
                    shots: self.shots,
                },
            );
        }

        Ok(())
    }

    /// Returns the computational-subspace probability.
    pub fn computational_probability(
        &self,
    ) -> f64 {
        self.computational_count as f64
            / self.shots as f64
    }

    /// Returns the leakage probability.
    pub fn leakage_probability(
        &self,
    ) -> f64 {
        self.leakage_count as f64 / self.shots as f64
    }

    /// Returns the unclassified probability.
    pub fn unclassified_probability(
        &self,
    ) -> f64 {
        self.unclassified_count as f64
            / self.shots as f64
    }
}

