//! Zamani Quantum Benchmarking — Leakage Randomized Benchmarking
//!
//! Production Leakage Randomized Benchmarking (LRB) protocol.
//!
//! # Responsibility
//!
//! This module owns the protocol-level semantics of leakage randomized
//! benchmarking:
//!
//! - LRB configuration;
//! - workload/resource validation;
//! - deterministic experiment planning;
//! - sequence-length planning;
//! - leakage-aware observation normalization;
//! - computational-subspace population aggregation;
//! - direct leakage-population aggregation;
//! - constrained exponential decay fitting;
//! - leakage-rate estimation;
//! - seepage-rate estimation;
//! - leakage+seepage decay diagnostics;
//! - protocol assumptions and validity warnings;
//! - reproducibility metadata;
//! - offline re-analysis of captured observations.
//!
//! It deliberately does NOT own:
//!
//! - Quantum IR;
//! - Clifford-group mathematics;
//! - physical gate construction;
//! - routing;
//! - scheduling;
//! - calibration;
//! - backend selection;
//! - hardware communication;
//! - simulator implementation;
//! - generic benchmark result serialization;
//! - generic benchmark reporting;
//! - generic benchmark registry;
//! - generic QEC execution.
//!
//! The intended dependency direction is:
//!
//! ```text
//! generators::clifford
//!          │
//!          ▼
//! leakage_rb
//!          │
//!     ┌────┴─────────────┐
//!     ▼                  ▼
//! execution          statistics
//!     │                  │
//!     ▼                  ▼
//! Quantum IR        regression
//!     │
//!     ▼
//! routing / scheduling / hardware / runtime
//! ```
//!
//! This file intentionally defines its protocol-level contracts without
//! importing those downstream layers. This permits the protocol to be
//! completed and tested independently.
//!
//! # Scientific model
//!
//! Leakage is population leaving the computational subspace and entering a
//! leakage subspace. Seepage is population returning from the leakage
//! subspace to the computational subspace.
//!
//! The canonical Wood–Gambetta LRB model is:
//!
//! ```text
//! P_comp(m) = A + B * lambda1^m
//! ```
//!
//! with:
//!
//! ```text
//! L1 = (1 - A) * (1 - lambda1)
//! L2 = A * (1 - lambda1)
//! ```
//!
//! and therefore:
//!
//! ```text
//! lambda1 = 1 - L1 - L2
//! ```
//!
//! `L1` is the average leakage rate per randomized Clifford operation and
//! `L2` is the average seepage rate per randomized Clifford operation under
//! the LRB model.
//!
//! These quantities must NOT be interpreted as architecture-independent
//! physical truths when the model assumptions are violated.
//!
//! # Required LRB assumptions
//!
//! The standard protocol assumes, in addition to ordinary RB requirements:
//!
//! 1. the randomized gate set acts as a suitable 2-design on the computational
//!    subspace;
//! 2. twirling suppresses relevant computational/leakage coherences;
//! 3. population in the leakage subspace is sufficiently depolarized for the
//!    effective two-state leakage model;
//! 4. the leakage dynamics are sufficiently stationary over the experiment;
//! 5. the measurement used to estimate computational-subspace population is
//!    stable and correctly normalized.
//!
//! Violations are reported through structured warnings rather than silently
//! producing a result that looks more certain than the experiment warrants.
//!
//! # Measurement models
//!
//! The protocol supports three measurement modes:
//!
//! ```text
//! ComputationalSubspace
//!     measure P_comp directly
//!
//! DirectLeakage
//!     measure P_leak directly
//!
//! Both
//!     measure both P_comp and P_leak
//! ```
//!
//! `DirectLeakage` is normalized internally through:
//!
//! ```text
//! P_comp = 1 - P_leak
//! ```
//!
//! when the measurement is complete and normalized.
//!
//! # Multi-level leakage
//!
//! The protocol does not assume a single leakage level such as |2>.
//!
//! A backend may classify:
//!
//! ```text
//! computational = {|0>, |1>}
//! leakage       = {|2>, |3>, ...}
//! ```
//!
//! or, for a larger logical system:
//!
//! ```text
//! computational subspace dimension = d_c
//! leakage subspace dimension       = d_l
//! ```
//!
//! The measurement adapter is responsible for classifying physical outcomes.
//!
//! # Sequence generation boundary
//!
//! This module does not reimplement Clifford algebra.
//!
//! `LeakageRbSequencePlan` contains the deterministic information required by
//! the existing Clifford generator:
//!
//! - sequence length;
//! - sequence index;
//! - deterministic seed;
//! - recovery requirement.
//!
//! The actual Clifford sequence must be generated by
//! `benchmarking::generators::clifford`.
//!
//! This prevents the leakage protocol from accidentally implementing a second,
//! statistically incompatible Clifford sampler.
//!
//! # Resource safety
//!
//! All user-controlled multiplicative quantities are checked before
//! multiplication:
//!
//! ```text
//! sequence_lengths
//! × sequences_per_length
//! × shots_per_sequence
//! ```
//!
//! Overflow is rejected.
//!
//! The protocol also has explicit configurable workload limits.
//!
//! # Reproducibility
//!
//! No process-global RNG is used.
//!
//! The sequence seed is deterministically derived from:
//!
//! ```text
//! experiment_seed
//! benchmark version
//! sequence length
//! sequence index
//! ```
//!
//! This allows a sequence plan to be reconstructed independently of the
//! execution backend.
//!
//! # Rust compatibility
//!
//! Target:
//!
//! - Rust 1.97
//! - Rust 1.97.1
//! - Rust 2021
//!
//! No nightly features are required.
//!
//! Existing repository dependencies used by this file:
//!
//! - serde
//!
//! No new crate dependency is required.
//!
//! # Integration contract
//!
//! Later modules may consume this file as follows:
//!
//! ```text
//! generators::clifford
//!          │
//!          ▼
//! LeakageRbSequencePlan
//!          │
//!          ▼
//! core::circuit / Quantum IR
//!          │
//!          ▼
//! execution
//!          │
//!          ▼
//! LeakageRbObservation
//!          │
//!          ▼
//! LeakageRbAnalyzer
//!          │
//!          ▼
//! LeakageRbResult
//!          │
//!          ├── core::result
//!          ├── metrics::leakage
//!          ├── reporting
//!          └── analysis
//! ```
//!
//! The protocol types in this file are stable protocol-level contracts.
//!
//! # References
//!
//! Primary protocol reference:
//!
//! Christopher J. Wood and Jay M. Gambetta,
//! "Quantification and Characterization of Leakage Errors",
//! Physical Review A 97, 032306 (2018).
//!
//! The implementation also accommodates the broader modern LRB direction in
//! which leakage benchmarking is applied to multi-qubit systems and does not
//! require direct operations on leakage states when an appropriate
//! computational-subspace measurement is available.

