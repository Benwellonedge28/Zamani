/// Deterministically derives a sequence seed.
///
/// SplitMix64-style mixing is used only for deterministic domain separation;
/// it is NOT a cryptographic random-number generator.
fn derive_sequence_seed(
    experiment_seed: u64,
    sequence_length: usize,
    sequence_index: usize,
) -> u64 {
    let mut value =
        experiment_seed
            ^ 0x9E37_79B9_7F4A_7C15;

    value = splitmix64(
        value
            ^ sequence_length as u64,
    );

    value = splitmix64(
        value
            ^ sequence_index as u64,
    );

    value
}

fn splitmix64(
    mut value: u64,
) -> u64 {
    value =
        value.wrapping_add(
            0x9E37_79B9_7F4A_7C15,
        );

    let mut result = value;

    result =
        (result ^ (result >> 30))
            .wrapping_mul(
                0xBF58_476D_1CE4_E5B9,
            );

    result =
        (result ^ (result >> 27))
            .wrapping_mul(
                0x94D0_49BB_1331_11EB,
            );

    result ^ (result >> 31)
}

