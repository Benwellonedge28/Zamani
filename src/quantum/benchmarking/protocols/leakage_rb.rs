fn build_warnings(
    config: &LeakageRbConfig,
    observations: &[LeakageRbLengthObservation],
    fit: &LeakageDecayFit,
    leakage_rate: f64,
    seepage_rate: f64,
) -> Vec<LeakageRbWarning> {
    let mut warnings =
        Vec::with_capacity(8);

    if !config.assumptions.are_satisfied() {
        warnings.push(
            LeakageRbWarning::AssumptionsNotSatisfied,
        );
    }

    if observations
        .iter()
        .any(|observation| {
            observation.unclassified_count > 0
        })
    {
        warnings.push(
            LeakageRbWarning::UnclassifiedOutcomesPresent,
        );
    }

    if matches!(
        config.measurement_mode,
        LeakageMeasurementMode::DirectLeakage
    ) {
        warnings.push(
            LeakageRbWarning::DerivedComputationalPopulation,
        );
    }

    if leakage_rate <= 1.0e-12 {
        warnings.push(
            LeakageRbWarning::LeakageRateNearZero,
        );
    }

    if seepage_rate <= 1.0e-12 {
        warnings.push(
            LeakageRbWarning::SeepageRateNearZero,
        );
    }

    if fit.decay_parameter
        >= 1.0 - 1.0e-8
    {
        warnings.push(
            LeakageRbWarning::DecayNearUnity,
        );
    }

    if fit.decay_parameter
        <= 1.0e-8
    {
        warnings.push(
            LeakageRbWarning::DecayNearZero,
        );
    }

    if fit.boundary_solution {
        warnings.push(
            LeakageRbWarning::BoundarySolution,
        );
    }

    if observations
        .iter()
        .any(|observation| {
            observation.sequence_count < 2
        })
    {
        warnings.push(
            LeakageRbWarning::LowSequenceReplication,
        );
    }

    if fit.r_squared
        .map(|value| value < 0.90)
        .unwrap_or(false)
    {
        warnings.push(
            LeakageRbWarning::PoorFitQuality,
        );
    }

    if fit.refinement_iterations == 0 {
        warnings.push(
            LeakageRbWarning::BoundarySolution,
        );
    }

    // Measurement-induced leakage is an explicit concern for many physical
    // systems. The protocol cannot determine this automatically, so the
    // warning is not emitted unconditionally. The caller can represent it
    // through the scientific assumption/telemetry layer.
    let _ = &config.assumptions;

    warnings
}

