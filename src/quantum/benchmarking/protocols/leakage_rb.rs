/// Constrained LRB exponential model.
///
/// ```text
/// y(m) = A + B * lambda^m
/// ```
///
/// Physical constraints:
///
/// ```text
/// A >= 0
/// B >= 0
/// A + B <= 1
/// 0 <= lambda <= 1
/// ```
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Serialize,
    Deserialize,
)]
pub struct LeakageDecayFit {
    /// Fitted asymptote A.
    pub amplitude: f64,

    /// Fitted transient coefficient B.
    pub transient_amplitude: f64,

    /// Fitted decay parameter lambda1.
    pub decay_parameter: f64,

    /// Equivalent per-step leakage-plus-seepage rate.
    pub total_transfer_rate: f64,

    /// Weighted sum of squared residuals.
    pub weighted_residual_sum_of_squares: f64,

    /// Root mean squared error.
    pub rmse: f64,

    /// R², if defined.
    pub r_squared: Option<f64>,

    /// Whether the fitted lambda lies at a numerical boundary.
    pub boundary_solution: bool,

    /// Whether the constrained fit converged.
    pub converged: bool,

    /// Number of refinement iterations.
    pub refinement_iterations: usize,
}

impl LeakageDecayFit {
    /// Returns the fitted leakage rate L1.
    ///
    /// Wood–Gambetta:
    ///
    /// ```text
    /// L1 = (1 - A) * (1 - lambda1)
    /// ```
    pub fn leakage_rate(
        &self,
    ) -> f64 {
        (1.0 - self.amplitude)
            * (1.0 - self.decay_parameter)
    }

    /// Returns the fitted seepage rate L2.
    ///
    /// Wood–Gambetta:
    ///
    /// ```text
    /// L2 = A * (1 - lambda1)
    /// ```
    pub fn seepage_rate(
        &self,
    ) -> f64 {
        self.amplitude
            * (1.0 - self.decay_parameter)
    }

    /// Predicts computational-subspace population at a sequence length.
    pub fn predict(
        &self,
        sequence_length: usize,
    ) -> LeakageRbResult<f64> {
        let value = self.amplitude
            + self.transient_amplitude
                * self
                    .decay_parameter
                    .powf(sequence_length as f64);

        validate_probability(
            "predicted_computational_probability",
            value,
        )?;

        Ok(value)
    }
}

