/// Explicit scientific assumptions attached to every analysis.
#[derive(
    Debug,
    Clone,
    Copy,
    PartialEq,
    Eq,
    Serialize,
    Deserialize,
)]
pub struct LeakageRbAssumptions {
    /// Randomized operations form a suitable 2-design on the computational
    /// subspace.
    pub computational_subspace_two_design: bool,

    /// Twirling sufficiently suppresses computational/leakage coherences.
    pub coherence_twirling: bool,

    /// Leakage-subspace population is sufficiently depolarized.
    pub leakage_subspace_depolarized: bool,

    /// Leakage dynamics are sufficiently stationary.
    pub stationary_noise: bool,

    /// Measurement classification is stable over the experiment.
    pub stable_measurement: bool,

    /// Sequence recovery is mathematically correct.
    pub valid_recovery: bool,
}

impl Default for LeakageRbAssumptions {
    fn default() -> Self {
        Self {
            computational_subspace_two_design: true,
            coherence_twirling: true,
            leakage_subspace_depolarized: true,
            stationary_noise: true,
            stable_measurement: true,
            valid_recovery: true,
        }
    }
}

impl LeakageRbAssumptions {
    /// Returns whether all mandatory assumptions have been declared satisfied.
    pub const fn are_satisfied(self) -> bool {
        self.computational_subspace_two_design
            && self.coherence_twirling
            && self.leakage_subspace_depolarized
            && self.stationary_noise
            && self.stable_measurement
            && self.valid_recovery
    }
}

