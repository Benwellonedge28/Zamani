/// Deterministic collection of routing candidates.
///
/// The set owns candidates and guarantees:
///
/// - no duplicate candidate identifier;
/// - deterministic iteration;
/// - deterministic best-candidate selection when a cost model is supplied;
/// - explicit size limits.
#[derive(Debug, Clone, Default)]
pub struct CandidateSet {
    candidates: Vec<SwapCandidate>,
}

impl CandidateSet {
    /// Creates an empty candidate set.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            candidates: Vec::new(),
        }
    }

    /// Creates an empty candidate set with a bounded allocation capacity.
    ///
    /// The requested capacity is clamped to `MAX_CANDIDATES`.
    #[must_use]
    pub fn with_capacity(capacity: usize) -> Self {
        let bounded = capacity.min(MAX_CANDIDATES);

        Self {
            candidates: Vec::with_capacity(bounded),
        }
    }

    /// Returns the number of candidates.
    #[must_use]
    pub fn len(&self) -> usize {
        self.candidates.len()
    }

    /// Returns whether the set is empty.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.candidates.is_empty()
    }

    /// Returns the candidates in deterministic order.
    #[must_use]
    pub fn as_slice(&self) -> &[SwapCandidate] {
        &self.candidates
    }

    /// Consumes the set and returns its candidate vector.
    #[must_use]
    pub fn into_vec(self) -> Vec<SwapCandidate> {
        self.candidates
    }

    /// Returns a candidate by stable identifier.
    #[must_use]
    pub fn get(
        &self,
        id: CandidateId,
    ) -> Option<&SwapCandidate> {
        self.candidates.iter().find(|candidate| candidate.id() == id)
    }

    /// Inserts a candidate.
    ///
    /// Duplicate identifiers are rejected rather than silently replacing an
    /// existing candidate.
    pub fn push(
        &mut self,
        candidate: SwapCandidate,
        maximum: usize,
    ) -> RoutingResult<()> {
        let limit = maximum.min(MAX_CANDIDATES);

        if limit == 0 {
            return Err(CandidateError::CandidateLimitExceeded {
                limit: 0,
            }
            .into());
        }

        if self.candidates.iter().any(|existing| {
            existing.id() == candidate.id()
        }) {
            return Ok(());
        }

        if self.candidates.len() >= limit {
            return Err(CandidateError::CandidateLimitExceeded {
                limit,
            }
            .into());
        }

        candidate.validate()?;

        self.candidates.push(candidate);

        Ok(())
    }

    /// Sorts candidates using their deterministic structural identity.
    pub fn sort_deterministically(&mut self) {
        self.candidates.sort_unstable_by_key(|candidate| {
            candidate.tie_break_key()
        });
    }

    /// Sorts candidates using a supplied cost model.
    ///
    /// Candidates without an evaluated cost are evaluated exactly once.
    ///
    /// If two candidates have equal semantic cost, their physical endpoint
    /// ordering is used as the deterministic tie-break.
    pub fn sort_by_cost(
        &mut self,
        cost_model: &dyn CostModel,
    ) -> RoutingResult<()> {
        for candidate in &mut self.candidates {
            if candidate.cost.is_none() {
                let evaluated = cost_model.evaluate(
                    &candidate.as_cost_candidate(),
                )?;

                candidate.cost = Some(evaluated);
            }
        }

        let mut comparison_error: Option<CandidateError> = None;

        self.candidates.sort_unstable_by(|left, right| {
            let left_cost = match left.cost {
                Some(cost) => cost,
                None => {
                    comparison_error =
                        Some(CandidateError::ScoreEvaluationFailed {
                            detail:
                                "candidate has no evaluated cost after cost-model evaluation"
                                    .to_string(),
                        });

                    return Ordering::Equal;
                }
            };

            let right_cost = match right.cost {
                Some(cost) => cost,
                None => {
                    comparison_error =
                        Some(CandidateError::ScoreEvaluationFailed {
                            detail:
                                "candidate has no evaluated cost after cost-model evaluation"
                                    .to_string(),
                        });

                    return Ordering::Equal;
                }
            };

            match cost_model.compare(&left_cost, &right_cost) {
                Ok(Ordering::Equal) => {
                    left.tie_break_key()
                        .cmp(&right.tie_break_key())
                }

                Ok(ordering) => ordering,

                Err(error) => {
                    comparison_error =
                        Some(CandidateError::ScoreEvaluationFailed {
                            detail: error.to_string(),
                        });

                    Ordering::Equal
                }
            }
        });

        if let Some(error) = comparison_error {
            return Err(error.into());
        }

        Ok(())
    }

    /// Returns the best candidate according to the supplied cost model.
    ///
    /// The set does not need to be sorted first.
    pub fn best(
        &self,
        cost_model: &dyn CostModel,
    ) -> RoutingResult<Option<&SwapCandidate>> {
        let mut best: Option<&SwapCandidate> = None;

        for candidate in &self.candidates {
            let candidate_cost = match candidate.cost {
                Some(cost) => cost,
                None => cost_model.evaluate(
                    &candidate.as_cost_candidate(),
                )?,
            };

            match best {
                None => {
                    best = Some(candidate);
                }

                Some(current) => {
                    let current_cost = match current.cost {
                        Some(cost) => cost,
                        None => cost_model.evaluate(
                            &current.as_cost_candidate(),
                        )?,
                    };

                    match cost_model.compare(
                        &candidate_cost,
                        &current_cost,
                    )? {
                        Ordering::Less => {
                            best = Some(candidate);
                        }

                        Ordering::Equal => {
                            if candidate.tie_break_key()
                                < current.tie_break_key()
                            {
                                best = Some(candidate);
                            }
                        }

                        Ordering::Greater => {}
                    }
                }
            }
        }

        Ok(best)
    }

    /// Returns the candidate with the lowest deterministic structural key.
    ///
    /// This is useful for deterministic baseline routing without a cost model.
    #[must_use]
    pub fn first_deterministic(&self) -> Option<&SwapCandidate> {
        self.candidates.iter().min_by_key(|candidate| {
            candidate.tie_break_key()
        })
    }
}

impl<'a> IntoIterator for &'a CandidateSet {
    type Item = &'a SwapCandidate;
    type IntoIter = std::slice::Iter<'a, SwapCandidate>;

    fn into_iter(self) -> Self::IntoIter {
        self.candidates.iter()
    }
}

