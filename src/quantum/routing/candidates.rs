/// Immutable routing candidate.
///
/// A candidate contains:
///
/// - its stable identity;
/// - its physical movement;
/// - the predicted routing metrics;
/// - optional evaluated cost.
///
/// It contains no mutable mapping and no topology-owned state.
///
/// # Important semantic property
///
/// A `SwapCandidate` is a *proposal*, not an already-applied SWAP.
///
/// The actual routing algorithm decides whether to commit it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SwapCandidate {
    /// Stable structural candidate identifier.
    id: CandidateId,

    /// Physical movement represented by this candidate.
    movement: CandidateMove,

    /// Predicted metrics after applying the movement.
    metrics: RoutingMetrics,

    /// Optional cost-model evaluation.
    cost: Option<RoutingCost>,

    /// Front-layer heuristic distance after the hypothetical movement.
    front_layer_distance: u64,

    /// Extended/lookahead heuristic distance after the hypothetical movement.
    extended_layer_distance: u64,

    /// Fixed-point decay factor associated with this candidate.
    decay_factor: u64,
}

impl SwapCandidate {
    /// Creates a candidate without cost-model evaluation.
    ///
    /// This constructor is useful for routing algorithms that perform their
    /// own scoring.
    pub fn new(
        movement: CandidateMove,
        metrics: RoutingMetrics,
        front_layer_distance: u64,
        extended_layer_distance: u64,
        front_layer_size: u64,
        extended_layer_size: u64,
        decay_factor: u64,
    ) -> RoutingResult<Self> {
        let id = CandidateId::from_move(movement);

        let cost_candidate = CostCandidate::new(metrics)
            .with_front_layer(
                front_layer_distance,
                front_layer_size,
            )
            .with_extended_layer(
                extended_layer_distance,
                extended_layer_size,
            )
            .with_decay_factor(decay_factor);

        cost_candidate.validate()?;

        Ok(Self {
            id,
            movement,
            metrics,
            cost: None,
            front_layer_distance,
            extended_layer_distance,
            decay_factor,
        })
    }

    /// Returns the stable candidate identifier.
    #[must_use]
    pub const fn id(&self) -> CandidateId {
        self.id
    }

    /// Returns the physical movement.
    #[must_use]
    pub const fn movement(&self) -> CandidateMove {
        self.movement
    }

    /// Returns the candidate's physical endpoint `a`.
    #[must_use]
    pub const fn a(&self) -> PhysicalQubitId {
        self.movement.a()
    }

    /// Returns the candidate's physical endpoint `b`.
    #[must_use]
    pub const fn b(&self) -> PhysicalQubitId {
        self.movement.b()
    }

    /// Returns predicted routing metrics.
    #[must_use]
    pub const fn metrics(&self) -> RoutingMetrics {
        self.metrics
    }

    /// Returns the evaluated cost, if one has been attached.
    #[must_use]
    pub const fn cost(&self) -> Option<RoutingCost> {
        self.cost
    }

    /// Returns the front-layer heuristic distance.
    #[must_use]
    pub const fn front_layer_distance(&self) -> u64 {
        self.front_layer_distance
    }

    /// Returns the extended-layer heuristic distance.
    #[must_use]
    pub const fn extended_layer_distance(&self) -> u64 {
        self.extended_layer_distance
    }

    /// Returns the fixed-point decay factor.
    #[must_use]
    pub const fn decay_factor(&self) -> u64 {
        self.decay_factor
    }

    /// Returns a candidate with an evaluated routing cost.
    ///
    /// The original candidate remains immutable; this creates a new value.
    pub fn with_cost(
        mut self,
        cost_model: &dyn CostModel,
    ) -> RoutingResult<Self> {
        let cost_candidate = CostCandidate::new(self.metrics)
            .with_front_layer(
                self.front_layer_distance,
                self.metrics.gate_count,
            )
            .with_extended_layer(
                self.extended_layer_distance,
                0,
            )
            .with_decay_factor(self.decay_factor);

        let cost = cost_model.evaluate(&cost_candidate)?;

        self.cost = Some(cost);

        Ok(self)
    }

    /// Returns the `CostCandidate` representation used by `cost.rs`.
    #[must_use]
    pub fn as_cost_candidate(&self) -> CostCandidate {
        CostCandidate::new(self.metrics)
            .with_front_layer(
                self.front_layer_distance,
                self.metrics.gate_count,
            )
            .with_extended_layer(
                self.extended_layer_distance,
                0,
            )
            .with_decay_factor(self.decay_factor)
    }

    /// Validates candidate invariants.
    pub fn validate(&self) -> RoutingResult<()> {
        if self.a() == self.b() {
            return Err(CandidateError::InvalidEdge {
                a: self.a().index(),
                b: self.b().index(),
            }
            .into());
        }

        if self.decay_factor == 0 {
            return Err(CandidateError::ScoreEvaluationFailed {
                detail: "candidate decay factor cannot be zero".to_string(),
            }
            .into());
        }

        self.metrics.validate()?;

        let cost_candidate = self.as_cost_candidate();
        cost_candidate.validate()?;

        Ok(())
    }

    /// Returns a deterministic candidate tie-break key.
    ///
    /// Cost models decide the semantic objective. This key is only used after
    /// objective comparison reports equality.
    #[must_use]
    pub const fn tie_break_key(
        &self,
    ) -> (PhysicalQubitId, PhysicalQubitId) {
        (self.a(), self.b())
    }
}

