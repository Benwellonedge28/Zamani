/// Candidate-generation policy.
///
/// This configuration is intentionally narrower than `RoutingConfig`.
///
/// `RoutingConfig` controls the complete routing algorithm.
/// `CandidateGenerationConfig` controls only the generation primitive.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct CandidateGenerationConfig {
    /// Maximum number of candidates to generate.
    pub max_candidates: usize,

    /// Whether a SWAP must connect two mutually reachable physical endpoints.
    ///
    /// For a physical SWAP, both directions must be executable as movement.
    /// Therefore this should normally remain `true`.
    pub require_bidirectional_edge: bool,

    /// Whether an empty physical endpoint may participate in a candidate.
    ///
    /// Allowing this is useful for movement into an unoccupied physical
    /// location if a future movement implementation supports it. For actual
    /// SWAP semantics, both endpoints normally represent physical resources,
    /// so the default is `true`.
    pub allow_unoccupied_endpoint: bool,

    /// Whether the candidate generator should evaluate candidates using a
    /// supplied cost model.
    ///
    /// The generator can still be used without a model; the algorithm may
    /// evaluate candidates later.
    pub evaluate_cost: bool,

    /// Fixed-point decay factor passed to `CostCandidate`.
    pub decay_factor: u64,

    /// Maximum number of front/extended interactions used during scoring.
    ///
    /// This bounds work for hostile or accidentally enormous inputs.
    pub max_interactions: usize,
}

impl Default for CandidateGenerationConfig {
    fn default() -> Self {
        Self {
            max_candidates: DEFAULT_MAX_CANDIDATES,
            require_bidirectional_edge: true,
            allow_unoccupied_endpoint: true,
            evaluate_cost: false,
            decay_factor: DEFAULT_DECAY_FACTOR,
            max_interactions: DEFAULT_MAX_INTERACTIONS,
        }
    }
}

impl CandidateGenerationConfig {
    /// Validates the generation policy.
    pub fn validate(self) -> RoutingResult<()> {
        if self.max_candidates == 0 {
            return Err(CandidateError::CandidateLimitExceeded {
                limit: 0,
            }
            .into());
        }

        if self.max_candidates > MAX_CANDIDATES {
            return Err(CandidateError::CandidateLimitExceeded {
                limit: MAX_CANDIDATES,
            }
            .into());
        }

        if self.decay_factor == 0 {
            return Err(CandidateError::ScoreEvaluationFailed {
                detail: "decay factor cannot be zero".to_string(),
            }
            .into());
        }

        if self.max_interactions == 0 {
            return Err(CandidateError::ScoreEvaluationFailed {
                detail: "maximum interaction count cannot be zero".to_string(),
            }
            .into());
        }

        Ok(())
    }
}

