/// Production candidate generator.
///
/// `CandidateGenerator` is intentionally stateless.
///
/// This is important because:
///
/// - routing algorithms may reuse one generator across iterations;
/// - parallel trials must not share mutable candidate state;
/// - deterministic behavior is easier to guarantee;
/// - topology/mapping remain the source of truth.
///
/// All routing state is supplied through [`CandidateContext`].
#[derive(Debug, Clone, Copy, Default)]
pub struct CandidateGenerator;

impl CandidateGenerator {
    /// Creates a stateless candidate generator.
    #[must_use]
    pub const fn new() -> Self {
        Self
    }

    /// Generates all legal SWAP candidates touching at least one currently
    /// occupied physical qubit.
    ///
    /// This is the general-purpose candidate-generation entry point.
    ///
    /// # Important
    ///
    /// The mapping is never mutated.
    pub fn generate(
        &self,
        context: &CandidateContext<'_>,
        config: CandidateGenerationConfig,
        distance_provider: &dyn CandidateDistanceProvider,
        cost_model: Option<&dyn CostModel>,
    ) -> RoutingResult<CandidateSet> {
        config.validate()?;

        validate_context(context)?;

        let mut candidate_edges = BTreeSet::new();

        self.collect_mapping_adjacent_edges(
            context,
            config,
            &mut candidate_edges,
        )?;

        if candidate_edges.is_empty() {
            return Err(CandidateError::EmptyCandidateSet.into());
        }

        let mut candidates = CandidateSet::with_capacity(
            candidate_edges.len().min(config.max_candidates),
        );

        for (a, b) in candidate_edges {
            if candidates.len() >= config.max_candidates {
                break;
            }

            let movement = match CandidateMove::swap(a, b) {
                Some(movement) => movement,
                None => {
                    return Err(CandidateError::InvalidEdge {
                        a: a.index(),
                        b: b.index(),
                    }
                    .into());
                }
            };

            if !self.is_legal_swap(
                context.topology,
                a,
                b,
                config,
            ) {
                continue;
            }

            let candidate = self.build_candidate(
                context,
                movement,
                config,
                distance_provider,
            )?;

            let candidate = if config.evaluate_cost {
                match cost_model {
                    Some(model) => candidate.with_cost(model)?,

                    None => {
                        return Err(
                            CandidateError::ScoreEvaluationFailed {
                                detail:
                                    "candidate cost evaluation was requested but no cost model was supplied"
                                        .to_string(),
                            }
                            .into(),
                        );
                    }
                }
            } else {
                candidate
            };

            candidates.push(
                candidate,
                config.max_candidates,
            )?;
        }

        if candidates.is_empty() {
            return Err(CandidateError::EmptyCandidateSet.into());
        }

        candidates.sort_deterministically();

        Ok(candidates)
    }

    /// Generates candidates touching the physical locations occupied by the
    /// logical qubits in the front layer.
    ///
    /// This is the preferred entry point for SABRE/lookahead-style routing.
    pub fn generate_for_front_layer(
        &self,
        context: &CandidateContext<'_>,
        config: CandidateGenerationConfig,
        distance_provider: &dyn CandidateDistanceProvider,
        cost_model: Option<&dyn CostModel>,
    ) -> RoutingResult<CandidateSet> {
        config.validate()?;
        validate_context(context)?;

        let mut physical_frontier = BTreeSet::new();

        for interaction in context.front_layer {
            for &logical in interaction.operands() {
                let physical = context
                    .mapping
                    .physical_of(logical)
                    .ok_or_else(|| {
                        CandidateError::MappingConflict {
                            a: logical.index(),
                            b: logical.index(),
                        }
                    })?;

                physical_frontier.insert(physical);
            }
        }

        if physical_frontier.is_empty() {
            return Err(CandidateError::EmptyCandidateSet.into());
        }

        let mut candidate_edges = BTreeSet::new();

        for physical in physical_frontier {
            for neighbour in context.topology.neighbors(physical) {
                let (a, b) = canonical_edge(physical, neighbour);

                candidate_edges.insert((a, b));

                if candidate_edges.len() >= MAX_CANDIDATES {
                    return Err(
                        CandidateError::CandidateLimitExceeded {
                            limit: MAX_CANDIDATES,
                        }
                        .into(),
                    );
                }
            }
        }

        self.materialize_candidates(
            context,
            config,
            distance_provider,
            cost_model,
            candidate_edges,
        )
    }

    /// Generates candidates touching both operands of a specific interaction.
    ///
    /// This is particularly useful for greedy and shortest-path routing.
    pub fn generate_for_interaction(
        &self,
        context: &CandidateContext<'_>,
        interaction: &QubitInteraction,
        config: CandidateGenerationConfig,
        distance_provider: &dyn CandidateDistanceProvider,
        cost_model: Option<&dyn CostModel>,
    ) -> RoutingResult<CandidateSet> {
        config.validate()?;
        validate_context(context)?;

        if interaction.arity() != 2 {
            return Err(CandidateError::ScoreEvaluationFailed {
                detail: format!(
                    "candidate generation for a single interaction requires \
                     exactly two logical operands; received {}",
                    interaction.arity()
                ),
            }
            .into());
        }

        let logical_a = interaction.operands()[0];
        let logical_b = interaction.operands()[1];

        let physical_a = context
            .mapping
            .physical_of(logical_a)
            .ok_or_else(|| CandidateError::MappingConflict {
                a: logical_a.index(),
                b: logical_b.index(),
            })?;

        let physical_b = context
            .mapping
            .physical_of(logical_b)
            .ok_or_else(|| CandidateError::MappingConflict {
                a: logical_a.index(),
                b: logical_b.index(),
            })?;

        let mut candidate_edges = BTreeSet::new();

        for neighbour in context.topology.neighbors(physical_a) {
            let (a, b) = canonical_edge(physical_a, neighbour);
            candidate_edges.insert((a, b));
        }

        for neighbour in context.topology.neighbors(physical_b) {
            let (a, b) = canonical_edge(physical_b, neighbour);
            candidate_edges.insert((a, b));
        }

        self.materialize_candidates(
            context,
            config,
            distance_provider,
            cost_model,
            candidate_edges,
        )
    }

    /// Returns whether a physical edge can represent a SWAP movement.
    ///
    /// A directed physical connection is not sufficient for a symmetric SWAP.
    /// Unless a future movement/lowering layer explicitly provides a directed
    /// SWAP decomposition, candidate generation requires bidirectional
    /// structural adjacency.
    #[must_use]
    pub fn is_legal_swap(
        &self,
        topology: &PhysicalTopology,
        a: PhysicalQubitId,
        b: PhysicalQubitId,
        config: CandidateGenerationConfig,
    ) -> bool {
        if a == b {
            return false;
        }

        if !topology.contains(a) || !topology.contains(b) {
            return false;
        }

        if !topology.is_available(a)
            || !topology.is_available(b)
        {
            return false;
        }

        if config.require_bidirectional_edge {
            topology.is_bidirectionally_adjacent(a, b)
        } else {
            topology.is_adjacent(a, b)
                || topology.is_adjacent(b, a)
        }
    }

    /// Hypothetically applies a SWAP to a logical qubit's physical location.
    ///
    /// This method never mutates the mapping.
    #[must_use]
    pub fn project_logical_location(
        &self,
        mapping: &QubitMapping,
        logical: LogicalQubitId,
        a: PhysicalQubitId,
        b: PhysicalQubitId,
    ) -> Option<PhysicalQubitId> {
        let physical = mapping.physical_of(logical)?;

        Some(
            PhysicalProjection::after_swap(
                physical,
                a,
                b,
            )
            .physical,
        )
    }

    /// Computes the distance of one interaction after a hypothetical SWAP.
    ///
    /// `None` means at least one logical operand is unmapped or the projected
    /// physical qubits are disconnected.
    pub fn projected_interaction_distance(
        &self,
        mapping: &QubitMapping,
        interaction: &QubitInteraction,
        a: PhysicalQubitId,
        b: PhysicalQubitId,
        topology: &PhysicalTopology,
        distance_provider: &dyn CandidateDistanceProvider,
    ) -> Option<u64> {
        if interaction.arity() != 2 {
            return None;
        }

        let logical_a = interaction.operands()[0];
        let logical_b = interaction.operands()[1];

        let physical_a = mapping.physical_of(logical_a)?;
        let physical_b = mapping.physical_of(logical_b)?;

        let projected_a =
            PhysicalProjection::after_swap(
                physical_a,
                a,
                b,
            )
            .physical;

        let projected_b =
            PhysicalProjection::after_swap(
                physical_b,
                a,
                b,
            )
            .physical;

        distance_provider.distance(
            topology,
            projected_a,
            projected_b,
        )
    }

    // =========================================================================
    // Internal generation
    // =========================================================================

    fn collect_mapping_adjacent_edges(
        &self,
        context: &CandidateContext<'_>,
        config: CandidateGenerationConfig,
        output: &mut BTreeSet<(
            PhysicalQubitId,
            PhysicalQubitId,
        )>,
    ) -> RoutingResult<()> {
        let mut occupied = BTreeSet::new();

        for logical in context.mapping.logical_qubits() {
            if let Some(physical) =
                context.mapping.physical_of(logical)
            {
                occupied.insert(physical);
            }
        }

        for physical in occupied {
            for neighbour in context.topology.neighbors(physical) {
                let (a, b) = canonical_edge(
                    physical,
                    neighbour,
                );

                if !self.is_legal_swap(
                    context.topology,
                    a,
                    b,
                    config,
                ) {
                    continue;
                }

                output.insert((a, b));

                if output.len() >= MAX_CANDIDATES {
                    return Err(
                        CandidateError::CandidateLimitExceeded {
                            limit: MAX_CANDIDATES,
                        }
                        .into(),
                    );
                }
            }
        }

        Ok(())
    }

    fn materialize_candidates(
        &self,
        context: &CandidateContext<'_>,
        config: CandidateGenerationConfig,
        distance_provider: &dyn CandidateDistanceProvider,
        cost_model: Option<&dyn CostModel>,
        candidate_edges: BTreeSet<(
            PhysicalQubitId,
            PhysicalQubitId,
        )>,
    ) -> RoutingResult<CandidateSet> {
        let mut candidates = CandidateSet::with_capacity(
            candidate_edges
                .len()
                .min(config.max_candidates),
        );

        for (a, b) in candidate_edges {
            if candidates.len() >= config.max_candidates {
                break;
            }

            if !self.is_legal_swap(
                context.topology,
                a,
                b,
                config,
            ) {
                continue;
            }

            let movement = CandidateMove::swap(a, b)
                .ok_or_else(|| CandidateError::InvalidEdge {
                    a: a.index(),
                    b: b.index(),
                })?;

            let candidate = self.build_candidate(
                context,
                movement,
                config,
                distance_provider,
            )?;

            let candidate = if config.evaluate_cost {
                let model = cost_model.ok_or_else(|| {
                    CandidateError::ScoreEvaluationFailed {
                        detail:
                            "cost evaluation requested without a cost model"
                                .to_string(),
                    }
                })?;

                candidate.with_cost(model)?
            } else {
                candidate
            };

            candidates.push(
                candidate,
                config.max_candidates,
            )?;
        }

        if candidates.is_empty() {
            return Err(CandidateError::EmptyCandidateSet.into());
        }

        candidates.sort_deterministically();

        Ok(candidates)
    }

    fn build_candidate(
        &self,
        context: &CandidateContext<'_>,
        movement: CandidateMove,
        config: CandidateGenerationConfig,
        distance_provider: &dyn CandidateDistanceProvider,
    ) -> RoutingResult<SwapCandidate> {
        let (a, b) = match movement {
            CandidateMove::Swap { a, b } => (a, b),
        };

        let front_layer_distance =
            self.aggregate_layer_distance(
                context,
                context.front_layer,
                a,
                b,
                distance_provider,
                config.max_interactions,
            )?;

        let extended_layer_distance =
            self.aggregate_layer_distance(
                context,
                context.extended_layer,
                a,
                b,
                distance_provider,
                config.max_interactions,
            )?;

        let front_size = checked_len_to_u64(
            context.front_layer.len(),
            "front-layer interaction count",
        )?;

        let extended_size = checked_len_to_u64(
            context.extended_layer.len(),
            "extended-layer interaction count",
        )?;

        let interaction_distance =
            front_layer_distance
                .checked_add(extended_layer_distance)
                .ok_or_else(|| {
                    CandidateError::ScoreEvaluationFailed {
                        detail:
                            "candidate interaction-distance accumulation overflowed"
                                .to_string(),
                    }
                })?;

        let metrics = RoutingMetrics {
            swap_count: 1,
            movement_count: 1,
            gate_count: front_size
                .checked_add(extended_size)
                .ok_or_else(|| {
                    CandidateError::ScoreEvaluationFailed {
                        detail:
                            "candidate gate-count accumulation overflowed"
                                .to_string(),
                    }
                })?,
            depth: 1,
            duration_ns: 0,
            error_ppb: 0,
            fidelity_ppb: 0,
            interaction_distance,
        };

        SwapCandidate::new(
            movement,
            metrics,
            front_layer_distance,
            extended_layer_distance,
            front_size,
            extended_size,
            config.decay_factor,
        )
    }

    fn aggregate_layer_distance(
        &self,
        context: &CandidateContext<'_>,
        interactions: &[QubitInteraction],
        a: PhysicalQubitId,
        b: PhysicalQubitId,
        distance_provider: &dyn CandidateDistanceProvider,
        maximum: usize,
    ) -> RoutingResult<u64> {
        if interactions.len() > maximum {
            return Err(
                CandidateError::CandidateLimitExceeded {
                    limit: maximum,
                }
                .into(),
            );
        }

        let mut total = 0u64;

        for interaction in interactions {
            if interaction.arity() != 2 {
                // Candidate generation does not silently reinterpret a
                // multi-qubit interaction as a pair. Unsupported multi-qubit
                // decomposition belongs to another compiler stage.
                continue;
            }

            let distance =
                self.projected_interaction_distance(
                    context.mapping,
                    interaction,
                    a,
                    b,
                    context.topology,
                    distance_provider,
                );

            let distance = match distance {
                Some(value) => value,
                None => {
                    // An unreachable future interaction must not create an
                    // artificial finite score. Treating it as zero would make
                    // an impossible candidate look optimal.
                    continue;
                }
            };

            total = total.checked_add(distance).ok_or_else(|| {
                CandidateError::ScoreEvaluationFailed {
                    detail:
                        "interaction-distance accumulation overflowed"
                            .to_string(),
                }
            })?;
        }

        Ok(total)
    }
}

