/// Immutable routing context used while generating candidates.
///
/// The context deliberately contains references rather than owning routing
/// state. Candidate generation therefore cannot accidentally replace the
/// caller's topology or mapping.
///
/// The front layer is the set of interactions currently eligible for routing.
/// The extended layer contains future interactions used by lookahead/SABRE
/// heuristics.
///
/// The slices may be empty:
///
/// - an empty front layer is useful when generating generic topology moves;
/// - an empty extended layer disables future-lookahead scoring.
pub struct CandidateContext<'a> {
    /// Current physical topology.
    pub topology: &'a PhysicalTopology,

    /// Current logical-to-physical mapping.
    pub mapping: &'a QubitMapping,

    /// Interactions currently at the routing front layer.
    pub front_layer: &'a [QubitInteraction],

    /// Future interactions considered by lookahead.
    pub extended_layer: &'a [QubitInteraction],
}

impl<'a> CandidateContext<'a> {
    /// Creates a candidate-generation context.
    #[must_use]
    pub const fn new(
        topology: &'a PhysicalTopology,
        mapping: &'a QubitMapping,
        front_layer: &'a [QubitInteraction],
        extended_layer: &'a [QubitInteraction],
    ) -> Self {
        Self {
            topology,
            mapping,
            front_layer,
            extended_layer,
        }
    }

    /// Returns the number of front-layer interactions.
    #[must_use]
    pub const fn front_layer_len(&self) -> usize {
        self.front_layer.len()
    }

    /// Returns the number of extended-layer interactions.
    #[must_use]
    pub const fn extended_layer_len(&self) -> usize {
        self.extended_layer.len()
    }
}

// =============================================================================
// Distance provider
// =============================================================================

/// Provides physical interaction distance to candidate generation.
///
/// The concrete shortest-path implementation belongs in `path.rs`.
///
/// A distance provider MUST:
///
/// 1. return `Some(0)` for identical physical qubits;
/// 2. return `Some(d)` for connected physical qubits;
/// 3. return `None` for disconnected/unreachable physical qubits;
/// 4. be deterministic for deterministic topology input;
/// 5. never mutate the topology or routing state.
///
/// `candidates.rs` does not implement shortest paths because that would create
/// an architectural overlap with `path.rs`.
pub trait CandidateDistanceProvider: Send + Sync {
    /// Returns the physical distance between two qubits.
    fn distance(
        &self,
        topology: &PhysicalTopology,
        from: PhysicalQubitId,
        to: PhysicalQubitId,
    ) -> Option<u64>;
}

/// Simple callback-backed distance provider.
///
/// This adapter lets path-finding code supply a function without having to
/// create a dedicated type.
pub struct FnDistanceProvider<F> {
    function: F,
}

impl<F> FnDistanceProvider<F> {
    /// Creates a callback-backed distance provider.
    #[must_use]
    pub const fn new(function: F) -> Self {
        Self { function }
    }
}

impl<F> CandidateDistanceProvider for FnDistanceProvider<F>
where
    F: Fn(
            &PhysicalTopology,
            PhysicalQubitId,
            PhysicalQubitId,
        ) -> Option<u64>
        + Send
        + Sync,
{
    fn distance(
        &self,
        topology: &PhysicalTopology,
        from: PhysicalQubitId,
        to: PhysicalQubitId,
    ) -> Option<u64> {
        (self.function)(topology, from, to)
    }
}

// =============================================================================
// Candidate projection
// =============================================================================

/// Result of applying a candidate *hypothetically* to one physical location.
///
/// This type is internal to candidate scoring and does not mutate the real
/// mapping.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct PhysicalProjection {
    physical: PhysicalQubitId,
}

impl PhysicalProjection {
    /// Returns the physical location after a hypothetical SWAP.
    #[must_use]
    fn after_swap(
        physical: PhysicalQubitId,
        a: PhysicalQubitId,
        b: PhysicalQubitId,
    ) -> Self {
        let projected = if physical == a {
            b
        } else if physical == b {
            a
        } else {
            physical
        };

        Self {
            physical: projected,
        }
    }
}

