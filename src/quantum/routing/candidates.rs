//! Zamani Quantum Routing — Candidate Generation
//!
//! `src/quantum/routing/candidates.rs`
//!
//! Production-grade candidate generation for topology-aware quantum routing.
//!
//! # Architectural responsibility
//!
//! This module generates and deterministically ranks *possible routing moves*
//! from the current physical topology and logical-to-physical mapping.
//!
//! Its primary use cases are:
//!
//! - basic routing;
//! - shortest-path routing;
//! - lookahead routing;
//! - SABRE/LightSABRE-style routing;
//! - noise-aware routing;
//! - dynamic routing;
//! - custom routing algorithms.
//!
//! The central candidate generated by this module is a physical SWAP between
//! two currently adjacent physical qubits.
//!
//! # This module does NOT own
//!
//! - topology storage;
//! - logical-to-physical mapping storage;
//! - shortest-path algorithms;
//! - layout selection;
//! - routing orchestration;
//! - gate decomposition;
//! - hardware execution;
//! - scheduling;
//! - pulse generation;
//! - calibration acquisition;
//! - OpenQASM parsing;
//! - Quantum IR implementation details;
//! - QEC decoding;
//! - simulation.
//!
//! Those responsibilities belong to the corresponding routing/backend
//! subsystems.
//!
//! # Stable dependency direction
//!
//! ```text
//!                         types.rs
//!                            │
//!              ┌─────────────┼─────────────┐
//!              ▼             ▼             ▼
//!         topology.rs    mapping.rs      cost.rs
//!              │             │             │
//!              └─────────────┼─────────────┘
//!                            ▼
//!                      candidates.rs
//!                            │
//!                ┌───────────┼────────────┐
//!                ▼           ▼            ▼
//!             lookahead    SABRE      noise-aware
//!                │           │            │
//!                └───────────┼────────────┘
//!                            ▼
//!                          router
//! ```
//!
//! `candidates.rs` is therefore a middle-layer primitive. It must remain
//! independent of concrete routing algorithms.
//!
//! # Important design rule
//!
//! Candidate generation MUST NOT mutate the caller's mapping.
//!
//! A routing algorithm may evaluate hundreds or millions of possible moves.
//! Each candidate is a hypothetical transition. The real mapping is mutated
//! only after the routing algorithm has selected and committed a move.
//!
//! # Determinism
//!
//! Candidate generation is deterministic for deterministic inputs.
//!
//! Determinism is guaranteed by:
//!
//! - deterministic topology neighbor iteration;
//! - canonical `(a, b)` physical-edge ordering;
//! - duplicate elimination;
//! - stable candidate identifiers;
//! - deterministic score tie-breaking;
//! - no dependence on `HashMap` iteration order;
//! - no random state in this module.
//!
//! If a stochastic algorithm wants multiple trials, the algorithm layer owns
//! the seed and trial policy. This file remains deterministic.
//!
//! # Candidate semantics
//!
//! A candidate represents a *hypothetical physical movement*.
//!
//! For a SWAP candidate:
//!
//! ```text
//! physical a <────SWAP────> physical b
//! ```
//!
//! If:
//!
//! ```text
//! logical q0 -> physical a
//! logical q1 -> physical b
//! ```
//!
//! then after the hypothetical candidate:
//!
//! ```text
//! logical q0 -> physical b
//! logical q1 -> physical a
//! ```
//!
//! No actual mapping mutation occurs during generation.
//!
//! # Distance-provider boundary
//!
//! SABRE/lookahead routing needs physical interaction distances. However,
//! shortest-path computation belongs to `path.rs`, not this file.
//!
//! Therefore this module defines [`CandidateDistanceProvider`].
//!
//! `path.rs` can implement that trait later without changing this file.
//!
//! This avoids the circular dependency:
//!
//! ```text
//! candidates -> path -> candidates
//! ```
//!
//! Instead:
//!
//! ```text
//! path.rs ─────implements────► CandidateDistanceProvider
//! candidates.rs ──consumes────► CandidateDistanceProvider
//! ```
//!
//! # Cost-model boundary
//!
//! Candidate generation can optionally evaluate candidates using the stable
//! [`CostModel`] trait from `cost.rs`.
//!
//! The candidate generator constructs [`CostCandidate`] values but does not
//! implement routing objectives itself.
//!
//! # Resource safety
//!
//! Candidate generation is explicitly bounded by a maximum candidate count.
//! This prevents a malformed or unexpectedly large topology from causing an
//! unbounded allocation.
//!
//! # Rust compatibility
//!
//! Target:
//!
//! - Rust 1.97;
//! - Rust 1.97.1;
//! - Rust 2021;
//! - stable Rust;
//! - no nightly features.
//!
//! # Safety
//!
//! Unsafe Rust is forbidden.
//!
//! ```text
//! #![deny(unsafe_code)]
//! #![deny(unsafe_op_in_unsafe_fn)]
//! #![deny(unused_must_use)]
//! ```
//!
//! # File completion invariant
//!
//! This file is complete when:
//!
//! 1. candidates use typed physical identifiers;
//! 2. candidate generation never mutates the caller's mapping;
//! 3. candidate endpoints are canonicalized;
//! 4. duplicate physical edges cannot create duplicate candidates;
//! 5. unavailable qubits are excluded;
//! 6. one-way directed edges cannot silently become SWAPs;
//! 7. candidate generation is bounded;
//! 8. candidate ordering is deterministic;
//! 9. candidate identity is stable;
//! 10. front-layer and extended-layer distances can be supplied by a path
//!     provider;
//! 11. cost models can evaluate candidates without coupling to algorithms;
//! 12. arithmetic cannot silently overflow;
//! 13. empty candidate sets are represented explicitly;
//! 14. the caller's mapping remains unchanged;
//! 15. the public API does not depend on future algorithm implementations;
//! 16. no unsafe code exists;
//! 17. the file is compatible with Rust 1.97/1.97.1.

