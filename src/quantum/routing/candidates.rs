fn validate_context(
    context: &CandidateContext<'_>,
) -> RoutingResult<()> {
    context.topology.validate()?;

    for logical in context.mapping.logical_qubits() {
        let physical = context
            .mapping
            .physical_of(logical)
            .ok_or_else(|| CandidateError::MappingConflict {
                a: logical.index(),
                b: logical.index(),
            })?;

        if !context.topology.contains(physical) {
            return Err(
                CandidateError::MappingConflict {
                    a: physical.index(),
                    b: physical.index(),
                }
                .into(),
            );
        }

        if !context.topology.is_available(physical) {
            return Err(
                CandidateError::MappingConflict {
                    a: physical.index(),
                    b: physical.index(),
                }
                .into(),
            );
        }
    }

    validate_interactions(
        context.mapping,
        context.front_layer,
    )?;

    validate_interactions(
        context.mapping,
        context.extended_layer,
    )?;

    Ok(())
}

fn validate_interactions(
    mapping: &QubitMapping,
    interactions: &[QubitInteraction],
) -> RoutingResult<()> {
    for interaction in interactions {
        for &logical in interaction.operands() {
            if !mapping.contains_logical(logical) {
                return Err(
                    CandidateError::MappingConflict {
                        a: logical.index(),
                        b: logical.index(),
                    }
                    .into(),
                );
            }
        }
    }

    Ok(())
}

