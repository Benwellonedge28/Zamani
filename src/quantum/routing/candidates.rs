/// Returns a canonical physical-edge representation.
///
/// The smaller physical identifier is always placed first.
#[must_use]
pub const fn canonical_edge(
    a: PhysicalQubitId,
    b: PhysicalQubitId,
) -> (PhysicalQubitId, PhysicalQubitId) {
    if a <= b {
        (a, b)
    } else {
        (b, a)
    }
}

/// Checked conversion from `usize` to `u64`.
///
/// On all supported Rust platforms this is normally infallible, but keeping
/// the conversion checked makes the contract explicit and avoids depending on
/// target-width assumptions.
fn checked_len_to_u64(
    value: usize,
    description: &str,
) -> RoutingResult<u64> {
    u64::try_from(value).map_err(|_| {
        CandidateError::ScoreEvaluationFailed {
            detail: format!(
                "{description} exceeds u64 representable range"
            ),
        }
        .into()
    })
}

