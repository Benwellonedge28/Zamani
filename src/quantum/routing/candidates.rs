/// Conservative default maximum number of candidates returned by one
/// generation request.
///
/// The routing configuration layer also defines a candidate limit. This local
/// constant is intentionally useful for direct users of `CandidateGenerator`
/// that do not construct a full `RoutingConfig`.
pub const DEFAULT_MAX_CANDIDATES: usize = 64;

/// Maximum candidate count accepted by the candidate-generation API.
///
/// This protects direct callers from accidentally requesting an effectively
/// unbounded candidate set.
pub const MAX_CANDIDATES: usize = 1_000_000;

/// Default decay factor representing 1.0 in the fixed-point representation
/// used by `cost.rs`.
pub const DEFAULT_DECAY_FACTOR: u64 = WEIGHT_SCALE;

/// Maximum number of interactions that may be accumulated into one candidate
/// evaluation without an explicit larger caller-controlled bound.
///
/// This prevents pathological input from silently overflowing counters.
pub const DEFAULT_MAX_INTERACTIONS: usize = 1_000_000;

// =============================================================================
// Candidate kind
// =============================================================================

/// Physical movement represented by a routing candidate.
///
/// Routing currently treats SWAP as the fundamental movement primitive.
/// Future movement types can be added here without changing the candidate
/// identity, ranking, or generation contracts.
///
/// The candidate generator deliberately does not turn a SWAP into CX gates.
/// That is the responsibility of the movement/lowering stage.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum CandidateMove {
    /// Exchange the quantum states occupying two physical qubits.
    Swap {
        /// First physical endpoint.
        a: PhysicalQubitId,

        /// Second physical endpoint.
        b: PhysicalQubitId,
    },
}

impl CandidateMove {
    /// Creates a canonical SWAP candidate.
    ///
    /// Physical endpoints are normalized so that:
    ///
    /// ```text
    /// Swap(a, b)
    /// ```
    ///
    /// and:
    ///
    /// ```text
    /// Swap(b, a)
    /// ```
    ///
    /// represent the same movement.
    #[must_use]
    pub fn swap(
        a: PhysicalQubitId,
        b: PhysicalQubitId,
    ) -> Option<Self> {
        if a == b {
            return None;
        }

        let (first, second) = canonical_edge(a, b);

        Some(Self::Swap {
            a: first,
            b: second,
        })
    }

    /// Returns the first physical endpoint.
    #[must_use]
    pub const fn a(self) -> PhysicalQubitId {
        match self {
            Self::Swap { a, .. } => a,
        }
    }

    /// Returns the second physical endpoint.
    #[must_use]
    pub const fn b(self) -> PhysicalQubitId {
        match self {
            Self::Swap { b, .. } => b,
        }
    }

    /// Returns the movement kind's stable name.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Swap { .. } => "swap",
        }
    }

    /// Returns whether this movement is a SWAP.
    #[must_use]
    pub const fn is_swap(self) -> bool {
        matches!(self, Self::Swap { .. })
    }
}

impl fmt::Display for CandidateMove {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Swap { a, b } => {
                write!(formatter, "swap({a},{b})")
            }
        }
    }
}

// =============================================================================
// Candidate identifier
// =============================================================================

/// Stable identifier for a routing candidate.
///
/// The identifier is intentionally structural rather than hash-randomized.
/// It is therefore stable across executions and suitable for:
///
/// - deterministic tests;
/// - diagnostics;
/// - benchmark reports;
/// - cache keys;
/// - candidate trace output.
///
/// The current representation is sufficient for physical SWAP candidates and
/// leaves room for future movement kinds.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct CandidateId {
    /// First physical endpoint.
    pub a: PhysicalQubitId,

    /// Second physical endpoint.
    pub b: PhysicalQubitId,
}

impl CandidateId {
    /// Creates a canonical candidate identifier.
    #[must_use]
    pub fn new(
        a: PhysicalQubitId,
        b: PhysicalQubitId,
    ) -> Option<Self> {
        if a == b {
            return None;
        }

        let (a, b) = canonical_edge(a, b);

        Some(Self { a, b })
    }

    /// Creates an identifier from a movement.
    #[must_use]
    pub fn from_move(movement: CandidateMove) -> Self {
        match movement {
            CandidateMove::Swap { a, b } => {
                // `CandidateMove::swap` already canonicalizes endpoints.
                Self { a, b }
            }
        }
    }
}

impl fmt::Display for CandidateId {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "swap:{}:{}", self.a, self.b)
    }
}

