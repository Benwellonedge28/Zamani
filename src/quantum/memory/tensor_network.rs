fn complex_matrix_2x2<S: ComplexScalar>(
    parameters: &[f64],
) -> Result<[S; 4], MemoryError> {
    if parameters.len() != 8 {
        return Err(invalid_argument(
            "2x2 complex matrix requires eight real parameters",
        ));
    }

    Ok([
        complex_from_pair::<S>(parameters, 0)?,
        complex_from_pair::<S>(parameters, 2)?,
        complex_from_pair::<S>(parameters, 4)?,
        complex_from_pair::<S>(parameters, 6)?,
    ])
}

fn complex_matrix_4x4<S: ComplexScalar>(
    parameters: &[f64],
) -> Result<[S; 16], MemoryError> {
    if parameters.len() != 32 {
        return Err(invalid_argument(
            "4x4 complex matrix requires thirty-two real parameters",
        ));
    }

    let mut result = [S::zero(); 16];

    for index in 0..16 {
        result[index] = complex_from_pair(parameters, index * 2)?;
    }

    Ok(result)
}

fn complex_from_pair<S: ComplexScalar>(
    parameters: &[f64],
    offset: usize,
) -> Result<S, MemoryError> {
    let real = *parameters
        .get(offset)
        .ok_or_else(|| invalid_argument("complex matrix real component is missing"))?;

    let imaginary = *parameters
        .get(offset + 1)
        .ok_or_else(|| invalid_argument("complex matrix imaginary component is missing"))?;

    if !real.is_finite() || !imaginary.is_finite() {
        return Err(non_finite_error());
    }

    S::try_new(
        S::Real::from_f64(real)
            .ok_or_else(|| invalid_argument("matrix real component is not representable"))?,
        S::Real::from_f64(imaginary)
            .ok_or_else(|| invalid_argument("matrix imaginary component is not representable"))?,
    )
    .map_err(|_| invalid_argument("matrix contains an invalid complex scalar"))
}

fn swap_matrix<S: ComplexScalar>() -> [S; 16] {
    let zero = S::zero();
    let one = S::one();

    [
        one, zero, zero, zero,
        zero, zero, one, zero,
        zero, one, zero, zero,
        zero, zero, zero, one,
    ]
}

fn reverse_two_qubit_basis_matrix<S: ComplexScalar>(
    matrix: [S; 16],
) -> [S; 16] {
    let mut result = [S::zero(); 16];

    for output_p in 0..2 {
        for output_q in 0..2 {
            for input_p in 0..2 {
                for input_q in 0..2 {
                    let original_row = output_q * 2 + output_p;
                    let original_col = input_q * 2 + input_p;

                    let new_row = output_p * 2 + output_q;
                    let new_col = input_p * 2 + input_q;

                    result[new_row * 4 + new_col] =
                        matrix[original_row * 4 + original_col];
                }
            }
        }
    }

    result
}

