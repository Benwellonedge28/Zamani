/// Maximum Jacobi sweeps for the safe reference SVD.
pub const DEFAULT_SVD_MAX_SWEEPS: usize = 64;

/// Convergence threshold for Jacobi SVD.
pub const DEFAULT_SVD_TOLERANCE: f64 = 1.0e-12;

struct SvdResult<S: ComplexScalar> {
    u: Vec<S>,
    singular_values: Vec<f64>,
    vh: Vec<S>,
}

/// Safe one-sided Jacobi SVD.
///
/// This computes a thin SVD:
///
/// ```text
/// A = U Σ V†
/// ```
///
/// without unsafe memory or external numerical libraries.
///
/// The implementation is deterministic for a fixed scalar representation.
fn jacobi_svd<S: ComplexScalar>(
    matrix: &[S],
    rows: usize,
    cols: usize,
    max_sweeps: usize,
    tolerance: f64,
) -> Result<SvdResult<S>, MemoryError> {
    if rows == 0 || cols == 0 {
        return Err(invalid_argument(
            "SVD requires non-zero matrix dimensions",
        ));
    }

    if matrix.len() != rows.saturating_mul(cols) {
        return Err(invalid_argument(
            "SVD matrix length does not match dimensions",
        ));
    }

    if matrix.iter().any(|value| !value.is_finite()) {
        return Err(non_finite_error());
    }

    if !tolerance.is_finite() || tolerance <= 0.0 {
        return Err(invalid_argument(
            "SVD tolerance must be finite and positive",
        ));
    }

    let m = rows;
    let n = cols;

    let mut a = matrix.to_vec();

    let mut v = vec![S::zero(); n * n];

    for i in 0..n {
        v[i * n + i] = S::one();
    }

    for _ in 0..max_sweeps {
        let mut changed = false;

        for p in 0..n {
            for q in (p + 1)..n {
                let mut alpha = 0.0f64;
                let mut beta = 0.0f64;
                let mut gamma = S::zero();

                for row in 0..m {
                    let ap = a[row * n + p];
                    let aq = a[row * n + q];

                    alpha += ap.norm_squared().to_f64();
                    beta += aq.norm_squared().to_f64();
                    gamma += ap.conjugate() * aq;
                }

                if alpha <= tolerance || beta <= tolerance {
                    continue;
                }

                let gamma_abs = gamma.norm_squared().to_f64().sqrt();

                if gamma_abs <= tolerance * (alpha * beta).sqrt() {
                    continue;
                }

                changed = true;

                let phase = if gamma_abs > 0.0 {
                    gamma / S::from_real(
                        S::Real::from_f64(gamma_abs)
                            .ok_or_else(|| invalid_argument("SVD phase is not representable"))?,
                    )
                    .map_err(|_| invalid_argument("SVD phase scalar is invalid"))?
                } else {
                    S::one()
                };

                let tau = (beta - alpha) / (2.0 * gamma_abs);

                let t = if tau >= 0.0 {
                    1.0 / (tau + (1.0 + tau * tau).sqrt())
                } else {
                    -1.0 / (-tau + (1.0 + tau * tau).sqrt())
                };

                let c = 1.0 / (1.0 + t * t).sqrt();
                let s = c * t;

                let cs = scalar_from_f64::<S>(c)?;
                let ss = scalar_from_f64::<S>(s)?;

                for row in 0..m {
                    let ap = a[row * n + p];
                    let aq = a[row * n + q];

                    let new_p = cs * ap - ss * phase * aq;
                    let new_q = ss * phase.conjugate() * ap + cs * aq;

                    a[row * n + p] = new_p;
                    a[row * n + q] = new_q;
                }

                for row in 0..n {
                    let vp = v[row * n + p];
                    let vq = v[row * n + q];

                    let new_p = cs * vp - ss * phase * vq;
                    let new_q = ss * phase.conjugate() * vp + cs * vq;

                    v[row * n + p] = new_p;
                    v[row * n + q] = new_q;
                }
            }
        }

        if !changed {
            break;
        }
    }

    let rank = m.min(n);

    let mut singular_values = Vec::new();

    singular_values
        .try_reserve_exact(rank)
        .map_err(|_| allocation_error(rank.saturating_mul(8)))?;

    for column in 0..rank {
        let mut norm = 0.0f64;

        for row in 0..m {
            norm += a[row * n + column].norm_squared().to_f64();
        }

        singular_values.push(norm.sqrt());
    }

    let mut order: Vec<usize> = (0..rank).collect();

    order.sort_by(|a, b| {
        singular_values[*b]
            .partial_cmp(&singular_values[*a])
            .unwrap_or(core::cmp::Ordering::Equal)
    });

    let mut sorted_singular_values = vec![0.0f64; rank];
    let mut sorted_u = vec![S::zero(); m * rank];
    let mut sorted_v = vec![S::zero(); n * rank];

    for new_column in 0..rank {
        let old_column = order[new_column];
        let sigma = singular_values[old_column];

        sorted_singular_values[new_column] = sigma;

        if sigma > tolerance {
            let inverse_sigma = scalar_from_f64::<S>(1.0 / sigma)?;

            for row in 0..m {
                sorted_u[row * rank + new_column] =
                    a[row * n + old_column] * inverse_sigma;
            }
        }

        for row in 0..n {
            sorted_v[row * rank + new_column] =
                v[row * n + old_column];
        }
    }

    let mut vh = vec![S::zero(); rank * n];

    for r in 0..rank {
        for c in 0..n {
            vh[r * n + c] = sorted_v[c * rank + r].conjugate();
        }
    }

    Ok(SvdResult {
        u: sorted_u,
        singular_values: sorted_singular_values,
        vh,
    })
}

