// =============================================================================
// ComplexScalar conversion compatibility
// =============================================================================
//
// `ComplexScalar::Real` is intentionally kept abstract in `complex.rs`.
// The tensor-network implementation therefore needs a small conversion
// boundary. The following extension trait is private to this module and does
// not alter Zamani's public numerical contract.

trait RealConversion: Copy {
    fn from_f64(value: f64) -> Option<Self>;
    fn to_f64(self) -> f64;
}

impl RealConversion for f32 {
    fn from_f64(value: f64) -> Option<Self> {
        if value.is_finite() && value >= f32::MIN as f64 && value <= f32::MAX as f64 {
            Some(value as f32)
        } else {
            None
        }
    }

    fn to_f64(self) -> f64 {
        self as f64
    }
}

impl RealConversion for f64 {
    fn from_f64(value: f64) -> Option<Self> {
        value.is_finite().then_some(value)
    }

    fn to_f64(self) -> f64 {
        self
    }
}