    // Two-qubit operations
    // =========================================================================

    /// Applies an arbitrary 4x4 two-qubit operator to adjacent qubits.
    ///
    /// The matrix is row-major.
    ///
    /// The first qubit is the lower logical site index supplied by `left_qubit`.
    ///
    /// For non-adjacent operations, use [`Self::apply_two_qubit_matrix`] only
    /// after explicitly bringing the qubits adjacent with `swap_adjacent`.
    pub fn apply_adjacent_two_qubit_matrix(
        &mut self,
        left_qubit: usize,
        matrix: [S; 16],
    ) -> Result<TensorNetworkOperationReport, MemoryError> {
        let right_qubit = left_qubit
            .checked_add(1)
            .ok_or_else(|| invalid_argument("two-qubit index overflow"))?;

        self.validate_qubit_index(left_qubit)?;
        self.validate_qubit_index(right_qubit)?;

        self.apply_two_site_operator(left_qubit, matrix)
    }

    /// Applies a two-qubit operator to arbitrary distinct logical qubits.
    ///
    /// The implementation moves the right operand next to the left operand
    /// using adjacent SWAP operations, applies the operator, then restores the
    /// original ordering.
    ///
    /// This is correct but may be expensive. Routing-aware execution should
    /// normally perform the logical-to-physical permutation before execution
    /// so that memory does not repeatedly move qubits.
    pub fn apply_two_qubit_matrix(
        &mut self,
        first_qubit: usize,
        second_qubit: usize,
        matrix: [S; 16],
    ) -> Result<TensorNetworkOperationReport, MemoryError> {
        self.validate_qubit_index(first_qubit)?;
        self.validate_qubit_index(second_qubit)?;

        if first_qubit == second_qubit {
            return Err(invalid_argument(
                "two-qubit operation requires two distinct qubits",
            ));
        }

        if second_qubit == first_qubit + 1 {
            return self.apply_two_site_operator(first_qubit, matrix);
        }

        if first_qubit == second_qubit + 1 {
            let swapped = reverse_two_qubit_basis_matrix(matrix);
            return self.apply_two_site_operator(second_qubit, swapped);
        }

        let mut swaps = Vec::new();

        if first_qubit < second_qubit {
            for position in ((first_qubit + 1)..second_qubit).rev() {
                self.swap_adjacent(position)?;
                swaps.push(position);
            }

            let report = self.apply_two_site_operator(first_qubit, matrix)?;

            for position in swaps.into_iter().rev() {
                self.swap_adjacent(position)?;
            }

            Ok(report)
        } else {
            for position in ((second_qubit + 1)..first_qubit).rev() {
                self.swap_adjacent(position)?;
                swaps.push(position);
            }

            let swapped = reverse_two_qubit_basis_matrix(matrix);

            let report = self.apply_two_site_operator(second_qubit, swapped)?;

            for position in swaps.into_iter().rev() {
                self.swap_adjacent(position)?;
            }

            Ok(report)
        }
    }

    /// Applies controlled-X.
    pub fn apply_cx(
        &mut self,
        control: usize,
        target: usize,
    ) -> Result<TensorNetworkOperationReport, MemoryError> {
        let zero = S::zero();
        let one = S::one();

        let matrix = [
            one, zero, zero, zero,
            zero, one, zero, zero,
            zero, zero, zero, one,
            zero, zero, one, zero,
        ];

        self.apply_two_qubit_matrix(control, target, matrix)
    }

    /// Applies controlled-Z.
    pub fn apply_cz(
        &mut self,
        control: usize,
        target: usize,
    ) -> Result<TensorNetworkOperationReport, MemoryError> {
        let zero = S::zero();
        let one = S::one();
        let minus_one = -one;

        let matrix = [
            one, zero, zero, zero,
            zero, one, zero, zero,
            zero, zero, one, zero,
            zero, zero, zero, minus_one,
        ];

        self.apply_two_qubit_matrix(control, target, matrix)
    }

    /// Applies SWAP.
    pub fn swap_adjacent(
        &mut self,
        left_qubit: usize,
    ) -> Result<TensorNetworkOperationReport, MemoryError> {
        let zero = S::zero();
        let one = S::one();

        let matrix = [
            one, zero, zero, zero,
            zero, zero, one, zero,
            zero, one, zero, zero,
            zero, zero, zero, one,
        ];

        self.apply_two_site_operator(left_qubit, matrix)
    }

    // =========================================================================
    // Measurement and reset
    // =========================================================================

    /// Measures a qubit using an explicitly supplied uniform sample.
    ///
    /// `sample` must be finite and in `[0, 1)`.
    pub fn measure_qubit(
        &mut self,
        qubit: usize,
        sample: f64,
    ) -> Result<TensorNetworkMeasurement<f64>, MemoryError> {
        self.validate_qubit_index(qubit)?;

        if !sample.is_finite() || !(0.0..1.0).contains(&sample) {
            return Err(invalid_argument(
                "measurement sample must be finite and in [0, 1)",
            ));
        }

        let p1 = self.qubit_one_probability(qubit)?;
        let outcome = if sample < p1 { 1 } else { 0 };

        let probability = if outcome == 1 {
            p1
        } else {
            1.0 - p1
        };

        self.project_qubit(qubit, outcome)?;
        self.normalize()?;

        Ok(TensorNetworkMeasurement {
            outcome,
            probability,
        })
    }

    /// Projects a qubit onto a computational-basis outcome without sampling.
    pub fn project_qubit(
        &mut self,
        qubit: usize,
        outcome: u8,
    ) -> Result<(), MemoryError> {
        self.validate_qubit_index(qubit)?;

        if outcome > 1 {
            return Err(invalid_argument(
                "qubit projection outcome must be 0 or 1",
            ));
        }

        let site = self
            .sites
            .get_mut(qubit)
            .ok_or_else(|| out_of_bounds(qubit, self.sites.len(), "MPS qubit"))?;

        for left in 0..site.left_dimension() {
            for physical in 0..2 {
                if physical != outcome as usize {
                    for right in 0..site.right_dimension() {
                        *site.get_mut(left, physical, right)? = S::zero();
                    }
                }
            }
        }

        Ok(())
    }

    /// Resets a qubit to `|0>`.
    pub fn reset_qubit(&mut self, qubit: usize) -> Result<(), MemoryError> {
        self.validate_qubit_index(qubit)?;

        let site = self
            .sites
            .get_mut(qubit)
            .ok_or_else(|| out_of_bounds(qubit, self.sites.len(), "MPS qubit"))?;

        for left in 0..site.left_dimension() {
            for right in 0..site.right_dimension() {
                let value = site.get(left, 0, right)?;

                *site.get_mut(left, 1, right)? = S::zero();

                if left == 0 && right == 0 {
                    *site.get_mut(left, 0, right)? = value;
                }
            }
        }

        self.normalize()
    }

