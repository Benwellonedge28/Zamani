fn left_u_to_mps_tensor<S: ComplexScalar>(
    u: &[S],
    singular_values: &[f64],
    rows: usize,
    rank: usize,
) -> Result<MpsTensor<S>, MemoryError> {
    if rows % 2 != 0 {
        return Err(invariant_error(
            "left MPS conversion requires an even row count",
        ));
    }

    let left_dimension = rows / 2;

    if rank == 0 || rank > singular_values.len() {
        return Err(invariant_error(
            "left MPS conversion rank is invalid",
        ));
    }

    let mut values = vec![S::zero(); left_dimension * 2 * rank];

    for left in 0..left_dimension {
        for physical in 0..2 {
            for bond in 0..rank {
                let source = (left * 2 + physical) * singular_values.len() + bond;

                let value = u
                    .get(source)
                    .copied()
                    .ok_or_else(|| invariant_error("left MPS SVD index out of bounds"))?;

                let sigma = scalar_from_f64::<S>(singular_values[bond])?;

                values[(left * 2 + physical) * rank + bond] =
                    value * sigma;
            }
        }
    }

    MpsTensor::from_values(left_dimension, rank, values)
}

fn multiply_vh_by_singular_values<S: ComplexScalar>(
    vh: &[S],
    singular_values: &[f64],
    cols: usize,
    rank: usize,
) -> Result<Vec<S>, MemoryError> {
    if vh.len() != singular_values.len().saturating_mul(cols) {
        return Err(invariant_error(
            "SVD V† dimensions are invalid",
        ));
    }

    let mut result = vec![S::zero(); rank * cols];

    for r in 0..rank {
        let sigma = scalar_from_f64::<S>(singular_values[r])?;

        for c in 0..cols {
            result[r * cols + c] = sigma * vh[r * cols + c];
        }
    }

    Ok(result)
}

fn matrix_to_right_mps_tensor<S: ComplexScalar>(
    matrix: &[S],
    rank: usize,
    right_dimension: usize,
) -> Result<MpsTensor<S>, MemoryError> {
    if matrix.len() != rank.saturating_mul(right_dimension) {
        return Err(invariant_error(
            "right MPS tensor dimensions are invalid",
        ));
    }

    let mut values = vec![S::zero(); rank * 2 * right_dimension];

    for bond in 0..rank {
        for physical in 0..2 {
            for right in 0..right_dimension {
                let source_column = physical
                    .checked_mul(right_dimension)
                    .and_then(|value| value.checked_add(right))
                    .ok_or_else(|| invariant_error("right MPS index overflow"))?;

                values[(bond * 2 + physical) * right_dimension + right] =
                    matrix[bond * right_dimension + source_column];
            }
        }
    }

    MpsTensor::from_values(rank, right_dimension, values)
}

fn product_site<S: ComplexScalar>(
    zero: S,
    one: S,
) -> Result<MpsTensor<S>, MemoryError> {
    MpsTensor::from_values(
        1,
        1,
        vec![zero, one],
    )
}

// =============================================================================
// Rank/truncation helpers
// =============================================================================

fn choose_rank(
    singular_values: &[f64],
    policy: &TruncationPolicy,
) -> Result<usize, MemoryError> {
    if singular_values.is_empty() {
        return Err(invariant_error(
            "cannot choose MPS rank from an empty singular-value set",
        ));
    }

    let largest = singular_values[0];

    if !largest.is_finite() {
        return Err(non_finite_error());
    }

    let threshold = policy
        .absolute_cutoff
        .max(policy.relative_cutoff * largest);

    let mut retained = singular_values
        .iter()
        .take(policy.max_bond_dimension)
        .take_while(|value| **value >= threshold)
        .count();

    if retained == 0 {
        retained = 1;
    }

    let max_allowed = singular_values
        .len()
        .min(policy.max_bond_dimension);

    retained = retained.min(max_allowed);

    let mut discarded_weight = 0.0;

    for value in singular_values.iter().skip(retained) {
        discarded_weight += value * value;
    }

    if discarded_weight > policy.maximum_discarded_weight
        && retained < singular_values.len()
    {
        if !policy.allow_truncation {
            return Err(invariant_error(
                "MPS rank reduction requested while truncation is disabled",
            ));
        }
    }

    Ok(retained)
}

fn truncation_report(
    singular_values: &[f64],
    retained: usize,
) -> TruncationReport {
    let original_rank = singular_values.len();
    let discarded_count = original_rank.saturating_sub(retained);

    let mut discarded_weight = 0.0;
    let mut largest_discarded = 0.0;

    for value in singular_values.iter().skip(retained) {
        discarded_weight += value * value;
        largest_discarded = largest_discarded.max(*value);
    }

    TruncationReport {
        original_rank,
        retained_rank: retained,
        discarded_count,
        discarded_weight,
        largest_discarded_singular_value: largest_discarded,
        truncated: discarded_count != 0,
    }
}

