//! Zamani Quantum Memory — Tensor-Network / Matrix-Product-State Representation
//!
//! Production-grade, provider-neutral tensor-network quantum-state storage.
//!
//! # Scope
//!
//! This module implements a one-dimensional Matrix Product State (MPS)
//! representation for finite-dimensional qubit systems.
//!
//! The implementation provides:
//!
//! - canonical little-endian logical-qubit ordering;
//! - explicit bond-dimension control;
//! - configurable truncation;
//! - numerical tolerance control;
//! - normalized-state invariants;
//! - product-state construction;
//! - computational-basis construction;
//! - conversion from a dense StateVector;
//! - conversion back to a dense StateVector when permitted;
//! - one-qubit arbitrary matrix application;
//! - common one-qubit gates;
//! - arbitrary two-qubit 4x4 unitary application;
//! - controlled operations;
//! - SWAP;
//! - computational-basis probability queries;
//! - reduced single-qubit probabilities;
//! - expectation values for one-qubit operators;
//! - overlap/fidelity;
//! - tensor-product composition;
//! - qubit permutation through explicit adjacent swaps;
//! - measurement sampling/collapse through an explicitly supplied random sample;
//! - reset;
//! - canonicalization;
//! - truncation/error accounting;
//! - memory estimation;
//! - state validation;
//! - representation-neutral QuantumState integration;
//! - provider-neutral execution;
//! - CPU-only baseline implementation with future accelerator boundaries;
//! - no unsafe code;
//! - no vendor-specific QPU dependencies;
//! - no hidden global RNG;
//! - no hidden backend assumptions.
//!
//! # Architectural boundary
//!
//! This module owns tensor-network state representation.
//!
//! It does NOT own:
//!
//! - quantum IR;
//! - compiler parsing;
//! - routing algorithms;
//! - scheduling;
//! - hardware topology;
//! - QPU drivers;
//! - CUDA/HIP/Metal/Vulkan APIs;
//! - MPI/RDMA;
//! - measurement orchestration;
//! - snapshot formats;
//! - checkpoint formats;
//! - benchmarking protocols;
//! - QEC decoding.
//!
//! Those systems integrate through their existing Zamani boundaries.
//!
//! # Representation
//!
//! An MPS represents:
//!
//! ```text
//! |ψ> = Σ_{s0...sn-1}
//!       A[0]^{s0} A[1]^{s1} ... A[n-1]^{sn-1}
//!       |s0...sn-1>
//! ```
//!
//! Every physical dimension is two because this module represents qubits.
//!
//! The internal tensors use:
//!
//! ```text
//! A[i][left_bond][physical_bit][right_bond]
//! ```
//!
//! with the invariant:
//!
//! ```text
//! site 0:     left bond = 1
//! site n-1:   right bond = 1
//! interior:   both bonds >= 1
//! physical:   exactly 2
//! ```
//!
//! # Qubit ordering
//!
//! The logical order is little-endian, matching `StateVector`:
//!
//! ```text
//! amplitude index bit q == logical qubit q
//! ```
//!
//! MPS site `q` therefore represents logical qubit `q`.
//!
//! External hardware providers MUST translate their physical ordering through
//! `memory::layout` rather than assuming this representation matches their
//! native ordering.
//!
//! # Truncation
//!
//! Two-qubit operations can increase the Schmidt rank across a bond.
//!
//! The implementation therefore performs SVD-based bond compression.
//!
//! A truncation policy controls:
//!
//! - maximum bond dimension;
//! - absolute singular-value cutoff;
//! - relative singular-value cutoff;
//! - discarded-weight tolerance;
//! - whether truncation is permitted.
//!
//! Truncation is NEVER silent:
//!
//! - the policy is explicit;
//! - the result records discarded weight;
//! - callers can reject excessive approximation error.
//!
//! # Numerical implementation
//!
//! No external BLAS/LAPACK dependency is required by this module.
//!
//! The baseline implementation uses a deterministic one-sided Jacobi SVD for
//! the relatively small two-site matrices generated by MPS operations.
//!
//! This is intentionally a safe reference implementation.
//!
//! Future `memory::simd`, `memory::gpu`, or distributed implementations may
//! replace the numerical kernel while preserving the public MPS semantics.
//!
//! # Hardware/QPU compatibility
//!
//! An MPS is a simulator-side representation.
//!
//! A physical QPU generally does not expose its complete quantum state.
//!
//! Therefore this module does NOT pretend to represent a remote QPU's physical
//! state. QPU backends that do not expose amplitudes must use
//! `memory::backend_state`.
//!
//! This module can nevertheless be used for:
//!
//! - local simulation;
//! - remote simulation;
//! - emulator validation;
//! - transpiler verification;
//! - small-system reference execution;
//! - approximate simulation;
//! - hybrid classical/quantum workflows;
//! - differential testing against QPUs;
//! - state-preparation verification;
//! - tensor-network based classical post-processing.
//!
//! # Rust compatibility
//!
//! Supported:
//!
//! - Rust 1.97;
//! - Rust 1.97.1;
//! - Rust 2021;
//! - stable Rust;
//! - no nightly features;
//! - no unsafe code.
//!
//! # Safety
//!
//! `unsafe` is explicitly denied.
//!
//! No raw pointers, FFI pointers, device pointers, or unsafe allocation APIs
//! are exposed.
//!
//! # Integration contract
//!
//! Foundational modules consumed:
//!
//! - `memory::complex`;
//! - `memory::errors`;
//! - `memory::types`;
//! - `memory::state`.
//!
//! Future modules may consume this implementation through:
//!
//! - `memory::view`;
//! - `memory::permutation`;
//! - `memory::measurement`;
//! - `memory::reset`;
//! - `memory::snapshot`;
//! - `memory::checkpoint`;
//! - `memory::migration`;
//! - `memory::gpu`;
//! - `memory::distributed`;
//! - `memory::telemetry`.
//!
//! Those modules MUST preserve the semantics defined here rather than
//! redefining MPS ordering, normalization, truncation, or tensor indexing.

