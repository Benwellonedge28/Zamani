fn checked_basis_dimension(
    qubits: QubitCount,
) -> Result<usize, MemoryError> {
    let count = qubits.get();

    if count >= usize::BITS as usize {
        return Err(invalid_argument(
            "qubit count exceeds platform basis-index width",
        ));
    }

    1usize
        .checked_shl(count as u32)
        .ok_or_else(|| invalid_argument("quantum basis dimension overflow"))
}

fn checked_tensor_elements(
    left: usize,
    right: usize,
) -> Result<usize, MemoryError> {
    left.checked_mul(QUBIT_PHYSICAL_DIMENSION)
        .and_then(|value| value.checked_mul(right))
        .ok_or_else(|| invariant_error("MPS tensor element count overflow"))
}

fn scalar_from_f64<S: ComplexScalar>(
    value: f64,
) -> Result<S, MemoryError> {
    if !value.is_finite() {
        return Err(non_finite_error());
    }

    let real = S::Real::from_f64(value)
        .ok_or_else(|| invalid_argument("floating-point value is not representable"))?;

    S::from_real(real)
        .map_err(|_| invalid_argument("floating-point scalar is invalid"))
}

fn require_one_qubit<S, F>(
    qubits: &[crate::quantum::ir::QubitId],
    mut operation: F,
) -> Result<(), MemoryError>
where
    F: FnMut(usize) -> Result<(), MemoryError>,
{
    if qubits.len() != 1 {
        return Err(invalid_argument(
            "single-qubit operation requires exactly one logical qubit",
        ));
    }

    operation(qubits[0].index())
}

fn unreachable_metadata() -> &'static StateMetadata {
    // This implementation is deliberately never intended to be called.
    //
    // The runtime-facing TensorNetworkQuantumState below owns stable metadata.
    // Keeping TensorNetworkState itself as a pure mathematical representation
    // prevents global metadata and avoids unsafe self-referential storage.
    panic!("TensorNetworkState must be wrapped in TensorNetworkQuantumState for QuantumState use")
}

