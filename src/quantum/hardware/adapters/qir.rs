/// Structured errors produced by the QIR adapter.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum QirError {
    /// QIR version is not supported by this adapter.
    UnsupportedVersion {
        requested: QirVersion,
    },

    /// QIR profile is not supported by this adapter.
    UnsupportedProfile {
        profile: QirProfile,
    },

    /// Adapter configuration is invalid.
    InvalidConfiguration {
        field: &'static str,
        reason: &'static str,
    },

    /// The circuit itself is not valid for QIR export.
    InvalidCircuit {
        reason: String,
    },

    /// A Zamani operation has no supported direct QIR mapping.
    UnsupportedGate {
        gate: GateKind,
    },

    /// A gate has an invalid parameter representation for QIR.
    UnsupportedParameter {
        gate: GateKind,
        index: usize,
        reason: &'static str,
    },

    /// A measurement cannot be represented by the Base Profile.
    UnsupportedMeasurement {
        reason: &'static str,
    },

    /// A gate appears after the terminal measurement region began.
    OperationAfterMeasurement {
        gate: GateKind,
    },

    /// The same classical destination is measured more than once.
    DuplicateClassicalDestination {
        bit: usize,
    },

    /// A logical qubit is outside the circuit namespace.
    InvalidQubit {
        qubit: usize,
        count: usize,
    },

    /// A classical bit is outside the circuit namespace.
    InvalidClassicalBit {
        bit: usize,
        count: usize,
    },

    /// Generated output exceeded the configured limit.
    OutputLimitExceeded {
        attempted: usize,
        maximum: usize,
    },

    /// An internal formatting operation failed.
    Formatting,

    /// An LLVM/QIR identifier is invalid.
    InvalidIdentifier {
        field: &'static str,
        reason: &'static str,
    },
}

impl fmt::Display for QirError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsupportedVersion { requested } => {
                write!(
                    formatter,
                    "unsupported QIR version {requested}; this adapter emits QIR 2.0"
                )
            }

            Self::UnsupportedProfile { profile } => {
                write!(
                    formatter,
                    "unsupported QIR profile {}",
                    profile.as_str()
                )
            }

            Self::InvalidConfiguration { field, reason } => {
                write!(
                    formatter,
                    "invalid QIR configuration `{field}`: {reason}"
                )
            }

            Self::InvalidCircuit { reason } => {
                write!(formatter, "invalid circuit for QIR export: {reason}")
            }

            Self::UnsupportedGate { gate } => {
                write!(
                    formatter,
                    "gate {gate:?} has no supported direct QIR Base Profile mapping"
                )
            }

            Self::UnsupportedParameter {
                gate,
                index,
                reason,
            } => {
                write!(
                    formatter,
                    "parameter {index} of gate {gate:?} cannot be emitted to QIR: {reason}"
                )
            }

            Self::UnsupportedMeasurement { reason } => {
                write!(
                    formatter,
                    "measurement cannot be emitted to QIR Base Profile: {reason}"
                )
            }

            Self::OperationAfterMeasurement { gate } => {
                write!(
                    formatter,
                    "operation {gate:?} occurs after terminal measurement region began"
                )
            }

            Self::DuplicateClassicalDestination { bit } => {
                write!(
                    formatter,
                    "classical destination c{bit} is measured more than once"
                )
            }

            Self::InvalidQubit { qubit, count } => {
                write!(
                    formatter,
                    "logical qubit {qubit} is outside circuit namespace 0..{count}"
                )
            }

            Self::InvalidClassicalBit { bit, count } => {
                write!(
                    formatter,
                    "classical bit {bit} is outside circuit namespace 0..{count}"
                )
            }

            Self::OutputLimitExceeded {
                attempted,
                maximum,
            } => {
                write!(
                    formatter,
                    "QIR artifact exceeds output limit: attempted {attempted} bytes, maximum {maximum}"
                )
            }

            Self::Formatting => {
                formatter.write_str("failed to construct QIR text")
            }

            Self::InvalidIdentifier { field, reason } => {
                write!(
                    formatter,
                    "invalid QIR identifier `{field}`: {reason}"
                )
            }
        }
    }
}

impl std::error::Error for QirError {}

