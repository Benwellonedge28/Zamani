fn constant_parameter<'a>(
    gate: GateKind,
    index: usize,
    parameters: &'a [Parameter],
) -> Result<f64, QirError> {
    let parameter =
        parameters.get(index).ok_or(
            QirError::UnsupportedParameter {
                gate,
                index,
                reason: "parameter is missing",
            },
        )?;

    match parameter {
        Parameter::Constant(value)
            if value.is_finite() =>
        {
            Ok(*value)
        }

        Parameter::Constant(_) => {
            Err(QirError::UnsupportedParameter {
                gate,
                index,
                reason: "parameter is not finite",
            })
        }

        Parameter::Symbol(_) => {
            Err(QirError::UnsupportedParameter {
                gate,
                index,
                reason: "symbolic parameter is not bound",
            })
        }

        Parameter::Expression(_) => {
            Err(QirError::UnsupportedParameter {
                gate,
                index,
                reason: "parameter expression is not lowered",
            })
        }
    }
}

/// Formats a QIR opaque pointer representing a statically identified qubit.
fn qir_qubit(index: usize) -> String {
    format!(
        "inttoptr (i64 {} to ptr)",
        index
    )
}

/// Formats a QIR opaque pointer representing a statically identified result.
fn qir_result(index: usize) -> String {
    format!(
        "inttoptr (i64 {} to ptr)",
        index
    )
}

/// Formats a finite Rust `f64` as a deterministic LLVM floating-point literal.
///
/// Scientific notation is used to avoid locale-dependent formatting.
fn llvm_double(value: f64) -> String {
    /*
     * `{:e}` is deterministic in Rust and does not depend on process locale.
     *
     * The precision is explicitly fixed so the same Rust value produces the
     * same textual artifact across invocations.
     */
    format!("{value:.17e}")
}

// =============================================================================
// Identifier validation
// =============================================================================

fn validate_llvm_identifier(
    value: &str,
    maximum: usize,
    field: &'static str,
) -> Result<(), QirError> {
    if value.is_empty() {
        return Err(QirError::InvalidIdentifier {
            field,
            reason: "identifier must not be empty",
        });
    }

    if value.len() > maximum {
        return Err(QirError::InvalidIdentifier {
            field,
            reason: "identifier exceeds maximum length",
        });
    }

    let mut characters =
        value.chars();

    let first =
        characters.next().ok_or(
            QirError::InvalidIdentifier {
                field,
                reason: "identifier must not be empty",
            },
        )?;

    if !(first == '_'
        || first.is_ascii_alphabetic())
    {
        return Err(QirError::InvalidIdentifier {
            field,
            reason: "identifier must start with an ASCII letter or underscore",
        });
    }

    for character in characters {
        if !(character == '_'
            || character == '.'
            || character == '$'
            || character == '-'
            || character.is_ascii_alphanumeric())
        {
            return Err(QirError::InvalidIdentifier {
                field,
                reason: "identifier contains an unsupported character",
            });
        }
    }

    Ok(())
}

fn validate_ascii_identifier(
    value: &str,
    maximum: usize,
    field: &'static str,
) -> Result<(), QirError> {
    if value.is_empty() {
        return Err(QirError::InvalidIdentifier {
            field,
            reason: "identifier must not be empty",
        });
    }

    if value.len() > maximum {
        return Err(QirError::InvalidIdentifier {
            field,
            reason: "identifier exceeds maximum length",
        });
    }

    if !value
        .bytes()
        .all(|byte| {
            byte == b'_'
                || byte == b'.'
                || byte == b'-'
                || byte.is_ascii_alphanumeric()
        })
    {
        return Err(QirError::InvalidIdentifier {
            field,
            reason: "identifier must contain only ASCII alphanumeric characters, '_', '.', or '-'",
        });
    }

    Ok(())
}

