/// Stable adapter identifier.
pub const QIR_ADAPTER_ID: &str = "zamani.quantum.hardware.adapters.qir";

/// QIR major version emitted by this adapter.
pub const QIR_MAJOR_VERSION: u32 = 2;

/// QIR minor version emitted by this adapter.
pub const QIR_MINOR_VERSION: u32 = 0;

/// QIR textual artifact format identifier.
pub const QIR_FORMAT_ID: &str = "qir";

/// Stable QIR Base Profile identifier.
pub const QIR_BASE_PROFILE: &str = "base_profile";

/// Default QIR entry point.
pub const DEFAULT_ENTRY_POINT: &str = "__zamani_entry";

/// Default output-labeling schema.
///
/// This is a Zamani-defined output labeling contract. QIR defines the
/// mechanism for output recording, while concrete output schemas can be
/// interpreted by the consuming environment.
pub const DEFAULT_OUTPUT_LABELING_SCHEMA: &str = "zamani.classical_bits.v1";

/// Default maximum QIR artifact size.
pub const DEFAULT_MAX_OUTPUT_BYTES: usize = 16 * 1024 * 1024;

/// Maximum length of an externally supplied entry-point identifier.
pub const MAX_ENTRY_POINT_LENGTH: usize = 256;

/// Maximum length of an output schema identifier.
pub const MAX_OUTPUT_SCHEMA_LENGTH: usize = 256;

// =============================================================================
// QIR version
