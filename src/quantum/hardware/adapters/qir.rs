//! Zamani Quantum Hardware — QIR Adapter
//!
//! Production QIR lowering boundary for the canonical Zamani Quantum IR.
//!
//! # Responsibility
//!
//! This module converts a validated [`QuantumCircuit`] into deterministic,
//! textual QIR based on LLVM IR and the QIR v2 Base Profile.
//!
//! The dependency direction is:
//!
//! ```text
//! Zamani source
//!      |
//!      v
//! Quantum Frontend
//!      |
//!      v
//! Zamani Quantum IR
//!      |
//!      v
//! compiler / routing / scheduling
//!      |
//!      v
//! hardware compatibility
//!      |
//!      v
//! adapters/qir.rs
//!      |
//!      v
//! QIR v2 + selected QIS
//!      |
//!      +-----------------------------+
//!      |                             |
//!      v                             v
//! QIR-compatible compiler       QIR-compatible backend
//! ```
//!
//! # What this module owns
//!
//! - QIR version selection;
//! - QIR profile selection;
//! - deterministic LLVM/QIR text generation;
//! - Zamani IR -> QIR gate mapping;
//! - Zamani logical qubit -> QIR opaque pointer mapping;
//! - Zamani measurement -> QIR result mapping;
//! - QIR entry-point attributes;
//! - QIR module flags;
//! - QIR runtime/QIS declarations;
//! - bounded output generation;
//! - representability validation;
//! - QIR-specific diagnostics.
//!
//! # What this module does NOT own
//!
//! - Zamani Quantum IR semantics;
//! - optimization;
//! - routing;
//! - scheduling;
//! - topology;
//! - calibration;
//! - provider authentication;
//! - provider APIs;
//! - job submission;
//! - result retrieval;
//! - simulation;
//! - hardware execution;
//! - provider-specific gate decomposition.
//!
//! Those responsibilities belong to the corresponding quantum/compiler/
//! hardware modules.
//!
//! # QIR interoperability model
//!
//! QIR is an interoperability target, not Zamani's canonical IR.
//!
//! ```text
//! Zamani Quantum IR
//!        |
//!        v
//!   qir.rs
//!        |
//!        v
//! QIR v2 / LLVM IR
//!        |
//!        +------------------+
//!        |                  |
//!        v                  v
//! target-specific       QIR-compatible
//! lowering              tooling
//! ```
//!
//! The canonical Zamani IR remains authoritative.
//!
//! QIR is not used as the internal representation of Zamani.
//!
//! # QIR version
//!
//! This implementation targets QIR v2.0 semantics using LLVM opaque pointers.
//! QIR v2 uses `ptr` rather than typed `%Qubit*` / `%Result*` pointers.
//!
//! QIR v1 output is intentionally not generated by this adapter. A future
//! compatibility adapter can implement QIR v1 separately without weakening
//! the v2 contract.
//!
//! # Profile
//!
//! This implementation generates the QIR Base Profile.
//!
//! Base Profile constraints are intentionally enforced:
//!
//! - straight-line quantum execution;
//! - no dynamic classical branching;
//! - measurements occur in the terminal measurement region;
//! - measurement results are recorded after measurement;
//! - QIS functions return `void`;
//! - measurement QIS functions are marked `irreversible`;
//! - result arguments are `writeonly`;
//! - static qubit/result identities are used;
//! - dynamic resource management is disabled.
//!
//! Unsupported Zamani operations are rejected rather than approximated.
//!
//! # QIS policy
//!
//! QIR itself does not mandate one universal gate set. A QIR program selects
//! a quantum instruction set supported by its target.
//!
//! Consequently this adapter maintains an explicit, auditable mapping from
//! Zamani `GateKind` to QIR QIS functions.
//!
//! The following operations are emitted directly:
//!
//! - `X`
//! - `Y`
//! - `Z`
//! - `H`
//! - `S`
//! - `Sdg`
//! - `T`
//! - `Tdg`
//! - `RX`
//! - `RY`
//! - `RZ`
//! - `CX`
//! - `CY`
//! - `CZ`
//! - `SWAP`
//! - `CCX`
//! - `Measure`
//!
//! The following canonical Zamani operations are intentionally rejected by
//! this Base Profile adapter because no universal direct QIR QIS mapping is
//! assumed here:
//!
//! - `I`
//! - `V`
//! - `Vdg`
//! - `Phase`
//! - `U1`
//! - `U2`
//! - `U3`
//! - `CH`
//! - `ISWAP`
//! - `ECR`
//! - `CRX`
//! - `CRY`
//! - `CRZ`
//! - `CSWAP`
//! - `Barrier`
//! - `Reset`
//!
//! A compiler transformation may decompose those operations before invoking
//! this adapter. This adapter never silently performs such a transformation.
//!
//! # Parameter policy
//!
//! Base Profile QIR requires QIS call arguments to be representable as LLVM
//! constants or valid pointer values. Therefore this adapter accepts only
//! concrete finite `Parameter::Constant` values.
//!
//! Symbolic parameters are rejected.
//!
//! Parameter binding belongs upstream in the compiler pipeline.
//!
//! # Measurement policy
//!
//! QIR's Base Profile measurement model is terminal measurement.
//!
//! The adapter therefore requires:
//!
//! - Z-basis measurement;
//! - non-destructive logical measurement semantics;
//! - an explicit classical destination;
//! - no quantum operation after the first measurement;
//! - no second measurement into the same classical destination if doing so
//!   would make the resulting output contract ambiguous.
//!
//! Each measurement receives a unique QIR result identity.
//!
//! The QIR output label preserves the original Zamani classical-bit identity:
//!
//! ```text
//! Zamani c7
//!     |
//!     v
//! QIR result #N
//!     |
//!     v
//! label "c7"
//! ```
//!
//! # Security
//!
//! This module:
//!
//! - performs no network access;
//! - performs no filesystem access;
//! - performs no process execution;
//! - stores no credentials;
//! - embeds no secrets;
//! - does not accept arbitrary LLVM snippets;
//! - does not allow caller-controlled LLVM identifiers;
//! - bounds generated output;
//! - validates every emitted instruction;
//! - fails closed on unsupported semantics.
//!
//! # Determinism
//!
//! For the same validated circuit and options, the generated QIR is byte-for-
//! byte deterministic.
//!
//! Determinism covers:
//!
//! - declaration ordering;
//! - instruction ordering;
//! - result numbering;
//! - output labels;
//! - module flags;
//! - attributes;
//! - whitespace;
//! - floating-point formatting.
//!
//! # Rust compatibility
//!
//! Supported:
//!
//! - Rust 1.97;
//! - Rust 1.97.1;
//! - Rust 2021.
//!
//! No nightly features are required.
//! No external dependencies are required.
//!
//! # Integration contract
//!
//! This file depends only on the canonical Quantum IR:
//!
//! - `quantum::ir::QuantumCircuit`;
//! - `quantum::ir::Gate`;
//! - `quantum::ir::GateKind`;
//! - `quantum::ir::MeasurementBasis`;
//! - `quantum::ir::MeasurementMode`;
//! - `quantum::ir::Parameter`.
//!
//! It deliberately does not depend on:
//!
//! - `hardware::backend`;
//! - provider adapters;
//! - benchmarking;
//! - routing;
//! - scheduling;
//! - Danga;
//! - frontend parsers.
//!
//! Future `backend.rs` / `backend_trait.rs` integration should consume
//! [`QirArtifact`] as a target representation. The backend layer is responsible
//! for deciding whether the selected provider accepts QIR and for submitting
//! it. Provider-specific transport must never be added here.
//!
//! # Completion guarantee
//!
//! This file is complete independently when:
//!
//! 1. every supported mapping is explicitly documented;
//! 2. unsupported mappings fail deterministically;
//! 3. QIR output is bounded;
//! 4. QIR metadata is deterministic;
//! 5. the Base Profile structural rules are enforced;
//! 6. symbolic parameters cannot leak into invalid QIR;
//! 7. classical measurement identity is preserved;
//! 8. no credentials or provider state are accessed;
//! 9. unit tests cover valid and invalid mappings;
//! 10. later hardware/provider modules can consume the artifact without
//!     changing this module's core semantics.

