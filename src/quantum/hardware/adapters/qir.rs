/// QIR execution profile supported by the adapter.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum QirProfile {
    /// QIR Base Profile.
    Base,
}

impl QirProfile {
    /// Returns the QIR profile identifier.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Base => QIR_BASE_PROFILE,
        }
    }
}

impl Default for QirProfile {
    fn default() -> Self {
        Self::Base
    }
}

// =============================================================================
// Options
