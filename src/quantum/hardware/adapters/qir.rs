/// Production QIR exporter.
///
/// The exporter is immutable and contains only configuration. It is therefore
/// safe to share between threads when the surrounding compiler shares the
/// canonical immutable circuit safely.
#[derive(Debug, Clone)]
pub struct QirExporter {
    options: QirOptions,
}

impl QirExporter {
    /// Creates the production exporter.
    pub fn production() -> Result<Self, QirError> {
        Self::new(QirOptions::production()?)
    }

    /// Creates an exporter from explicit validated options.
    pub fn new(options: QirOptions) -> Result<Self, QirError> {
        options.validate()?;

        Ok(Self { options })
    }

    /// Returns the immutable exporter configuration.
    pub fn options(&self) -> &QirOptions {
        &self.options
    }

    /// Exports a canonical Zamani circuit to QIR.
    pub fn export(
        &self,
        circuit: &QuantumCircuit,
    ) -> Result<QirArtifact, QirError> {
        self.validate_circuit(circuit)?;

        let declarations = collect_declarations(circuit)?;

        let measurement_count = circuit
            .operations()
            .iter()
            .filter(|gate| gate.kind() == GateKind::Measure)
            .count();

        let mut output =
            BoundedOutput::new(self.options.max_output_bytes);

        self.write_module_header(
            &mut output,
            circuit,
        )?;

        self.write_declarations(
            &mut output,
            &declarations,
        )?;

        self.write_entry_point(
            &mut output,
            circuit,
        )?;

        self.write_attributes(
            &mut output,
            circuit,
        )?;

        self.write_module_flags(
            &mut output,
        )?;

        /*
         * `measurement_count` is intentionally calculated before construction
         * of the artifact so the artifact metadata is derived from the exact
         * emitted circuit, not from mutable state.
         */
        Ok(QirArtifact::new(
            output.into_string(),
            self.options.version,
            self.options.profile,
            self.options.entry_point.clone(),
            circuit.num_qubits(),
            measurement_count,
        ))
    }

    // -------------------------------------------------------------------------
    // Validation
    // -------------------------------------------------------------------------

    /// Validates the complete QIR representability contract before emitting
    /// output.
    fn validate_circuit(
        &self,
        circuit: &QuantumCircuit,
    ) -> Result<(), QirError> {
        /*
         * QuantumCircuit exposes its canonical validation boundary. The QIR
         * adapter performs an additional format-specific validation pass after
         * that boundary because a structurally valid Zamani circuit may still
         * contain operations that QIR Base Profile cannot represent directly.
         */
        circuit
            .validate()
            .map_err(|error| QirError::InvalidCircuit {
                reason: error.to_string(),
            })?;

        let mut measurement_started = false;
        let mut classical_destinations = BTreeSet::new();

        for gate in circuit.operations() {
            self.validate_gate(
                gate,
                circuit,
                &mut measurement_started,
                &mut classical_destinations,
            )?;
        }

        Ok(())
    }

    fn validate_gate(
        &self,
        gate: &Gate,
        circuit: &QuantumCircuit,
        measurement_started: &mut bool,
        classical_destinations: &mut BTreeSet<usize>,
    ) -> Result<(), QirError> {
        for qubit in gate.qubits() {
            if qubit.index() >= circuit.num_qubits() {
                return Err(QirError::InvalidQubit {
                    qubit: qubit.index(),
                    count: circuit.num_qubits(),
                });
            }
        }

        match gate.kind() {
            GateKind::Measure => {
                if *measurement_started {
                    /*
                     * Multiple terminal measurements are valid. The flag means
                     * the circuit has entered its measurement-only suffix, not
                     * that only one measurement may occur.
                     */
                }

                *measurement_started = true;

                let measurement = gate
                    .measurement()
                    .ok_or(QirError::UnsupportedMeasurement {
                        reason: "measurement payload is missing",
                    })?;

                if measurement.basis() != MeasurementBasis::Z {
                    return Err(QirError::UnsupportedMeasurement {
                        reason: "QIR Base Profile adapter emits only Z-basis measurement",
                    });
                }

                if measurement.mode() != MeasurementMode::NonDestructive {
                    return Err(QirError::UnsupportedMeasurement {
                        reason: "destructive measurement semantics are not emitted by this adapter",
                    });
                }

                let classical =
                    measurement.classical_bit().index();

                if classical >= circuit.num_classical_bits() {
                    return Err(QirError::InvalidClassicalBit {
                        bit: classical,
                        count: circuit.num_classical_bits(),
                    });
                }

                if !classical_destinations.insert(classical) {
                    return Err(
                        QirError::DuplicateClassicalDestination {
                            bit: classical,
                        },
                    );
                }

                if measurement.requests_reset_after() {
                    return Err(QirError::UnsupportedMeasurement {
                        reason: "reset-after-measurement is not part of this Base Profile mapping",
                    });
                }
            }

            _ if *measurement_started => {
                return Err(
                    QirError::OperationAfterMeasurement {
                        gate: gate.kind(),
                    },
                );
            }

            GateKind::I
            | GateKind::V
            | GateKind::Vdg
            | GateKind::Phase
            | GateKind::U1
            | GateKind::U2
            | GateKind::U3
            | GateKind::CH
            | GateKind::ISWAP
            | GateKind::ECR
            | GateKind::CRX
            | GateKind::CRY
            | GateKind::CRZ
            | GateKind::CSWAP
            | GateKind::Barrier
            | GateKind::Reset => {
                return Err(QirError::UnsupportedGate {
                    gate: gate.kind(),
                });
            }

            GateKind::X
            | GateKind::Y
            | GateKind::Z
            | GateKind::H
            | GateKind::S
            | GateKind::Sdg
            | GateKind::T
            | GateKind::Tdg
            | GateKind::RX
            | GateKind::RY
            | GateKind::RZ
            | GateKind::CX
            | GateKind::CY
            | GateKind::CZ
            | GateKind::SWAP
            | GateKind::CCX => {}
        }

        for (index, parameter) in gate.parameters().iter().enumerate() {
            match parameter {
                Parameter::Constant(value) if value.is_finite() => {}

                Parameter::Constant(_) => {
                    return Err(QirError::UnsupportedParameter {
                        gate: gate.kind(),
                        index,
                        reason: "QIR cannot contain non-finite LLVM floating-point constants",
                    });
                }

                Parameter::Symbol(_) => {
                    return Err(QirError::UnsupportedParameter {
                        gate: gate.kind(),
                        index,
                        reason: "symbolic parameters must be bound before QIR lowering",
                    });
                }

                Parameter::Expression(_) => {
                    return Err(QirError::UnsupportedParameter {
                        gate: gate.kind(),
                        index,
                        reason: "parameter expressions must be lowered to constants before QIR Base Profile export",
                    });
                }
            }
        }

        Ok(())
    }

    // -------------------------------------------------------------------------
    // Module generation
    // -------------------------------------------------------------------------

    fn write_module_header(
        &self,
        output: &mut BoundedOutput,
        circuit: &QuantumCircuit,
    ) -> Result<(), QirError> {
        output.line("; Zamani Quantum -> QIR v2.0")?;
        output.line("; Generated by zamani.quantum.hardware.adapters.qir")?;
        output.line("")?;

        output.line("source_filename = \"zamani.quantum.qir\"")?;
        output.line("")?;

        /*
         * QIR v2 uses opaque pointers. There is intentionally no `%Qubit =
         * type opaque` or `%Result = type opaque` declaration.
         */
        output.line(&format!(
            "; required_num_qubits = {}",
            circuit.num_qubits()
        ))?;

        output.line(&format!(
            "; required_num_results = {}",
            circuit
                .operations()
                .iter()
                .filter(|gate| gate.kind() == GateKind::Measure)
                .count()
        ))?;

        output.line("")?;

        Ok(())
    }

    fn write_declarations(
        &self,
        output: &mut BoundedOutput,
        declarations: &DeclarationSet,
    ) -> Result<(), QirError> {
        for declaration in declarations.qis.iter() {
            output.line(declaration)?;
        }

        if !declarations.qis.is_empty() {
            output.line("")?;
        }

        /*
         * Base Profile runtime declarations.
         *
         * `initialize` prepares the execution environment.
         *
         * `tuple_record_output` and `result_record_output` provide the output
         * recording boundary.
         */
        if self.options.emit_output_recording {
            output.line(
                "declare void @__quantum__rt__initialize(ptr)"
            )?;

            output.line(
                "declare void @__quantum__rt__tuple_record_output(i64, ptr)"
            )?;

            output.line(
                "declare void @__quantum__rt__result_record_output(ptr, ptr)"
            )?;

            output.line("")?;
        }

        Ok(())
    }

    fn write_entry_point(
        &self,
        output: &mut BoundedOutput,
        circuit: &QuantumCircuit,
    ) -> Result<(), QirError> {
        output.line(&format!(
            "define i64 @{}() #0 {{",
            self.options.entry_point
        ))?;

        output.line("entry:")?;

        output.line(
            "  call void @__quantum__rt__initialize(ptr null)"
        )?;

        output.line("  br label %body")?;
        output.line("")?;

        output.line("body:")?;

        /*
         * Base Profile permits a straight-line sequence of QIS calls in the
         * non-irreversible region followed by a measurement region.
         */
        let mut measurement_index = 0usize;

        for gate in circuit.operations() {
            if gate.kind() == GateKind::Measure {
                break;
            }

            self.write_gate_call(
                output,
                gate,
            )?;
        }

        output.line("  br label %measurements")?;
        output.line("")?;

        output.line("measurements:")?;

        for gate in circuit.operations() {
            if gate.kind() != GateKind::Measure {
                continue;
            }

            self.write_measurement_call(
                output,
                gate,
                measurement_index,
            )?;

            measurement_index = measurement_index
                .checked_add(1)
                .ok_or(QirError::InvalidCircuit {
                    reason: "measurement index overflow".to_owned(),
                })?;
        }

        output.line("  br label %output")?;
        output.line("")?;

        output.line("output:")?;

        if self.options.emit_output_recording {
            measurement_index = 0;

            for gate in circuit.operations() {
                if gate.kind() != GateKind::Measure {
                    continue;
                }

                self.write_result_output(
                    output,
                    gate,
                    measurement_index,
                )?;

                measurement_index = measurement_index
                    .checked_add(1)
                    .ok_or(QirError::InvalidCircuit {
                        reason: "measurement index overflow".to_owned(),
                    })?;
            }
        }

        output.line("  ret i64 0")?;
        output.line("}")?;
        output.line("")?;

        Ok(())
    }

    fn write_attributes(
        &self,
        output: &mut BoundedOutput,
        circuit: &QuantumCircuit,
    ) -> Result<(), QirError> {
        let measurement_count = circuit
            .operations()
            .iter()
            .filter(|gate| gate.kind() == GateKind::Measure)
            .count();

        output.line(&format!(
            "#0 = {{ \"entry_point\", \
             \"qir_profiles\"=\"{}\", \
             \"output_labeling_schema\"=\"{}\", \
             \"required_num_qubits\"=\"{}\", \
             \"required_num_results\"=\"{}\" }}",
            self.options.profile.as_str(),
            self.options.output_labeling_schema,
            circuit.num_qubits(),
            measurement_count,
        ))?;

        output.line(
            "#1 = { \"irreversible\" }"
        )?;

        output.line("")?;

        Ok(())
    }

    fn write_module_flags(
        &self,
        output: &mut BoundedOutput,
    ) -> Result<(), QirError> {
        /*
         * QIR v2 module flags.
         *
         * Dynamic resource management remains disabled because the Zamani
         * circuit supplied to this adapter has a statically known logical
         * namespace.
         */
        output.line(
            "!llvm.module.flags = !{!0, !1, !2, !3}"
        )?;

        output.line(
            "!0 = !{i32 1, !\"qir_major_version\", i32 2}"
        )?;

        output.line(
            "!1 = !{i32 7, !\"qir_minor_version\", i32 0}"
        )?;

        output.line(
            "!2 = !{i32 1, !\"dynamic_qubit_management\", i1 false}"
        )?;

        output.line(
            "!3 = !{i32 1, !\"dynamic_result_management\", i1 false}"
        )?;

        Ok(())
    }

    // -------------------------------------------------------------------------
    // Gate emission
    // -------------------------------------------------------------------------

    fn write_gate_call(
        &self,
        output: &mut BoundedOutput,
        gate: &Gate,
    ) -> Result<(), QirError> {
        let q = gate.qubits();

        match gate.kind() {
            GateKind::X => {
                output.line(&format!(
                    "  call void @__quantum__qis__x__body(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::Y => {
                output.line(&format!(
                    "  call void @__quantum__qis__y__body(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::Z => {
                output.line(&format!(
                    "  call void @__quantum__qis__z__body(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::H => {
                output.line(&format!(
                    "  call void @__quantum__qis__h__body(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::S => {
                output.line(&format!(
                    "  call void @__quantum__qis__s__body(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::Sdg => {
                output.line(&format!(
                    "  call void @__quantum__qis__s__adj(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::T => {
                output.line(&format!(
                    "  call void @__quantum__qis__t__body(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::Tdg => {
                output.line(&format!(
                    "  call void @__quantum__qis__t__adj(ptr {})",
                    qir_qubit(q[0].index())
                ))?;
            }

            GateKind::RX
            | GateKind::RY
            | GateKind::RZ => {
                let parameter = constant_parameter(
                    gate.kind(),
                    0,
                    gate.parameters(),
                )?;

                let function = match gate.kind() {
                    GateKind::RX => "__quantum__qis__rx__body",
                    GateKind::RY => "__quantum__qis__ry__body",
                    GateKind::RZ => "__quantum__qis__rz__body",
                    _ => unreachable!(),
                };

                output.line(&format!(
                    "  call void @{function}(double {}, ptr {})",
                    llvm_double(parameter),
                    qir_qubit(q[0].index()),
                ))?;
            }

            GateKind::CX => {
                output.line(&format!(
                    "  call void @__quantum__qis__cx__body(ptr {}, ptr {})",
                    qir_qubit(q[0].index()),
                    qir_qubit(q[1].index()),
                ))?;
            }

            GateKind::CY => {
                output.line(&format!(
                    "  call void @__quantum__qis__cy__body(ptr {}, ptr {})",
                    qir_qubit(q[0].index()),
                    qir_qubit(q[1].index()),
                ))?;
            }

            GateKind::CZ => {
                output.line(&format!(
                    "  call void @__quantum__qis__cz__body(ptr {}, ptr {})",
                    qir_qubit(q[0].index()),
                    qir_qubit(q[1].index()),
                ))?;
            }

            GateKind::SWAP => {
                output.line(&format!(
                    "  call void @__quantum__qis__swap__body(ptr {}, ptr {})",
                    qir_qubit(q[0].index()),
                    qir_qubit(q[1].index()),
                ))?;
            }

            GateKind::CCX => {
                output.line(&format!(
                    "  call void @__quantum__qis__ccx__body(ptr {}, ptr {}, ptr {})",
                    qir_qubit(q[0].index()),
                    qir_qubit(q[1].index()),
                    qir_qubit(q[2].index()),
                ))?;
            }

            /*
             * Measurement is emitted by the dedicated measurement routine so
             * that result numbering and `irreversible` semantics remain
             * centralized.
             */
            GateKind::Measure => {
                return Err(QirError::InvalidCircuit {
                    reason:
                        "measurement reached the unitary gate emission path"
                            .to_owned(),
                });
            }

            _ => {
                return Err(QirError::UnsupportedGate {
                    gate: gate.kind(),
                });
            }
        }

        Ok(())
    }

    fn write_measurement_call(
        &self,
        output: &mut BoundedOutput,
        gate: &Gate,
        measurement_index: usize,
    ) -> Result<(), QirError> {
        let measurement =
            gate.measurement().ok_or(
                QirError::UnsupportedMeasurement {
                    reason: "measurement payload is missing",
                },
            )?;

        output.line(&format!(
            "  call void @__quantum__qis__mz__body(ptr {}, ptr {}) #1",
            qir_qubit(measurement.qubit().index()),
            qir_result(measurement_index),
        ))?;

        Ok(())
    }

    fn write_result_output(
        &self,
        output: &mut BoundedOutput,
        gate: &Gate,
        measurement_index: usize,
    ) -> Result<(), QirError> {
        let measurement =
            gate.measurement().ok_or(
                QirError::UnsupportedMeasurement {
                    reason: "measurement payload is missing",
                },
            )?;

        /*
         * The label is generated entirely from the validated logical classical
         * bit index. No user-controlled string enters the LLVM global name or
         * contents.
         */
        let classical =
            measurement.classical_bit().index();

        output.line(&format!(
            "  call void @__quantum__rt__result_record_output(ptr {}, ptr @zamani_c{})",
            qir_result(measurement_index),
            classical,
        ))?;

        Ok(())
    }
}

