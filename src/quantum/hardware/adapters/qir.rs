/// Options controlling deterministic QIR generation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QirOptions {
    /// QIR version to emit.
    pub version: QirVersion,

    /// QIR profile.
    pub profile: QirProfile,

    /// LLVM/QIR entry-point identifier.
    pub entry_point: String,

    /// Output-labeling schema identifier.
    pub output_labeling_schema: String,

    /// Maximum generated artifact size in bytes.
    pub max_output_bytes: usize,

    /// Whether output-recording calls should be emitted.
    ///
    /// Production output should normally keep this enabled.
    pub emit_output_recording: bool,
}

impl Default for QirOptions {
    fn default() -> Self {
        Self {
            version: QirVersion::production(),
            profile: QirProfile::Base,
            entry_point: DEFAULT_ENTRY_POINT.to_owned(),
            output_labeling_schema:
                DEFAULT_OUTPUT_LABELING_SCHEMA.to_owned(),
            max_output_bytes: DEFAULT_MAX_OUTPUT_BYTES,
            emit_output_recording: true,
        }
    }
}

impl QirOptions {
    /// Returns the production configuration.
    pub fn production() -> Result<Self, QirError> {
        let options = Self::default();
        options.validate()?;
        Ok(options)
    }

    /// Validates all externally configurable options.
    pub fn validate(&self) -> Result<(), QirError> {
        if !self.version.is_supported() {
            return Err(QirError::UnsupportedVersion {
                requested: self.version,
            });
        }

        if self.max_output_bytes == 0 {
            return Err(QirError::InvalidConfiguration {
                field: "max_output_bytes",
                reason: "must be greater than zero",
            });
        }

        validate_llvm_identifier(
            &self.entry_point,
            MAX_ENTRY_POINT_LENGTH,
            "entry_point",
        )?;

        validate_ascii_identifier(
            &self.output_labeling_schema,
            MAX_OUTPUT_SCHEMA_LENGTH,
            "output_labeling_schema",
        )?;

        if self.profile != QirProfile::Base {
            return Err(QirError::UnsupportedProfile {
                profile: self.profile,
            });
        }

        Ok(())
    }
}

