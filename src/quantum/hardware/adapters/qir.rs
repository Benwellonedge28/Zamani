// Bounded output
// =============================================================================

/// Output buffer that enforces its limit before every append.
///
/// This is intentionally implemented independently of the final `String`
/// length check. A post-construction check would allow an attacker-controlled
/// circuit to allocate an oversized artifact before rejection.
struct BoundedOutput {
    buffer: String,
    maximum: usize,
}

impl BoundedOutput {
    fn new(maximum: usize) -> Self {
        Self {
            buffer: String::new(),
            maximum,
        }
    }

    fn line(&mut self, line: &str) -> Result<(), QirError> {
        let additional =
            line.len()
                .checked_add(1)
                .ok_or(QirError::OutputLimitExceeded {
                    attempted: usize::MAX,
                    maximum: self.maximum,
                })?;

        let attempted =
            self.buffer
                .len()
                .checked_add(additional)
                .ok_or(QirError::OutputLimitExceeded {
                    attempted: usize::MAX,
                    maximum: self.maximum,
                })?;

        if attempted > self.maximum {
            return Err(QirError::OutputLimitExceeded {
                attempted,
                maximum: self.maximum,
            });
        }

        self.buffer
            .write_str(line)
            .map_err(|_| QirError::Formatting)?;

        self.buffer
            .write_char('\n')
            .map_err(|_| QirError::Formatting)?;

        Ok(())
    }

    fn into_string(self) -> String {
        self.buffer
    }
}

