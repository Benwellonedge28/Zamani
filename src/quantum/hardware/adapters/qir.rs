/// Supported QIR specification version.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct QirVersion {
    major: u32,
    minor: u32,
}

impl QirVersion {
    /// Creates a QIR version.
    ///
    /// Only QIR 2.0 is currently emitted by this adapter.
    pub const fn new(major: u32, minor: u32) -> Self {
        Self { major, minor }
    }

    /// Returns the QIR major version.
    pub const fn major(self) -> u32 {
        self.major
    }

    /// Returns the QIR minor version.
    pub const fn minor(self) -> u32 {
        self.minor
    }

    /// Returns the production version.
    pub const fn production() -> Self {
        Self::new(QIR_MAJOR_VERSION, QIR_MINOR_VERSION)
    }

    /// Returns whether this is the production version supported by this file.
    pub const fn is_supported(self) -> bool {
        self.major == QIR_MAJOR_VERSION && self.minor == QIR_MINOR_VERSION
    }
}

impl Default for QirVersion {
    fn default() -> Self {
        Self::production()
    }
}

impl fmt::Display for QirVersion {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(formatter, "{}.{}", self.major, self.minor)
    }
}

