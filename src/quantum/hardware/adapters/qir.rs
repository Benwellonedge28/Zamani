/// Deterministic QIR artifact produced by [`QirExporter`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct QirArtifact {
    /// Generated LLVM/QIR text.
    text: String,

    /// QIR version.
    version: QirVersion,

    /// QIR profile.
    profile: QirProfile,

    /// Entry-point name.
    entry_point: String,

    /// Number of logical qubits required by the circuit.
    required_num_qubits: usize,

    /// Number of QIR measurement-result objects required.
    required_num_results: usize,
}

impl QirArtifact {
    /// Creates a QIR artifact.
    fn new(
        text: String,
        version: QirVersion,
        profile: QirProfile,
        entry_point: String,
        required_num_qubits: usize,
        required_num_results: usize,
    ) -> Self {
        Self {
            text,
            version,
            profile,
            entry_point,
            required_num_qubits,
            required_num_results,
        }
    }

    /// Returns the complete QIR text.
    pub fn text(&self) -> &str {
        &self.text
    }

    /// Consumes the artifact and returns its text.
    pub fn into_text(self) -> String {
        self.text
    }

    /// Returns the QIR version.
    pub const fn version(&self) -> QirVersion {
        self.version
    }

    /// Returns the selected profile.
    pub const fn profile(&self) -> QirProfile {
        self.profile
    }

    /// Returns the entry point.
    pub fn entry_point(&self) -> &str {
        &self.entry_point
    }

    /// Returns the required qubit count.
    pub const fn required_num_qubits(&self) -> usize {
        self.required_num_qubits
    }

    /// Returns the required QIR result count.
    pub const fn required_num_results(&self) -> usize {
        self.required_num_results
    }
}

