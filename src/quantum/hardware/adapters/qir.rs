/// Deterministic QIS declaration set.
#[derive(Debug, Default)]
struct DeclarationSet {
    qis: BTreeSet<String>,
}

fn collect_declarations(
    circuit: &QuantumCircuit,
) -> Result<DeclarationSet, QirError> {
    let mut declarations =
        DeclarationSet::default();

    for gate in circuit.operations() {
        let declaration =
            match gate.kind() {
                GateKind::X =>
                    "declare void @__quantum__qis__x__body(ptr)",
                GateKind::Y =>
                    "declare void @__quantum__qis__y__body(ptr)",
                GateKind::Z =>
                    "declare void @__quantum__qis__z__body(ptr)",
                GateKind::H =>
                    "declare void @__quantum__qis__h__body(ptr)",
                GateKind::S =>
                    "declare void @__quantum__qis__s__body(ptr)",
                GateKind::Sdg =>
                    "declare void @__quantum__qis__s__adj(ptr)",
                GateKind::T =>
                    "declare void @__quantum__qis__t__body(ptr)",
                GateKind::Tdg =>
                    "declare void @__quantum__qis__t__adj(ptr)",
                GateKind::RX =>
                    "declare void @__quantum__qis__rx__body(double, ptr)",
                GateKind::RY =>
                    "declare void @__quantum__qis__ry__body(double, ptr)",
                GateKind::RZ =>
                    "declare void @__quantum__qis__rz__body(double, ptr)",
                GateKind::CX =>
                    "declare void @__quantum__qis__cx__body(ptr, ptr)",
                GateKind::CY =>
                    "declare void @__quantum__qis__cy__body(ptr, ptr)",
                GateKind::CZ =>
                    "declare void @__quantum__qis__cz__body(ptr, ptr)",
                GateKind::SWAP =>
                    "declare void @__quantum__qis__swap__body(ptr, ptr)",
                GateKind::CCX =>
                    "declare void @__quantum__qis__ccx__body(ptr, ptr, ptr)",
                GateKind::Measure =>
                    "declare void @__quantum__qis__mz__body(ptr, ptr writeonly) #1",

                _ => continue,
            };

        declarations.qis.insert(
            declaration.to_owned()
        );
    }

    Ok(declarations)
}

