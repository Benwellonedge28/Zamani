//! - Event outcomes.
//! - Extensible provenance properties.
//! - Explicit causal parent relationships.
//! - Immutable provenance snapshots.
//! - Provenance merging for parallel compilation.
//!
//! # Ownership boundaries
//!
//! This module owns:
//!
//! - Provenance identifiers.
//! - Provenance event metadata.
//! - Provenance event validation.
//! - Provenance lineage relationships.
//! - Provenance ledger storage.
//! - Provenance snapshot creation.
//! - Provenance snapshot merging.
//!
//! This module does NOT own:
//!
//! - Source-language semantics.
//! - Semantic identity.
//! - Type information.
//! - Ownership or borrow analysis.
//! - Effects.
//! - Capability semantics.
//! - Resource requirements.
//! - Source parsing.
//! - AST construction.
//! - Source-map storage.
//! - Source spans.
//! - Source-content hashing.
//! - Incremental fingerprints.
//! - Incremental invalidation.
//! - Build-cache storage.
//! - Canonical IR.
//! - IR transformations.
//! - Optimization algorithms.
//! - Target discovery.
//! - Hardware allocation.
//! - Backend implementation.
//! - Artifact contents.
//! - Artifact serialization.
//! - Runtime execution.
//! - Distributed execution.
//!
//! # Existing integration authorities
//!
//! crate::compiler::context::compilation_context
//!     CompilationContext
//!     SourceIdentity
//!     CancellationToken
//!
//! crate::compiler::context::dependency_context
//!     DependencyContext
//!     CompilationUnitId
