//! # Purpose
//!
//! This module provides an append-only, thread-safe provenance ledger for
//! one compilation operation.
//!
//! It records:
//!
//! - Compilation identity.
//! - Source references.
//! - Compilation-unit references.
//! - Dependency-context association.
