/// Builder for a provenance context.
///
/// This builder associates existing repository authorities with the
/// provenance ledger without redefining their contracts.
#[derive(Debug)]
pub struct ProvenanceContextBuilder {
    compilation: CompilationProvenanceId,
    primary_source: Option<SourceIdentity>,
    dependencies: Option<DependencyContext>,
    cancellation: CancellationToken,
    state: Option<CompilationStateTracker>,
}

impl ProvenanceContextBuilder {
    /// Creates a builder.
    pub fn new(
        compilation: CompilationProvenanceId,
    ) -> Self {
        Self {
            compilation,
            primary_source: None,
            dependencies: None,
            cancellation: CancellationToken::new(),
            state: None,
        }
    }

    /// Supplies a primary source identity.
    #[must_use]
    pub fn source(
        mut self,
        source: SourceIdentity,
    ) -> Self {
        self.primary_source = Some(source);
        self
    }

    /// Supplies an optional primary source identity.
    #[must_use]
    pub fn optional_source(
        mut self,
        source: Option<SourceIdentity>,
    ) -> Self {
        self.primary_source = source;
        self
    }

    /// Associates the existing immutable dependency context.
    #[must_use]
    pub fn dependencies(
        mut self,
        dependencies: DependencyContext,
    ) -> Self {
        self.dependencies = Some(dependencies);
        self
    }

    /// Supplies the existing cancellation token.
    #[must_use]
    pub fn cancellation_token(
        mut self,
        cancellation: CancellationToken,
    ) -> Self {
        self.cancellation = cancellation;
        self
    }

    /// Associates the existing compilation-state tracker.
    #[must_use]
    pub fn state_tracker(
        mut self,
        state: CompilationStateTracker,
    ) -> Self {
        self.state = Some(state);
        self
    }

    /// Builds the provenance context.
    #[must_use]
    pub fn build(self) -> ProvenanceContext {
        ProvenanceContext {
            inner: Arc::new(ProvenanceContextInner {
                compilation: self.compilation,
                primary_source: self.primary_source,
                dependencies: self.dependencies,
                cancellation: self.cancellation,
                state: self.state,
                ledger: RwLock::new(
                    ProvenanceLedgerData::default(),
                ),
            }),
        }
    }
}

