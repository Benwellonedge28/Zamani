/// Describes the determinism guarantee declared by a provenance event.
///
/// This is a recorded contract, not a proof.
///
/// Actual reproducibility verification belongs to the deterministic-build,
/// reproducibility, and artifact-verification subsystems.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum ProvenanceDeterminism {
    /// The event is declared deterministic.
    Deterministic,

    /// The event is deterministic when its declared inputs and
    /// configuration are unchanged.
    DeterministicGivenInputs,

    /// The event may produce different results across executions.
    Nondeterministic,

    /// No determinism guarantee was supplied.
    Unspecified,

    /// An extension-defined determinism contract.
    Custom(Arc<str>),
}

impl ProvenanceDeterminism {
    /// Creates an extension-defined determinism contract.
    pub fn custom(
        identifier: impl Into<Arc<str>>,
    ) -> Result<Self, ProvenanceError> {
        let identifier = identifier.into();

        validate_identifier(
            &identifier,
            "determinism contract",
        )?;

        Ok(Self::Custom(identifier))
    }
}

