//!     Dirty propagation.
//!
//! crate::compiler::diagnostics
//!     Structured diagnostics.
//!
//! Existing semantic, IR, optimizer, backend and artifact subsystems
//!     Remain authoritative for their respective responsibilities.
//!
//! # POCO-REAF
//!
//! Provenance is independent of:
//!
//! - CPU architecture.
//! - GPU architecture.
//! - FPGA family.
//! - ASIC design.
//! - Quantum processor.
//! - Neuromorphic processor.
//! - Photonic processor.
//! - Distributed topology.
//! - Machine size.
//! - Device count.
//! - Memory capacity.
//! - Storage capacity.
//!
//! No universal hardware or provenance-event ceiling is imposed.
//!
//! Practical storage and execution limits remain subject to available
//! resources and explicitly configured operational budgets.
//!
//! # Determinism
//!
//! Provenance events use caller-supplied stable identifiers.
//!
//! Snapshots expose events in deterministic identifier order.
//!
//! No wall-clock timestamp, random identifier, host address, or implicit
//! machine identity is generated by this module.
//!
//! The ledger revision represents accepted mutation order. It is not a
//! cross-run deterministic identifier for parallel event execution.
//!
//! # Parallel compilation
//!
//! Independent compilation branches may produce separate snapshots.
//!
//! Those snapshots can be merged when their causal parent references are
//! available.
//!
//! Conflicting event identifiers and conflicting artifact producers are
//! rejected.
//!
//! # Source locations
//!
//! Source locations are represented by opaque source-map references.
//!
//! This module does not define byte positions, spans, line numbers, or
//! source-file storage.
//!
//! An adapter must supply identifiers from the canonical source-map
//! implementation.
//!
//! # Digests
//!
//! Digests are opaque externally supplied values.
//!
//! This module does not implement hashing or cryptographic verification.
//!
//! Incremental compilation remains responsible for its fingerprints.
//! Security and artifact-verification subsystems remain responsible for
//! cryptographic integrity and authenticity.

