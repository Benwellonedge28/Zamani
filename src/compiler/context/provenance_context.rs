#[derive(Debug)]
struct ProvenanceContextInner {
    compilation: CompilationProvenanceId,

    primary_source: Option<SourceIdentity>,

    dependencies: Option<DependencyContext>,

    cancellation: CancellationToken,

    state: Option<CompilationStateTracker>,

    ledger: RwLock<ProvenanceLedgerData>,
}

/// Thread-safe provenance context for one compilation operation.
///
/// Cloning the context shares:
///
/// - Compilation identity.
/// - Primary source identity.
/// - Dependency snapshot.
/// - Cancellation token.
/// - Compilation-state tracker.
/// - Provenance ledger.
///
/// The ledger is append-only through its public API.
///
/// The context does not own source semantics, artifact contents,
/// incremental fingerprints, or compiler transformations.
#[derive(Debug, Clone)]
pub struct ProvenanceContext {
    inner: Arc<ProvenanceContextInner>,
}

impl ProvenanceContext {
    /// Creates an independent provenance context.
    ///
    /// No source, dependency graph, or compilation-state tracker is
    /// assumed.
    pub fn new(
        compilation: CompilationProvenanceId,
    ) -> Self {
        ProvenanceContextBuilder::new(compilation)
            .build()
    }

    /// Creates a provenance context from an existing CompilationContext.
    ///
    /// The source identity and cancellation token are shared logically
    /// with the existing compilation operation.
    ///
    /// A state tracker is constructed using the same cancellation token.
    pub fn from_compilation(
        compilation: CompilationProvenanceId,
        context: &CompilationContext,
    ) -> Self {
        ProvenanceContextBuilder::new(compilation)
            .optional_source(context.source().cloned())
            .cancellation_token(context.cancellation_token())
            .state_tracker(
                CompilationStateTracker::with_cancellation(
                    context.cancellation_token(),
                ),
            )
            .build()
    }

    /// Returns a builder for advanced integration.
    #[must_use]
    pub fn builder(
        compilation: CompilationProvenanceId,
    ) -> ProvenanceContextBuilder {
        ProvenanceContextBuilder::new(compilation)
    }

    /// Returns the compilation identity.
    #[must_use]
    pub fn compilation(&self) -> &CompilationProvenanceId {
        &self.inner.compilation
    }

    /// Returns the primary source identity, if supplied.
    #[must_use]
    pub fn primary_source(&self) -> Option<&SourceIdentity> {
        self.inner.primary_source.as_ref()
    }

    /// Returns the immutable dependency snapshot, if supplied.
    #[must_use]
    pub fn dependencies(&self) -> Option<&DependencyContext> {
        self.inner.dependencies.as_ref()
    }

    /// Returns whether the associated compilation has been cancelled.
    #[must_use]
    pub fn is_cancelled(&self) -> bool {
        self.inner.cancellation.is_cancelled()
    }

    /// Returns the shared cancellation token.
    #[must_use]
    pub fn cancellation_token(&self) -> CancellationToken {
        self.inner.cancellation.clone()
    }

    /// Returns the associated state tracker, if supplied.
    #[must_use]
    pub fn state_tracker(&self) -> Option<&CompilationStateTracker> {
        self.inner.state.as_ref()
    }

    /// Records one provenance event.
    ///
    /// If a compilation-state tracker is associated, the current phase and
    /// stage are captured when the event does not already contain them.
    ///
    /// The primary source is automatically attached when the event has no
    /// explicit source references.
    ///
    /// Cancellation does not prevent provenance recording. This is
    /// intentional: cancellation and failure events must remain recordable.
    ///
    /// The returned revision is local to this ledger.
    pub fn record(
        &self,
        mut event: ProvenanceEvent,
    ) -> Result<u64, ProvenanceError> {
        if event.sources.is_empty() {
            if let Some(source) = &self.inner.primary_source {
                if let Ok(reference) =
                    ProvenanceSourceReference::new(
                        Arc::<str>::from(source.logical_name()),
                    )
                {
                    event.sources.insert(reference);
                }
            }
        }

        if let Some(state_tracker) = &self.inner.state {
            let snapshot = state_tracker
                .snapshot()
                .map_err(|error| {
                    ProvenanceError::StateUnavailable {
                        message: Arc::from(error.to_string()),
                    }
                })?;

            if event.compilation_phase.is_none() {
                event.compilation_phase = snapshot.phase;
            }

            if event.compilation_stage.is_none() {
                event.compilation_stage = snapshot.stage_name;
            }
        }

        let mut ledger = self
            .inner
            .ledger
            .write()
            .map_err(|_| {
                ProvenanceError::SynchronizationPoisoned
            })?;

        ledger.insert(event)
    }

    /// Returns an immutable snapshot of the current provenance ledger.
    pub fn snapshot(
        &self,
    ) -> Result<ProvenanceSnapshot, ProvenanceError> {
        let ledger = self
            .inner
            .ledger
            .read()
            .map_err(|_| {
                ProvenanceError::SynchronizationPoisoned
            })?;

        Ok(ProvenanceSnapshot {
            compilation: self.inner.compilation.clone(),
            events: Arc::new(ledger.events.clone()),
            artifact_producers: Arc::new(
                ledger.artifact_producers.clone(),
            ),
            revision: ledger.revision,
        })
    }

    /// Returns the number of recorded events.
    pub fn event_count(&self) -> Result<usize, ProvenanceError> {
        let ledger = self
            .inner
            .ledger
            .read()
            .map_err(|_| {
                ProvenanceError::SynchronizationPoisoned
            })?;

        Ok(ledger.events.len())
    }

    /// Merges another immutable snapshot into this ledger.
    ///
    /// Merge behavior:
    ///
    /// - Compilation identities must match.
    /// - Identical event IDs with identical contents are idempotently
    ///   ignored.
    /// - Identical event IDs with different contents are rejected.
    /// - Parent events must be present before dependent events are inserted.
    /// - Events are selected in deterministic identifier order whenever
    ///   multiple events are ready.
    /// - Duplicate artifact producers are rejected.
    ///
    /// The merge is atomic with respect to other ledger writers.
    ///
    /// On failure, no partially merged snapshot is published.
    pub fn merge(
        &self,
        snapshot: &ProvenanceSnapshot,
    ) -> Result<u64, ProvenanceError> {
        if self.inner.compilation != snapshot.compilation {
            return Err(
                ProvenanceError::CompilationIdentityMismatch {
                    expected: self.inner.compilation.clone(),
                    actual: snapshot.compilation.clone(),
                },
            );
        }

        let mut ledger = self
            .inner
            .ledger
            .write()
            .map_err(|_| {
                ProvenanceError::SynchronizationPoisoned
            })?;

        // Work against a private candidate so that a failed merge cannot
        // leave the live ledger partially updated.
        let mut candidate = ProvenanceLedgerData {
            events: ledger.events.clone(),
            artifact_producers: ledger.artifact_producers.clone(),
            revision: ledger.revision,
        };

        let mut pending = BTreeMap::new();

        for (identifier, event) in snapshot.events.iter() {
            if let Some(existing) = candidate.events.get(identifier) {
                if existing != event {
                    return Err(
                        ProvenanceError::DuplicateEvent {
                            event: identifier.clone(),
                        },
                    );
                }
            } else {
                pending.insert(identifier.clone(), event.clone());
            }
        }

        while !pending.is_empty() {
            let ready: Vec<ProvenanceEventId> = pending
                .iter()
                .filter_map(|(identifier, event)| {
                    let parents_available = event.parents.iter().all(
                        |parent| candidate.events.contains_key(parent),
                    );

                    parents_available.then(|| identifier.clone())
                })
                .collect();

            if ready.is_empty() {
                return Err(
                    ProvenanceError::UnresolvedParents {
                        events: pending.keys().cloned().collect(),
                    },
                );
            }

            for identifier in ready {
                if let Some(event) = pending.remove(&identifier) {
                    candidate.insert(event)?;
                }
            }
        }

        *ledger = candidate;

        Ok(ledger.revision)
    }

    /// Returns the number of references to the shared context.
    ///
    /// This is an observability method only.
    #[must_use]
    pub fn reference_count(&self) -> usize {
        Arc::strong_count(&self.inner)
    }
}

