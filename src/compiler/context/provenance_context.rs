/// Errors produced by provenance construction, recording, or merging.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum ProvenanceError {
    EmptyIdentifier {
        description: &'static str,
    },

    InvalidIdentifier {
        description: &'static str,
    },

    DuplicateEvent {
        event: ProvenanceEventId,
    },

    UnknownParent {
        event: ProvenanceEventId,
        parent: ProvenanceEventId,
    },

    SelfParent {
        event: ProvenanceEventId,
    },

    DuplicateArtifactProducer {
        artifact: Arc<str>,
        existing_event: ProvenanceEventId,
        attempted_event: ProvenanceEventId,
    },

    UnresolvedParents {
        events: Vec<ProvenanceEventId>,
    },

    RevisionExhausted,

    SynchronizationPoisoned,

    StateUnavailable {
        message: Arc<str>,
    },

    CompilationIdentityMismatch {
        expected: CompilationProvenanceId,
        actual: CompilationProvenanceId,
    },
}

impl fmt::Display for ProvenanceError {
    fn fmt(
        &self,
        formatter: &mut fmt::Formatter<'_>,
    ) -> fmt::Result {
        match self {
            Self::EmptyIdentifier { description } => {
                write!(
                    formatter,
                    "{description} cannot be empty"
                )
            }

            Self::InvalidIdentifier { description } => {
                write!(
                    formatter,
                    "{description} contains control characters"
                )
            }

            Self::DuplicateEvent { event } => {
                write!(
                    formatter,
                    "duplicate provenance event: {event}"
                )
            }

            Self::UnknownParent { event, parent } => {
                write!(
                    formatter,
                    "provenance event '{event}' references unknown parent '{parent}'"
                )
            }

            Self::SelfParent { event } => {
                write!(
                    formatter,
                    "provenance event '{event}' cannot be its own parent"
                )
            }

            Self::DuplicateArtifactProducer {
                artifact,
                existing_event,
                attempted_event,
            } => {
                write!(
                    formatter,
                    "artifact '{artifact}' already has producer '{existing_event}'; \
                     conflicting producer '{attempted_event}'"
                )
            }

            Self::UnresolvedParents { events } => {
                write!(
                    formatter,
                    "provenance merge contains unresolved parent relationships: "
                )?;

                for (index, event) in events.iter().enumerate() {
                    if index > 0 {
                        formatter.write_str(", ")?;
                    }

                    write!(formatter, "{event}")?;
                }

                Ok(())
            }

            Self::RevisionExhausted => {
                formatter.write_str(
                    "provenance ledger revision counter exhausted",
                )
            }

            Self::SynchronizationPoisoned => {
                formatter.write_str(
                    "provenance ledger synchronization is poisoned",
                )
            }

            Self::StateUnavailable { message } => {
                write!(
                    formatter,
                    "compilation state snapshot unavailable: {message}"
                )
            }

            Self::CompilationIdentityMismatch {
                expected,
                actual,
            } => {
                write!(
                    formatter,
                    "cannot merge provenance for compilation '{actual}' \
                     into compilation '{expected}'"
                )
            }
        }
    }
}

impl Error for ProvenanceError {}

