/// Stable identity of one compilation operation.
///
/// The identifier is supplied by the caller.
///
/// This module does not generate random or time-dependent identities.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct CompilationProvenanceId(Arc<str>);

impl CompilationProvenanceId {
    /// Creates a compilation provenance identifier.
    pub fn new(
        value: impl Into<Arc<str>>,
    ) -> Result<Self, ProvenanceError> {
        let value = value.into();

        validate_identifier(
            &value,
            "compilation provenance identifier",
        )?;

        Ok(Self(value))
    }

    /// Returns the identifier.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for CompilationProvenanceId {
    fn fmt(
        &self,
        formatter: &mut fmt::Formatter<'_>,
    ) -> fmt::Result {
        formatter.write_str(&self.0)
    }
}

