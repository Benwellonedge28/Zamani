#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn representation_kind_is_stable() {
        assert_eq!(
            IrRepresentationKind::Zuir,
            IrRepresentationKind::Zuir
        );
    }

    #[test]
    fn api_version_is_available() {
        assert_eq!(IR_INPUT_API_VERSION, 1);
    }

    #[test]
    fn error_preserves_verification_report() {
        let report = FullVerificationReport::default();

        let error = IrInputError::InvalidIr {
            report: report.clone(),
        };

        assert_eq!(
            error.report().status(),
            VerificationStatus::Valid
        );
    }
}
