/// backend ABI version.
pub const IR_INPUT_API_VERSION: u16 = 1;

// =============================================================================
// IR REPRESENTATION KIND
// =============================================================================

/// Identifies the canonical representation accepted by this
/// input boundary.
///
/// The representation identifier is descriptive. It does not
/// create or own the underlying IR.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum IrRepresentationKind {
    /// Zamani Universal Intermediate Representation.
    Zuir,
}

// =============================================================================
// INPUT ERROR
// =============================================================================

/// Errors produced when constructing or validating compiler IR input.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IrInputError {
    /// The canonical verifier found invalid IR.
    InvalidIr {
        /// Complete verification findings.
        report: FullVerificationReport,
    },

    /// Verification could not establish all required properties.
    IncompleteVerification {
        /// Complete verification findings.
        report: FullVerificationReport,
    },
}

impl IrInputError {
    /// Returns the verification report associated with this error.
    #[must_use]
    pub fn report(&self) -> &FullVerificationReport {
        match self {
            Self::InvalidIr { report }
            | Self::IncompleteVerification { report } => report,
        }
    }

    /// Returns the representation kind associated with this error.
    #[must_use]
    pub const fn representation(&self) -> IrRepresentationKind {
        IrRepresentationKind::Zuir
    }
}

impl fmt::Display for IrInputError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidIr { report } => {
                write!(
                    formatter,
                    "ZUIR verification failed: {} verification errors",
                    report.count(crate::zuir::verify::VerificationSeverity::Error)
                )
            }

            Self::IncompleteVerification { report } => {
                write!(
                    formatter,
                    "ZUIR verification incomplete: {} deferred findings",
                    report.count(
                        crate::zuir::verify::VerificationSeverity::Deferred
                    )
                )
            }
        }
    }
}

impl std::error::Error for IrInputError {}

// =============================================================================
// COMPILATION IR INPUT
// =============================================================================

/// An immutable compiler-facing description of canonical ZUIR input.
///
/// This structure borrows the complete verification snapshot.
///
/// It does not copy, reconstruct, mutate or reinterpret the IR.
///
/// The caller must ensure that all components supplied through
/// FullVerificationInput belong to the same consistent IR snapshot.
///
/// The canonical verifier remains responsible for validating the
/// relationships between these components.
pub struct CompilationIrInput<'a> {
    representation: IrRepresentation<'a>,
}

/// Canonical IR representation supplied to the compiler.
enum IrRepresentation<'a> {
    Zuir(&'a FullVerificationInput<'a>),
}

impl<'a> CompilationIrInput<'a> {
    /// Constructs a compiler input from canonical ZUIR.
    ///
    /// Construction itself does not establish verification.
    ///
    /// Use verify() to obtain a VerifiedIrInput.
    #[must_use]
    pub fn from_zuir(input: &'a FullVerificationInput<'a>) -> Self {
        Self {
            representation: IrRepresentation::Zuir(input),
        }
    }

    /// Returns the representation kind.
    #[must_use]
    pub const fn representation_kind(&self) -> IrRepresentationKind {
        match self.representation {
            IrRepresentation::Zuir(_) => IrRepresentationKind::Zuir,
        }
    }

    /// Runs canonical full-program verification.
    ///
    /// Returns VerifiedIrInput only when the canonical verifier
    /// reports VerificationStatus::Valid.
    ///
    /// Invalid and incomplete reports are preserved in the returned
    /// error.
    ///
    /// No fallback or partial-success conversion is performed.
    pub fn verify(self) -> Result<VerifiedIrInput<'a>, IrInputError> {
        match self.representation {
            IrRepresentation::Zuir(input) => {
                let report = verify_full(input);

                match report.status() {
                    VerificationStatus::Valid => {
                        Ok(VerifiedIrInput {
                            input,
                            report,
                        })
                    }

                    VerificationStatus::Invalid => {
                        Err(IrInputError::InvalidIr {
                            report,
                        })
                    }

                    VerificationStatus::Incomplete => {
                        Err(IrInputError::IncompleteVerification {
                            report,
                        })
                    }
                }
            }
        }
    }
}

// =============================================================================
// VERIFIED IR INPUT
// =============================================================================

/// Immutable ZUIR input that passed the currently integrated
/// canonical full-program verifier.
///
/// This type can only be constructed through the verification
/// gate in this module.
///
/// It preserves the original IR snapshot and the verification
/// report that justified admission.
///
/// IMPORTANT:
///
/// VerificationStatus::Valid means that all currently integrated
/// checks in the canonical full ZUIR verifier passed.
///
/// It does not imply that every possible future verification
/// property, backend compatibility property or hardware feasibility
/// property has been established.
///
/// Consumers must perform additional checks when their stage
/// requires properties outside the existing verifier's coverage.
pub struct VerifiedIrInput<'a> {
    input: &'a FullVerificationInput<'a>,
    report: FullVerificationReport,
}

impl<'a> VerifiedIrInput<'a> {
    /// Returns the representation kind.
    #[must_use]
    pub const fn representation_kind(&self) -> IrRepresentationKind {
        IrRepresentationKind::Zuir
    }

    /// Returns the original canonical ZUIR program.
    ///
    /// The returned reference is immutable and has the lifetime
    /// of the original verification snapshot.
    #[must_use]
    pub fn program(
        &self,
    ) -> &'a ZuirProgram<ZuirModule<ZuirFunction>> {
        self.input.program
    }

    /// Returns the original complete verification input.
    ///
    /// This gives downstream verification-aware compiler stages
    /// access to the same snapshot that was verified.
    ///
    /// No reconstruction or cloning occurs.
    #[must_use]
    pub fn verification_input(&self) -> &'a FullVerificationInput<'a> {
        self.input
    }

    /// Returns the verification report.
    ///
    /// The report is retained so downstream stages can inspect
    /// the exact findings and completed verification stages.
    #[must_use]
    pub fn verification_report(&self) -> &FullVerificationReport {
        &self.report
    }

    /// Returns the verified status.
    ///
    /// This is always true for a successfully constructed instance.
    #[must_use]
    pub fn is_verified(&self) -> bool {
        self.report.status() == VerificationStatus::Valid
    }

    /// Returns the number of verification findings.
    #[must_use]
    pub fn finding_count(&self) -> usize {
        self.report.issues().len()
    }

    /// Returns the verification API version.
    #[must_use]
    pub const fn api_version(&self) -> u16 {
        IR_INPUT_API_VERSION
    }
}

